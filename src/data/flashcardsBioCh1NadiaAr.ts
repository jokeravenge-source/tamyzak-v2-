const toSourceMinisterialWording = (question: string): string => {
  const cleaned = question
    .replace(" بحسب الملف", "")
    .replace(" في قسم أسئلة الملف", "")
    .replace(" تحديداً", "")
    .trim();

  if (cleaned.startsWith("لماذا ")) {
    return `علل: ${cleaned.slice("لماذا ".length)}`;
  }

  if (cleaned.startsWith("ما المصطلح العلمي ل")) {
    const statement = cleaned.slice("ما المصطلح العلمي ل".length).replace(/؟$/, "").trim();
    return `ما المصطلح العلمي الذي يدل على: ${statement}؟`;
  }

  if (cleaned.startsWith("في أي طور ")) {
    return `في أي طور يحدث ما يأتي: ${cleaned.slice("في أي طور ".length)}`;
  }

  if (cleaned.startsWith("في أي مرحلة ")) {
    return `في أي دور يحدث ما يأتي: ${cleaned.slice("في أي مرحلة ".length)}`;
  }

  return cleaned;
};

