const recitationLetters = [
  ["الإظهار الحلقي", ["ء", "هـ", "ع", "ح", "غ", "خ"]],
  ["الإدغام بغنة", ["ي", "ن", "م", "و"]],
  ["الإدغام بغير غنة", ["ل", "ر"]],
  ["الإقلاب", ["ب"]],
  ["الإخفاء الحقيقي", ["ت", "ث", "ج", "د", "ذ", "ز", "س", "ش", "ص", "ض", "ط", "ظ", "ف", "ق", "ك"]],
] as const;

export function quickStudyArabicPractice(subject: string, chapter: string): PracticeItem[] {
  if (subject === "islamic") {
    if (chapter === "recitation") {
      const rules = recitationLetters.map(([rule]) => rule);
      return recitationLetters.flatMap(([rule, letters]) => letters.map(letter =>
        choose(`نون ساكنة في آخر كلمة يليها حرف «${letter}» في بداية الكلمة التالية. ما الحكم؟`, rule, rules)));
    }
    return matchingPairs(islamicFacts[chapter] ?? [],
      definition => `أي مصطلح أو مثال يقابل هذا الوصف؟ ${definition}`,
      term => `أي عبارة تناسب «${term}» في هذا الدرس؟`);
  }

  switch (chapter) {
    case "ar-nafy":
      return negationVerbs.flatMap(([base, jussive, subjunctive]) => [
        choose(`اختر الضبط بعد «لم» لنفي الفعل «${base}» في الماضي.`, jussive, [jussive, subjunctive, base]),
        choose(`اختر الضبط بعد «لن» لنفي الفعل «${base}» في المستقبل.`, subjunctive, [jussive, subjunctive, base]),
        choose(`انفِ وقوع الفعل «${base}» في الحال باستعمال «لا» النافية.`,
          `لا ${base}`, [`لا ${base}`, `لم ${jussive}`, `لن ${subjunctive}`]),
      ]);
    case "ar-ardh":
      return invitationVerbs.flatMap(sentence => [
        choose(`أكمل بأداة للعرض برفق: «___ ${sentence}؟»`, "ألا", ["ألا", "هلّا", "ليت", "لن"]),
        choose(`أكمل بأداة للتحضيض: «___ ${sentence}؟»`, "هلّا", ["ألا", "هلّا", "ليت", "لن"]),
        choose(`قال المتحدّث برفق: «ألا ${sentence}؟». ما نوع الطلب؟`,
          "عرض", ["عرض", "تحضيض", "تمنٍّ", "نفي"]),
      ]);
    case "ar-tahdir":
      return warningWords.flatMap(([harm, virtue]) => [
        choose(`ما الأسلوب في «إيّاكَ و${harm}»؟`, "تحذير", ["تحذير", "إغراء", "نداء", "تعجّب"]),
        choose(`ما الأسلوب في «${virtue} ${virtue}» عند الحثّ على هذه الصفة؟`, "إغراء", ["تحذير", "إغراء", "نداء", "تعجّب"]),
        choose(`عيّن المحذّر منه في «إيّاكَ و${harm}».`, harm, [harm, virtue, "إيّاكَ", "الواو"]),
      ]);
    case "ar-tamanni":
      return wishExamples.flatMap(([sentence, name, verb]) => [
        choose(`حدّد اسم ليت في «${sentence}».`, name, [name, verb, "ليت"]),
        choose(`حدّد خبر ليت في «${sentence}».`, `الجملة الفعلية «${verb}»`,
          [`الجملة الفعلية «${verb}»`, name, "ليت", "لا يوجد خبر"]),
        choose(`ما الأسلوب في «${sentence}»؟`, "تمنٍّ", ["تمنٍّ", "نداء", "نفي", "استفهام"]),
      ]);
    case "ar-adab": return matchingPairs(literaryTopics,
      description => `أي أديب يطابق هذا الوصف؟ ${description}`,
      author => `أي وصف يناسب «${author}»؟`);
    case "ar-nusos": return matchingPairs(memorizationTexts,
      description => `أي نص يطابق هذا الوصف؟ ${description}`,
      title => `أي وصف يطابق النص «${title}»؟`);
    default: return [];
  }
}
