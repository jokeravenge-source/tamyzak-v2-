import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import McqBank from "@/pages/McqBank";
import { getFahrastTopicGroups } from "@/lib/mcqFahrastTopics";

const mocks = vi.hoisted(() => ({ rows: [] as { id: string; subject: string; chapter: number; chapter_title: string | null; question: string; choices: string[]; answer_index: number; explanation: null; section?: string; tags?: string[] }[], rpc: vi.fn() }));
vi.mock("@/integrations/supabase/client", () => ({ supabase: {
  from: () => {
    const chain = { select: () => chain, eq: () => chain, order: () => chain, limit: async () => ({ data: mocks.rows }) };
    return chain;
  }, rpc: mocks.rpc,
} }));
vi.mock("@/lib/physicsChapter2Mcqs", () => ({ getBuiltInPhysicsCh2: () => [] }));
vi.mock("@/lib/englishLiteratureSection1Mcqs", () => ({ getBuiltInEnglishLiteratureSection1: () => [] }));
vi.mock("@/lib/englishLiteratureSection2Mcqs", () => ({ getBuiltInEnglishLiteratureSection2: () => [] }));
vi.mock("@/lib/englishLiteratureSection3Mcqs", () => ({ getBuiltInEnglishLiteratureSection3: () => [] }));
vi.mock("canvas-confetti", () => ({ default: vi.fn() }));
vi.mock("@/lib/points", () => ({ awardPoints: vi.fn(), showAward: vi.fn() }));
vi.mock("@/lib/mistakes", () => ({ recordMistake: vi.fn() }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
beforeEach(() => {
  sessionStorage.clear();
  mocks.rpc.mockReset().mockResolvedValue({ data: [], error: null });
  mocks.rows = [];
  vi.spyOn(window, "scrollTo").mockImplementation(() => {});
});
function row(subject: string, chapter: number, chapter_title: string | null) {
  return { id: `${subject}-${chapter}`, subject, chapter, chapter_title, question: `Question for ${subject} ${chapter}`, choices: ["A", "B", "C", "D"], answer_index: 0, explanation: null };
}

describe("MCQ bank flashcard divisions", () => {
  it("opens all supplied Biology Chapter 2 questions from the built-in bank", async () => {
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Biology/ }));
    fireEvent.click(screen.getByRole("button", { name: /Tissues/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question 1 of 50")).toBeInTheDocument();
    expect(screen.getByText("The science concerned with the study of tissues is called:")).toBeInTheDocument();
  });
  it("opens all 45 supplied Alternating Current questions under English Physics", async () => {
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    fireEvent.click(screen.getByRole("button", { name: /Alternating Current/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question 1 of 45")).toBeInTheDocument();
    expect(screen.getByText("Direct current (DC) is the current that:")).toBeInTheDocument();
    expect(screen.getByText("Flows in one direction and is generated by batteries")).toBeInTheDocument();
  });
  it("opens the 57 supplied Arabic Alternating Current questions", async () => {
    render(<McqBank language="ar" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /الفيزياء/ }));
    fireEvent.click(screen.getByRole("button", { name: /التيار المتناوب/ }));
    fireEvent.click(screen.getByRole("button", { name: /^كل أسئلة الفصل/ }));
    expect(screen.getByText("السؤال 1 من 57")).toBeInTheDocument();
    expect(screen.getByText("ترسل القدرة الكهربائية بفولطية عالية وتيار واطئ لغرض:")).toBeInTheDocument();
    expect(screen.getByText("تقليل خسائر القدرة الحرارية في الأسلاك الناقلة")).toBeInTheDocument();
  });
  it("opens all 77 supplied Electromagnetic Waves questions under English Physics", async () => {
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    fireEvent.click(screen.getByRole("button", { name: /Electromagnetic Waves/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question 1 of 77")).toBeInTheDocument();
    expect(screen.getByText("A static point charge generates:")).toBeInTheDocument();
    expect(screen.getByText("an electric field only")).toBeInTheDocument();
  });
  it("opens all 70 supplied Arabic Physical Optics questions", async () => {
    render(<McqBank language="ar" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /الفيزياء/ }));
    fireEvent.click(screen.getByRole("button", { name: /البصريات الفيزيائية/ }));
    fireEvent.click(screen.getByRole("button", { name: /^كل أسئلة الفصل/ }));
    expect(screen.getByText("السؤال 1 من 70")).toBeInTheDocument();
    expect(screen.getByText("في التداخل البناء تكون سعة الموجة الناتجة:")).toBeInTheDocument();
    expect(screen.getByText("مساوية لضعف سعة أي من الموجتين الأصليتين")).toBeInTheDocument();
  });
  it("opens all 61 supplied Physical Optics questions under English Physics", async () => {
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    fireEvent.click(screen.getByRole("button", { name: /Physical Optics/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question 1 of 61")).toBeInTheDocument();
    expect(screen.getByText("When two waves of equal amplitude meet in phase, the resulting amplitude is:")).toBeInTheDocument();
    expect(screen.getByText("Twice the amplitude of one wave")).toBeInTheDocument();
  });
  it("opens the subject selected in Subjects instead of asking for it twice", async () => {
    mocks.rows = [row("physics", 1, "Capacitors")];
    sessionStorage.setItem("mcq_subject_focus_v1", "physics");
    const onBack = vi.fn();
    render(<McqBank language="en" onBack={onBack} />);
    expect(await screen.findByRole("button", { name: /Capacitors/ })).toBeInTheDocument();
    expect(sessionStorage.getItem("mcq_subject_focus_v1")).toBeNull();
    fireEvent.click(screen.getByRole("button", { name: /Back/ }));
    expect(onBack).toHaveBeenCalledOnce();
  });
  it("shows matching chapter titles, disables empty chapters, and opens only that chapter", async () => {
    mocks.rows = [row("physics", 1, "Capacitors"), row("physics", 2, "Electromagnetic Induction")];
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    expect(screen.getByRole("button", { name: /Modern Physics/ })).toBeDisabled();
    fireEvent.click(screen.getByRole("button", { name: /Capacitors/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByRole("heading", { name: "Physics · Capacitors" })).toBeInTheDocument();
    expect(screen.getByText("Question for physics 1")).toBeInTheDocument();
    expect(screen.queryByText("Question for physics 2")).not.toBeInTheDocument();
  });
  it("keeps unclassified bank questions accessible without assigning a guessed chapter", async () => {
    mocks.rows = [row("physics", 99, "Unknown")];
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    fireEvent.click(screen.getByRole("button", { name: /Unclassified/ }));
    expect(screen.getByText("Question for physics 99")).toBeInTheDocument();
  });
  it("uses Arabic titles and retains the existing Arabic MCQ access lock", async () => {
    mocks.rows = [row("physics", 1, "Capacitors"), row("arabic", 2, "Istifham")];
    render(<McqBank language="ar" onBack={vi.fn()} />);
    expect(await screen.findByRole("button", { name: "العربية — مغلق" })).toBeDisabled();
    fireEvent.click(screen.getByRole("button", { name: /الفيزياء/ }));
    expect(screen.getByRole("main")).toHaveAttribute("dir", "rtl");
    expect(screen.getByRole("button", { name: /المتسعات/ })).toBeEnabled();
  });
  it("preserves the existing English literature section navigation", async () => {
    mocks.rows = [row("english_literature", 2, "Section 2"), row("english_literature", 3, "Section 3")];
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /English Literature/ }));
    fireEvent.click(screen.getByRole("button", { name: /Section 2/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question for english_literature 2")).toBeInTheDocument();
  });
  it("opens English literature Section 3 independently", async () => {
    mocks.rows = [row("english_literature", 2, "Section 2"), row("english_literature", 3, "Section 3")];
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /English Literature/ }));
    fireEvent.click(screen.getByRole("button", { name: /Section 3/ }));
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question for english_literature 3")).toBeInTheDocument();
    expect(screen.queryByText("Question for english_literature 2")).not.toBeInTheDocument();
  });

  it("offers Fahrast topics, opens only matching questions and returns to the topic list", async () => {
    mocks.rows = [
      { ...row("physics", 1, "Capacitors"), id: "dielectric-q", question: "A dielectric slab is inserted into a capacitor. What changes?", section: "phys-1-4" },
      { ...row("physics", 1, "Electric Capacitance"), id: "circuit-q", question: "Which expression gives the time constant?", section: "R-C Circuits" },
      { ...row("physics", 1, "Capacitors"), id: "general-q", question: "Which statement is correct?" },
    ];
    mocks.rpc.mockImplementation(async (method: string) => method === "answer_mcq_bank"
      ? { data: { correct: true, answer_index: 0, points: 1 }, error: null }
      : { data: [], error: null });
    render(<McqBank language="en" onBack={vi.fn()} />);
    fireEvent.click(await screen.findByRole("button", { name: /Physics/ }));
    fireEvent.click(screen.getByRole("button", { name: /Capacitors/ }));
    expect(screen.getByRole("heading", { name: "Fahrast topics" })).toBeInTheDocument();
    expect(screen.getByRole("button", { name: /1-2 Parallel-plate capacitor/ })).toBeDisabled();
    expect(screen.getByRole("button", { name: /1-9 RC-circuit 1 question/ })).toBeEnabled();
    expect(screen.getByRole("button", { name: /General chapter questions 1 question/ })).toBeEnabled();
    fireEvent.click(screen.getByRole("button", { name: /1-4 Dielectric 1 question/ }));
    expect(screen.getByRole("heading", { name: "Physics · 1-4 Dielectric" })).toBeInTheDocument();
    expect(screen.getByText("Question 1 of 1")).toBeInTheDocument();
    expect(screen.getByText(mocks.rows[0].question)).toBeInTheDocument();
    expect(screen.queryByText(mocks.rows[1].question)).toBeNull();
    fireEvent.click(screen.getByRole("button", { name: "A A" }));
    await waitFor(() => expect(mocks.rpc).toHaveBeenCalledWith("answer_mcq_bank", { _question_id: "dielectric-q", _choice_index: 0 }));
    fireEvent.click(await screen.findByRole("button", { name: "Chapter topics" }));
    expect(screen.getByRole("heading", { name: "Fahrast topics" })).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: /^All chapter questions/ }));
    expect(screen.getByText("Question 1 of 3")).toBeInTheDocument();
  });

  it("uses the original grammar and reading topics from the same English unit", () => {
    const groups = getFahrastTopicGroups("english", { key: "chapter:2", chapter: 2 }, [
      { id: "grammar", question: "We use this form for a polite request.", choices: ["Would you", "must", "need to"], answer_index: 0 },
      { id: "reading", question: "What is a radar speed gun?" },
      { id: "distractor", question: "Select the correct item.", choices: ["Radar speed gun", "Officer"], answer_index: 1 },
    ], "en");
    expect(groups.find(topic => topic.key === "eng-g2-2")).toMatchObject({ section: "Grammar — Unit 2", questionIds: ["grammar"] });
    expect(groups.find(topic => topic.key === "eng-r2-4")).toMatchObject({ section: "Reading — Unit 2", questionIds: ["reading"] });
    expect(groups.find(topic => topic.key === "general")?.questionIds).toEqual(["distractor"]);
  });
});
