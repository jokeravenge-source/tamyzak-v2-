Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
  const guard = await protect(req, "math-ch2-flashcards", { max: 30, windowSeconds: 60 });
  if (!guard.ok) return json({ error: guard.error }, guard.status);
  if (req.method !== "POST") return json({ error: "method_not_allowed" }, 405);

  let body: Record<string, unknown>;
  try { body = await req.json(); } catch { return json({ error: "bad_json" }, 400); }
  const expected = Deno.env.get("FLASHCARDS_DASH_PASSWORD") ?? "";
  if (!expected || typeof body.password !== "string" || !safeEqual(body.password, expected)) {
    return json({ error: "wrong_password" }, 401);
  }

  const topic = typeof body.topic === "string" ? body.topic.trim() : "";
  const cards = topic ? CARDS.filter((c) => c.topic === topic) : CARDS;
  const topics = [...new Set(CARDS.map((c) => c.topic))];
  return json({
    deck: "math-ch2-ahmed-fathi",
    count: cards.length,
    topics,
    cards,
  });
});
