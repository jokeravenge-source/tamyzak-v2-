# المحاضرة الثانية عشرة – الجسيم المركزي والجسيم الحركي

## 🧭 نظرة عامة

تستكمل المحاضرة دراسة الهيكل الخلوي بشرح الجسيم المركزي (Centrosome) وتركيبه ودوره أثناء الانقسام، ثم تشرح الجسيم الحركي (Kinetosome/Basal Body) الموجود عند قواعد الأهداب والأسواط والمسؤول عن حركتها.

## 1. الجسيم المركزي (Centrosome)

### الموقع والمنشأ

- يوجد في سيتوبلازم الخلية الحيوانية بالقرب من النواة.
- ينشأ تنظيمه من النبيبات الدقيقة.
- يتكون كيميائياً من بروتين التيوبيولين؛ لأن وحداته الأساسية نبيبات دقيقة.

### التركيب

- يتكون الجسيم المركزي من زوج من المريكزات (Pair of Centrioles).
- كل مريكز تركيب أسطواني.
- يكون المريكزان متعامدين، أي تصنع محاورهما زاوية تقارب 90 درجة.
- يتكون كل مريكز من تسع مجموعات ثلاثية من النبيبات الدقيقة:

**9 مجموعات × 3 نبيبات دقيقة = 27 نبيباً دقيقاً في المريكز الواحد.**

يسمى هذا الترتيب **9 Triplet Microtubules**.

## 2. دور الجسيم المركزي أثناء انقسام الخلية

وظيفته الأساسية هي تنظيم حركة الكروموسومات أثناء انقسام الخلية.

### التسلسل

1. يتضاعف الجسيم المركزي، فيصبح في الخلية جسيمان مركزيان.
2. يتحرك كل جسيم مركزي نحو قطب مقابل من أقطاب الخلية.
3. تتكون خيوط المغزل (Spindle Fibers) بين القطبين.
4. ترتبط خيوط المغزل بالكروموسومات وتساعد على حركتها وتوزيعها أثناء الانقسام.

**سلسلة الحفظ:** تضاعف ← حركة نحو القطبين ← خيوط المغزل ← حركة الكروموسومات

## 3. ماذا يحدث في الخلايا النباتية؟

- لا تمتلك الخلايا النباتية العليا جسماً مركزياً نموذجياً مثل الخلايا الحيوانية.
- توجد بدلاً منه مراكز تنظيمية تكوّن الخيوط الدقيقة والنبيبات الدقيقة اللازمة للخلية والانقسام.
- يجب التمييز بين وجود المريكزات وبين قدرة الخلية على تنظيم النبيبات الدقيقة.

## 4. الجسيم الحركي (Kinetosome)

### الأسماء

- يسمى الجسيم الحركي (Kinetosome).
- يسمى أيضاً الجسم القاعدي (Basal Body).

### سبب التسمية

سمي جسماً حركياً لأنه يسهم في حركة الأهداب والأسواط.

### الموقع

- يوجد عند قاعدة أو أسفل الهدب (Cilium) أو السوط (Flagellum).
- يوجد فقط في الخلايا التي تحتوي على أهداب أو أسواط.
- من الأمثلة:
  - الباراميسيوم: توجد الأجسام القاعدية عند قواعد الأهداب.
  - اليوغلينا: يوجد الجسم القاعدي عند قاعدة السوط.

### التركيب

- يشبه المريكز في تركيبه.
- يتكون من تسع مجموعات ثلاثية من النبيبات الدقيقة.
- تتكون النبيبات الدقيقة من بروتين التيوبيولين.
- تمتد التراكيب الأنبوبية من الجسم القاعدي إلى داخل الهدب أو السوط.

### الوظيفة

- تنظيم وتثبيت الأهداب والأسواط.
- المساهمة في حركة الأهداب والأسواط.

## 🔬 مقارنة بين الجسيم المركزي والجسيم الحركي

