4. موقع قريب من النواة.
5. خيوط المغزل المتكونة أثناء الانقسام.

### رسم الجسيم الحركي

1. الهدب أو السوط.
2. الجسم القاعدي عند القاعدة.
3. تسع مجموعات ثلاثية من النبيبات الدقيقة.
4. امتداد النبيبات باتجاه الهدب أو السوط.

