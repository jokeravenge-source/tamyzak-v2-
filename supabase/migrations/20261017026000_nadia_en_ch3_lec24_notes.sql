# المحاضرة الرابعة والعشرون – الجهاز التكاثري الأنثوي في الضفدع (Female Reproductive System of Frog)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة الجهاز التكاثري الأنثوي في الضفدع، ولا سيما المبيضين (Ovaries) وقناتي البيض (Oviducts) والجسم الدهني (Adipose Body). توضح صفات المبيضين وموقعهما ولونهما وتركيبهما المفصص، ثم تشرح قناة البيض من الخارج والداخل، ووظيفة القمع المهدب والغدد التي تفرز الألبومين، وتبين أن قناة البيض منفصلة عن القناة الكلوية عند الأنثى، وأن نهايتها تتوسع لتكوين كيس البيض (Egg Sac) قبل أن تفتح في المجمع (Cloaca).

## 📚 المفاهيم والشرح التفصيلي

### 1. المبيضان (Ovaries)

- تمتلك أنثى الضفدع زوجاً من المبايض (A Pair of Ovaries).
- يقع المبيضان قرب الكليتين (Kidneys).
- يرتبط المبيضان بالجدار الداخلي لجسم الضفدع بواسطة مسراق المبيض (Mesovarium).
- المبيض تركيب غير منتظم الشكل، ويكون متعدد الفصوص (Multilobed).
- يظهر المبيض على شكل كيس غير منتظم، أو مجموعة من الفصوص المتعددة.
- لون المبيض أسود مائل إلى الرصاصي أو رصاصي مسود (Blackish Gray).

### 2. الجسم الدهني عند الأنثى

- يوجد الجسم الدهني (Adipose Body) في الجهة الأمامية من المبيض.
- الجسم الدهني مخزن للغذاء (Food Store)، ويتكون من دهون مخزنة.
- يستخدمه الذكر والأنثى خلال السبات الشتوي (Winter Hibernation).
- خلال الشتاء يعتمد الضفدع على الدهون المخزنة.
- تساعد الدهون على نمو المبايض والخصى، وتحضيرها لموسم التكاثر في الربيع.
- بعد انتهاء السبات يبدأ موسم التكاثر، لذلك تكون الدهون قد ساعدت على تهيئة الجهاز التكاثري.

### 3. البطانة الداخلية للمبيض

- يبطن السطح الداخلي للمبيض بطبقة من الخلايا الجرثومية (Germinal Cells).
- وجود هذه الطبقة يدل على أن المبيض قادر على تكوين الخلايا الجنسية الأنثوية.
- تدخل الخلايا الجرثومية في انقسامات متعددة، ثم تتكون البيوض (Eggs).
- تسمى عملية تكوين البيوض تكوّن البيوض (Oogenesis).
- لون المبيض الخارجي الأسود أو الرصاصي المسود مرتبط بتركيبه ومحتواه كما وصف في المحاضرة.

## 🧬 قناة البيض (Oviduct)

### 1. صفات قناة البيض الخارجية

- قناة البيض طويلة (Long) وملتوية أو ملفوفة (Coiled).
- تشبه في طبيعتها الأنابيب المنوية الملتوية، لكن وظيفتها نقل البيوض.
- تقع قناة البيض قرب المبيض، لكنها لا ترتبط به ارتباطاً مباشراً.
- لا تكون قناة البيض متصلة بالمبيض من الأمام أو الخلف أو الجوانب.

### 2. القمع المهدب (Funnel with Cilia)

- تكون النهاية الأمامية أو الطرف الأمامي لقناة البيض على شكل تركيب قمعي (Funnel-shaped Structure).
- يكون القمع مهدباً (Ciliated)، أي يحتوي على أهداب (Cilia) على حافته.
- تساعد الأهداب على دفع البيوض وتحريكها باتجاه الجزء الخلفي من قناة البيض.
- عندما تنطلق البيوض من المبيض، يلتقطها القمع المهدب ويوجهها إلى داخل قناة البيض.

### 3. بطانة قناة البيض والغدد

- تحتوي البطانة الداخلية لقناة البيض على غدد (Glands).
- تفرز هذه الغدد مادة الألبومين (Albumin).
- أثناء مرور البيضة داخل قناة البيض، تحيط بها الغدد بمادة الألبومين.
- الألبومين مادة بروتينية (Protein Material).
- يفيد الألبومين البيضة المخصبة والجنين (Embryo) بعد ذلك.

### 4. نهاية قناة البيض وكيس البيض

- تتسع النهاية الخلفية لقناة البيض بشكل كيسي.
- يسمى هذا التوسع كيس البيض (Ovisac/Egg Sac).
- وظيفة كيس البيض جمع البيوض قبل طرحها.
- يتجمع البيض في كيس البيض قبل وضعه، ولا سيما أثناء التزاوج.
- تفتح قناة البيض بعد توسعها وتكوين الكيس في المجمع (Cloaca) من خلال فتحة خاصة.

## 🔍 الفرق بين جهاز الذكر وجهاز الأنثى في القنوات

- في الذكر ترتبط القنوات الناقلة للنطف بالقنوات الكلوية، وتشترك معها في قناة بولية تناسلية واحدة.
- في الأنثى تكون قناة البيض منفصلة عن القناة الكلوية.
- ينقل البول عند الأنثى إلى المثانة (Urinary Bladder)، ثم تفتح المثانة في المجمع.
- تكون فتحة قناة البيض منفصلة عن فتحة البول.
- لذلك لكل قناة فتحتها الخاصة في المجمع، ولا تختلط فتحة قناة البيض بفتحة البول.

## 🔄 مسار البيضة في الجهاز الأنثوي

**المبيض (Ovary) ⟶ القمع المهدب (Ciliated Funnel) ⟶ قناة البيض الطويلة الملتوية (Oviduct) ⟶ إضافة الألبومين (Albumin) ⟶ كيس البيض (Egg Sac) ⟶ المجمع (Cloaca).**

## 📖 التعريفات والمصطلحات

- **المبيض (Ovary):** عضو تكاثري أنثوي يوجد قرب الكلية، وتتكون داخله البيوض.
- **المبيضان (Ovaries):** زوج من الأعضاء التكاثرية الأنثوية في أنثى الضفدع.
- **مسراق المبيض (Mesovarium):** تركيب يربط المبيض بالجدار الداخلي لجسم الضفدع.
- **المبيض متعدد الفصوص (Multilobed Ovary):** مبيض غير منتظم يتكون من عدة فصوص.
- **الجسم الدهني (Adipose Body):** تركيب دهني أمام المبيض، يخزن الغذاء ويساعد على نمو المبايض والتحضير للتكاثر.
- **الخلايا الجرثومية (Germinal Cells):** خلايا تبطن السطح الداخلي للمبيض وتدخل في تكوين البيوض.
- **تكوّن البيوض (Oogenesis):** عملية تكوين البيوض من الخلايا الجرثومية.
- **قناة البيض (Oviduct):** قناة طويلة ملتوية تنقل البيوض من المبيض إلى المجمع.
- **القمع (Funnel):** النهاية الأمامية لقناة البيض، وتلتقط البيوض المنطلقة من المبيض.
- **الأهداب (Cilia):** زوائد دقيقة على حافة القمع تساعد على تحريك البيوض نحو داخل القناة.
- **الغدد (Glands):** تراكيب موجودة في بطانة قناة البيض وتفرز الألبومين.
- **الألبومين (Albumin):** مادة بروتينية تحيط بالبيضة أثناء مرورها في قناة البيض، وتفيد الجنين.
- **كيس البيض (Ovisac/Egg Sac):** توسع كيسي في نهاية قناة البيض، يجمع البيوض قبل وضعها.
- **المجمع (Cloaca):** تركيب تفتح فيه قناة البيض والفتحات الأخرى.
- **المثانة البولية (Urinary Bladder):** تركيب يخزن البول عند الأنثى، ثم يفتح في المجمع.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة تركيب المبيض

مبيضان قرب الكليتين + اتصال بالجدار الداخلي بواسطة مسراق المبيض + شكل متعدد الفصوص + لون رصاصي مسود.

### قاعدة وظيفة الجسم الدهني

دهون مخزنة ⟶ غذاء أثناء السبات + نمو المبايض + تحضير الجهاز التكاثري لموسم الربيع.

### قاعدة وظيفة القمع

قمع مهدب + أهداب ⟶ التقاط البيوض ودفعها إلى داخل قناة البيض.

### قاعدة وظيفة قناة البيض

قناة بيض طويلة ملتوية + غدد داخلية ⟶ نقل البيضة وإحاطتها بالألبومين.

### قاعدة مسار البيوض

المبيض ⟶ القمع المهدب ⟶ قناة البيض ⟶ كيس البيض ⟶ المجمع.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: موقع المبيضين واتصالهما

**السؤال:** أين يقع مبيضا أنثى الضفدع وكيف يرتبطان؟

**الإجابة:** يقعان قرب الكليتين، ويرتبطان بالجدار الداخلي لجسم الضفدع بواسطة مسراق المبيض (Mesovarium).

### مثال 2: صفات المبيض

**المعطيات:** تركيب غير منتظم، متعدد الفصوص، ولونه رصاصي مسود.

**الناتج:** هذا التركيب هو المبيض (Ovary) في أنثى الضفدع.

### مثال 3: وظيفة القمع المهدب

**السؤال:** ما وظيفة الأهداب الموجودة على القمع الأمامي لقناة البيض؟

**الإجابة:** تلتقط البيوض المنطلقة من المبيض وتدفعها إلى الجزء الخلفي من قناة البيض.

### مثال 4: وظيفة غدد قناة البيض

**المعطيات:** غدد موجودة في البطانة الداخلية لقناة البيض.

**الحل:** تفرز هذه الغدد مادة الألبومين البروتينية حول البيضة أثناء مرورها.

**الناتج النهائي:** تزويد البيضة المخصبة والجنين بمادة غذائية/واقية من الألبومين.

### مثال 5: الفرق بين قناة البيض والقناة الكلوية عند الأنثى

**السؤال:** هل قناة البيض مرتبطة مباشرة بالقناة الكلوية؟

**الإجابة:** لا، تكون قناة البيض منفصلة عن القناة الكلوية، ولكل منهما فتحة منفصلة في المجمع؛ فالبيض يمر من قناة البيض والبول يمر من المسار البولي إلى المثانة ثم المجمع.

