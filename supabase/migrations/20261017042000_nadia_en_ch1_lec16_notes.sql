# المحاضرة السادسة عشرة – الأنشطة الخلوية والانتشار

## 🧭 نظرة عامة

تبدأ المحاضرة الجزء الثاني من الفصل الأول بدراسة الأنشطة التي تجري داخل الخلية. تعرض تصنيفاً عاماً لهذه الأنشطة، ثم تركز على تبادل المواد بين الخلية وبيئتها عبر الغشاء البلازمي، وتشرح الانتشار وتعريفه وأمثلته وتجربة إثباته.

## 1. الأنشطة الخلوية (Cellular Activities)

- تحدث داخل الخلايا أنشطة متعددة تسهم في نشاط الكائن الحي كله.
- في الكائنات متعددة الخلايا، مثل النباتات والحيوانات، تمثل أنشطة الخلايا أساس الوظائف التي يؤديها الجسم.
- يمكن تلخيص الأنشطة التي ستُدرس ضمن محورين رئيسين:
  1. تبادل المواد بين الخلية وبيئتها عبر الغشاء البلازمي.
  2. الأيض الخلوي (Cellular Metabolism).

## 2. تبادل المواد عبر الغشاء البلازمي

تختلف آلية التبادل بحسب نوع المادة وحجمها وشحنتها وحاجة الخلية إليها. ومن العمليات المذكورة:

- الانتشار (Diffusion).
- الأسموزية (Osmosis).
- النقل الفعال (Active Transport).
- البلعمة (Phagocytosis).
- عمليات نقل أخرى تُشرح في المحاضرات اللاحقة.

## 3. الأيض الخلوي بإيجاز

### الهدم (Catabolism)

- تحطيم المواد والجزيئات المعقدة إلى مواد أبسط.
- يرتبط بإطلاق الطاقة.
- من أمثلته التنفس الخلوي الهوائي واللاهوائي.

### البناء (Anabolism)

- بناء مواد معقدة من مواد أبسط.
- من أمثلته بناء السكريات وتثبيت ثاني أوكسيد الكربون في النباتات.

## 4. أهمية تبادل المواد

يعد تبادل المواد أساساً للعمليات الخلوية لأنه:

- يسمح بدخول المواد اللازمة لبناء المادة الحية واستمرار النشاط الخلوي.
- ينظم خروج الفضلات والمواد غير اللازمة.
- يساعد على التخلص من الماء الزائد عند الحاجة.
- يحافظ على اتزان البيئة الداخلية للخلية.
- يتيح استمرار العمليات الحيوية داخل العضيات المختلفة.

## 5. الانتشار (Diffusion)

### التعريف

الانتشار هو حركة الأيونات أو الجزيئات في وسط معين من منطقة ذات تركيز عالٍ إلى منطقة ذات تركيز منخفض، حتى تتوزع بصورة أكثر اتزاناً.

### اتجاه الحركة

**تركيز عالٍ → تركيز منخفض → اتزان**

- لا يحتاج الانتشار إلى طاقة خلوية مباشرة.
- يختص بحركة الجزيئات والأيونات وفق تدرج التركيز.
- للماء عملية خاصة تسمى الأسموزية، وتُشرح بصورة مستقلة.

## 6. مواد تعبر بالانتشار

### الغازات

- الأوكسجين (O₂).
- ثاني أوكسيد الكربون (CO₂).

تنتشر هذه الغازات عبر الغشاء تبعاً لاختلاف تركيزها بين الخلية وبيئتها.

### المواد القابلة للذوبان في الدهون

- يساعد ذوبان بعض الجزيئات في الدهون على عبورها خلال الغشاء البلازمي.
- من الأمثلة المذكورة:
  - الهيدروكربونات (Hydrocarbons).
  - الكحولات (Alcohols).

## 7. تجربة إثبات الانتشار

### المواد المطلوبة

- إناء يحتوي على الماء بوصفه المذيب (Solvent).
- بلورات قليلة من إحدى المادتين:
  - كبريتات النحاس (Copper Sulfate)، ولونها أزرق.
  - برمنغنات البوتاسيوم (Potassium Permanganate)، ولونها بنفسجي.
- تمثل البلورات المادة المذابة (Solute).

### خطوات التجربة

1. يوضع الماء في الإناء من دون تحريك.
2. توضع بلورات كبريتات النحاس أو برمنغنات البوتاسيوم برفق في موضع محدد.
3. تذوب البلورات تدريجياً في الماء.
4. يبدأ اللون بالانتشار من موضع التركيز العالي حول البلورات.
5. ينتقل اللون إلى المناطق الأقل تركيزاً.
6. مع مرور الوقت ينتشر اللون في الماء كله ويصبح التوزيع متوازناً.

### المشاهدة

- يكون اللون شديداً قرب موضع البلورات في البداية.
- ينتشر اللون لمسافة صغيرة خلال زمن قصير.
- تزداد مسافة انتشار اللون كلما زاد زمن الانتشار.
- بعد مدة كافية يصبح اللون موزعاً بصورة متجانسة في المذيب.

### الاستنتاج

- تتحرك جسيمات المذاب من منطقة التركيز العالي إلى منطقة التركيز المنخفض.
- الانتشار فعال في المسافات القصيرة، بينما يحتاج الانتشار لمسافات أطول إلى زمن أكبر.
- تزداد المسافة التي تقطعها الجسيمات المنتشرة مع مرور الزمن حتى يتحقق الاتزان.

## 🔬 مصطلحات التجربة

| المصطلح | المعنى | المثال |
|---|---|---|
| Solute | المادة المذابة | كبريتات النحاس أو برمنغنات البوتاسيوم |
| Solvent | المادة المذيبة | الماء |
| High Concentration | منطقة ذات عدد أكبر من جسيمات المذاب | قرب البلورات |
| Low Concentration | منطقة ذات عدد أقل من جسيمات المذاب | الأجزاء البعيدة من الماء |
| Equilibrium | توزيع متقارب ومتوازن للجسيمات | انتشار اللون في الإناء كله |

