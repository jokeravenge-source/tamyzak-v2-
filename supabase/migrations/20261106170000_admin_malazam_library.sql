ON storage.objects FOR DELETE TO authenticated
USING (bucket_id = 'malazam-covers' AND public.has_role(auth.uid(), 'admin'::public.app_role));

-- Students never receive direct read permission for PDF objects. The gated
-- edge function verifies Telegram membership and returns a short-lived URL.
CREATE POLICY "Admins manage private malazam files"
ON storage.objects FOR ALL TO authenticated
USING (bucket_id = 'malazam-files' AND public.has_role(auth.uid(), 'admin'::public.app_role))
WITH CHECK (bucket_id = 'malazam-files' AND public.has_role(auth.uid(), 'admin'::public.app_role));
