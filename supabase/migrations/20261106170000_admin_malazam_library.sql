-- Admin-managed Al-Malazam library with Telegram-gated private downloads.
CREATE TABLE IF NOT EXISTS public.malazam (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  subject text NOT NULL CHECK (subject IN ('physics', 'chemistry', 'biology', 'math', 'arabic', 'english', 'french', 'islamic', 'revision')),
  topic text NOT NULL CHECK (char_length(topic) BETWEEN 1 AND 120),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 180),
  cover_path text NOT NULL,
  file_path text NOT NULL,
  is_published boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_by uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.malazam TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.malazam TO authenticated;
GRANT ALL ON public.malazam TO service_role;

ALTER TABLE public.malazam ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Published malazam are publicly readable"
ON public.malazam FOR SELECT TO anon, authenticated
USING (is_published = true OR public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE POLICY "Admins insert malazam"
ON public.malazam FOR INSERT TO authenticated
WITH CHECK (public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE POLICY "Admins update malazam"
ON public.malazam FOR UPDATE TO authenticated
USING (public.has_role(auth.uid(), 'admin'::public.app_role))
WITH CHECK (public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE POLICY "Admins delete malazam"
ON public.malazam FOR DELETE TO authenticated
USING (public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE INDEX IF NOT EXISTS malazam_public_catalog_idx
ON public.malazam (is_published, subject, sort_order, created_at DESC);

CREATE TRIGGER malazam_set_updated_at
BEFORE UPDATE ON public.malazam
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public.malazam_downloads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  malzama_id uuid NOT NULL REFERENCES public.malazam(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  downloaded_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT ON public.malazam_downloads TO authenticated;
GRANT ALL ON public.malazam_downloads TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.malazam_downloads_id_seq TO service_role;

ALTER TABLE public.malazam_downloads ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins view malazam download analytics"
ON public.malazam_downloads FOR SELECT TO authenticated
USING (public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE INDEX IF NOT EXISTS malazam_downloads_item_time_idx
ON public.malazam_downloads (malzama_id, downloaded_at DESC);

