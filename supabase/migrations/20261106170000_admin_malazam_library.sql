CREATE POLICY "Malazam covers are public"
ON storage.objects FOR SELECT TO anon, authenticated
USING (bucket_id = 'malazam-covers');

CREATE POLICY "Admins upload malazam covers"
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (bucket_id = 'malazam-covers' AND public.has_role(auth.uid(), 'admin'::public.app_role));

CREATE POLICY "Admins update malazam covers"
ON storage.objects FOR UPDATE TO authenticated
USING (bucket_id = 'malazam-covers' AND public.has_role(auth.uid(), 'admin'::public.app_role))
WITH CHECK (bucket_id = 'malazam-covers' AND public.has_role(auth.uid(), 'admin'::public.app_role));

