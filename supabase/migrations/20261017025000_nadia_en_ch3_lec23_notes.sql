# المحاضرة الثالثة والعشرون – الجهاز التكاثري الذكري في الضفدع (Male Reproductive System of Frog)

## 🧭 نظرة عامة سريعة

تتناول المحاضرة الضفدع (Frog) بوصفه مثالاً مهماً من البرمائيات (Amphibians)، وتحدد تصنيفه ضمن الفقريات (Vertebrates) وذوات الأربع أقدام (Tetrapods). ثم تشرح الجهاز التكاثري الذكري، ولا سيما الخصيتين (Testes)، الجسم الدهني (Adipose Body)، الأنابيب المنوية (Seminiferous Tubules)، القنوات الصادرة (Vasa Efferentia)، القنوات الناقلة للنطف (Vasa Deferentia) والمجمع (Cloaca). كما توضح صفات الخصية ولونها وموقعها ووظائف تراكيبها، وتؤكد أن ذكر الضفدع لا يمتلك أعضاء جماع خارجية.

## 📚 المفاهيم والشرح التفصيلي

### 1. تصنيف الضفدع

- الضفدع (Frog) من أفضل الأمثلة التي تدرس ضمن الحيوانات الفقرية.
- ينتمي إلى صف البرمائيات (Class Amphibia).
- البرمائيات تنتمي إلى شعبة الفقريات (Phylum Vertebrata).
- الضفدع من الحيوانات رباعية الأقدام (Tetrapods)، أي يمتلك أربعة أطراف.
- تكاثر الضفدع تكاثر جنسي (Sexual Reproduction)، إذ توجد أعضاء تكاثرية ذكرية وأعضاء تكاثرية أنثوية منفصلة.

### 2. الخصيتان (Testes)

- يمتلك ذكر الضفدع زوجاً من الخصى (A Pair of Testes).
- الخصية تركيب بيضاوي الشكل (Oval-shaped) ومتطاول.
- تكون الخصيتان ملاصقتين للكليتين (Kidneys) ومرتبطتين بهما.
- لون الخصية أصفر فاتح (Light Yellow).
- ترتبط الخصية بالجدار الداخلي للجسم بواسطة مسراق الخصية (Mesorchium).
- مسراق الخصية هو تركيب يشبه المسراق، يثبت الخصية ويربطها بالجدار الداخلي أو بالكلية.

### 3. الجسم الدهني (Adipose Body)

- يوجد الجسم الدهني (Adipose Body) في الطرف الأمامي/العلوي من الخصية عند الذكر، ويوجد أيضاً عند الأنثى في الموضع الأمامي.
- شكله يشبه زوائد أو أصابع متطاولة (Finger-shaped Projections).
- يتكون من دهون مخزنة (Stored Fat).
- يسمى جسماً دهنياً لأنه يمثل مخزناً للغذاء (Food Store).
- يستخدمه الحيوان لنمو الخصيتين (Testes) وتحضيرهما للتكاثر.
- يساعد على نمو الخصية وإنتاج النطف (Sperms) استعداداً لموسم التكاثر.

### 4. أهمية الجسم الدهني خلال السبات

- يدخل الضفدع في سبات شتوي (Winter Hibernation) خلال فصل الشتاء.
- أثناء السبات تقل حركة الحيوان، ويعتمد على الدهون المخزنة في الجسم الدهني.
- يتنفس الضفدع خلال هذه الفترة عن طريق الجلد (Cutaneous Respiration)، لأن المزمار/الحنجرة تكون مغلقة بحسب ما ورد في الشرح.
- يستعمل الدهون المخزنة بوصفها مصدراً غذائياً خلال السبات.
- بعد انتهاء السبات، ولا سيما في فصل الربيع، يبدأ موسم التكاثر.
- يحتاج الذكر إلى نمو الخصيتين وإنتاج النطف، لذلك يستعمل الدهون المخزنة لهذا الغرض.

### 5. الأنابيب المنوية (Seminiferous Tubules)

- تحتوي الخصية من الداخل على أنابيب منوية تسمى الأنابيب المنوية (Seminiferous Tubules).
- كلمة Seminiferous تعني مرتبطة بتكوين النطف أو الأنابيب المنتجة للنطف.
- تكون الأنابيب المنوية ملتوية (Coiled)، وليست أنابيب مستقيمة.
- تبطن الأنابيب المنوية من الداخل بنسيج طلائي (Epithelial Tissue).
- توجد داخلها خلايا تكوّن النطف.
- وظيفة الخصية الرئيسة هي إنتاج النطف (Sperm Production).
- عملية تكوين النطف تسمى تكوّن النطف (Spermatogenesis).

### 6. القنوات الصادرة (Vasa Efferentia)

- توجد قنوات صادرة تسمى القنوات الصادرة (Vasa Efferentia).
- يبلغ عددها تقريباً من 10 إلى 12 قناة.
- ترتبط هذه القنوات بالأنابيب المنوية من جهة وبالقنوات الكلوية من جهة أخرى.
- تقع بين الأنابيب المنوية والقنوات الكلوية.
- وظيفتها نقل النطف من الخصية باتجاه القنوات الكلوية.
- تعد حلقة وصل بين الجهاز التكاثري والجهاز الإخراجي.

### 7. القنوات الكلوية (Kidney Ducts)

- توجد القنوات الكلوية أو البولية (Kidney/Urinary Ducts) بجوار القنوات المنوية.
- تستقبل القنوات الصادرة النطف من الأنابيب المنوية.
- لا تنقل النطف وحدها؛ بل ترتبط لاحقاً بمسار نقل البول أيضاً.

### 8. القنوات الناقلة للنطف (Vasa Deferentia)

- بعد القنوات الصادرة توجد القنوات الناقلة للنطف، وتسمى القنوات الناقلة (Vasa Deferentia).
- توجد عادة قناتان ناقلتان للنطف بحسب الشرح.
- وظيفتها نقل النطف باتجاه المجمع (Cloaca).
- تتميز في الضفدع بأنها تشترك مع القنوات الكلوية في قناة واحدة.

### 9. القناة البولية التناسلية المشتركة (Urogenital Duct)

- تشترك القناة الناقلة للنطف مع القناة الكلوية في قناة مشتركة.
- تسمى هذه القناة القناة البولية التناسلية (Urogenital Duct/Canal).
- تنقل هذه القناة كلاً من البول والنطف.
- لذلك فهي تجمع بين وظيفة الجهاز البولي ووظيفة الجهاز التكاثري.
- تفتح القناة البولية التناسلية في المجمع (Cloaca).

### 10. المجمع (Cloaca)

- المجمع (Cloaca) تركيب تفتح فيه القنوات البولية والتناسلية.
- تصب فيه القناة المشتركة البولية التناسلية.
- يستقبل البول والنطف قبل خروجهما.
- يمثل نهاية المسار المشترك للجهاز البولي والتكاثري في ذكر الضفدع.

### 11. الحويصلة المنوية (Seminal Vesicle)

- في بعض أنواع الضفادع تتمدد القناة الناقلة للنطف.
- يؤدي هذا التمدد إلى تكوين حويصلة منوية (Seminal Vesicle).
- تخزن الحويصلة المنوية النطف الناضجة (Mature Sperms).
- لا تتكون الحويصلة المنوية بالطريقة نفسها في جميع أنواع الضفادع؛ فهي موجودة في بعض الأنواع فقط.

### 12. عدم وجود أعضاء جماع خارجية

- ذكر الضفدع لا يمتلك أعضاء جماع خارجية (External Mating Organs).
- هذه صفة مهمة يجب حفظها.
- يحدث التكاثر دون وجود عضو جماع خارجي.

