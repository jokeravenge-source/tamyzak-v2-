## 📖 التعريفات والمصطلحات

- **الضفدع (Frog):** حيوان فقري من البرمائيات وذوات الأربع أقدام.
- **البرمائيات (Amphibia):** صف من الفقريات يضم الضفدع.
- **الفقريات (Vertebrata):** شعبة الحيوانات التي ينتمي إليها الضفدع بحسب المحاضرة.
- **ذوات الأربع أقدام (Tetrapods):** حيوانات تمتلك أربعة أطراف، ومنها الضفدع.
- **الخصية (Testis):** عضو تكاثري ذكري ينتج النطف.
- **مسراق الخصية (Mesorchium):** تركيب يربط الخصية بالكلية أو بالجدار الداخلي للجسم.
- **الجسم الدهني (Adipose Body):** زوائد إصبعية الشكل تحتوي على دهون مخزنة وتعمل مخزناً للغذاء.
- **السبات الشتوي (Winter Hibernation):** فترة يقل فيها نشاط الضفدع خلال الشتاء ويعتمد فيها على الدهون المخزنة.
- **الأنابيب المنوية (Seminiferous Tubules):** أنابيب ملتوية داخل الخصية، تتكون فيها النطف.
- **تكوّن النطف (Spermatogenesis):** عملية إنتاج النطف داخل الأنابيب المنوية.
- **القنوات الصادرة (Vasa Efferentia):** قنوات عددها تقريباً 10–12، تنقل النطف من الأنابيب المنوية إلى القنوات الكلوية.
- **القنوات الناقلة للنطف (Vasa Deferentia):** قنوات تنقل النطف باتجاه القناة البولية التناسلية والمجمع.
- **القنوات الكلوية (Kidney Ducts):** قنوات ترتبط بالقنوات الصادرة وتنقل البول، وقد تشترك مع القنوات الناقلة للنطف.
- **القناة البولية التناسلية (Urogenital Duct):** قناة مشتركة تنقل البول والنطف معاً.
- **المجمع (Cloaca):** تركيب تفتح فيه القناة البولية التناسلية وتصب فيه الفضلات والنطف.
- **الحويصلة المنوية (Seminal Vesicle):** توسع في القناة الناقلة للنطف عند بعض الأنواع، وتخزن النطف الناضجة.
- **الأعضاء الجماعية الخارجية (External Mating Organs):** أعضاء غير موجودة عند ذكر الضفدع.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة تركيب الخصية

خصيتان بيضاويتان متطاولتان + لون أصفر فاتح + اتصال بالكلية بواسطة مسراق الخصية.

### قاعدة وظيفة الجسم الدهني

دهون مخزنة ⟶ غذاء خلال السبات + نمو الخصيتين + تكوين النطف استعداداً للتكاثر.

### قاعدة مسار النطف

الأنابيب المنوية ⟶ القنوات الصادرة ⟶ القنوات الكلوية ⟶ القنوات الناقلة للنطف ⟶ القناة البولية التناسلية ⟶ المجمع.

### قاعدة القناة المشتركة

القناة الناقلة للنطف + القناة الكلوية ⟶ القناة البولية التناسلية المشتركة.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تحديد موقع الخصيتين

**السؤال:** أين توجد خصيتا الضفدع؟

**الإجابة:** توجدان في الجهة الداخلية قرب الكليتين، وتكونان متصلتين بهما بواسطة مسراق الخصية.

### مثال 2: وظيفة الجسم الدهني

**السؤال:** ما وظيفة الجسم الدهني؟

**الإجابة:** يخزن الدهون التي يستعملها الضفدع غذاءً خلال السبات، كما تساعد هذه الدهون على نمو الخصيتين وتكوين النطف قبل موسم التكاثر.

### مثال 3: مسار النطف

**المعطيات:** نطف تكونت داخل الأنابيب المنوية.

**خطوات الانتقال:**

1. تنتقل إلى القنوات الصادرة.
2. تصل إلى القنوات الكلوية.
3. تنتقل إلى القنوات الناقلة للنطف.
4. تدخل القناة البولية التناسلية المشتركة.
5. تفتح في المجمع.

**الناتج النهائي:** تصل النطف إلى المجمع عبر القناة البولية التناسلية المشتركة.

### مثال 4: وظيفة القنوات الصادرة

**السؤال:** لماذا تعد القنوات الصادرة مهمة؟

**الإجابة:** لأنها تربط الأنابيب المنوية بالقنوات الكلوية وتنقل النطف من الخصية باتجاه المسار المشترك.

