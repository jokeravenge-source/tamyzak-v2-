### مثال 3: تحديد مكونات الشبكة الإندوبلازمية

- **المعطيات:** نظام شبكي داخل السيتوبلازم.
- **القاعدة:** الشبكة الإندوبلازمية تتكون من أنابيب وحويصلات مترابطة.
- **الناتج:** أنابيب + حويصلات.

### مثال 4: تحديد وظيفة الشبكة الإندوبلازمية

