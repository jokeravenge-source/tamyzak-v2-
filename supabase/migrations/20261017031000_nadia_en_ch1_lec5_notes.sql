# محاضرة 5: السيتوبلازم والشبكة الإندوبلازمية

## 🧭 نظرة عامة سريعة

تشرح المحاضرة السيتوبلازم (Cytoplasm) بوصفه جزءاً رئيسياً من الخلية، وموقعه وتركيبه ونسب مكوناته ومحتوياته الحية وغير الحية، ثم تبدأ بدراسة الشبكة الإندوبلازمية (Endoplasmic Reticulum) بوصفها أول عضية، مع تعريفها وموقعها ووظيفتها العامة وتقسيمها إلى شبكة خشنة وملساء.

## 📚 المفاهيم والشرح التفصيلي

### 1. السيتوبلازم (Cytoplasm)

- السيتوبلازم جزء رئيسي من الخلية (Main Part of the Cell).
- يوجد بين النواة (Nucleus) والغشاء البلازمي (Plasma Membrane).
- السيتوبلازم مادة معقدة التركيب (Complex Material).
- يوجد في الخلايا النباتية والحيوانية.

### 2. التركيب النسبي للسيتوبلازم

النسب التي ركزت عليها المحاضرة:

- **80% ماء (Water).**
- **50% بروتينات (Proteins).**
- **5% دهون وسكريات (Fats and Sugars).**

كما ورد في الشرح أن السيتوبلازم يتكون من ماء ودهون وسكريات وبروتينات، ويجب الانتباه إلى النسب لأنها قد تأتي في الفراغات.

### 3. محتويات السيتوبلازم

يمتلك السيتوبلازم نوعين من المحتويات:

#### أ. المحتويات الحية (Living Contents)

- تتمثل بالعضيات (Organelles) الموجودة داخل السيتوبلازم.

#### ب. المحتويات غير الحية (Non-living Contents)

- تتمثل بالجزيئات والمواد غير الحية الموجودة في السيتوبلازم.
- تنشأ من الأنشطة الحيوية (Biological Activities) التي تقوم بها العضيات.
- عندما تؤدي العضيات وظائفها وعملياتها، تكون النتيجة مواد غير حية تتركز أو تُخزن داخل السيتوبلازم.
- قد تتجمع هذه المواد على شكل حبيبات (Granules).

⚠️ **مهم:** إذا سُئل عن محتويات السيتوبلازم، فالإجابة نوعان: محتويات حية وهي العضيات، ومحتويات غير حية وهي الجزيئات والمواد الناتجة من النشاط الحيوي.

### 4. الشبكة الإندوبلازمية (Endoplasmic Reticulum)

هي أول عضية حية يدرسها المدرس بالتفصيل ضمن محتويات السيتوبلازم.

#### أ. التعريف

الشبكة الإندوبلازمية هي **نظام شبكي مترابط (Interconnected System)** داخل السيتوبلازم.

#### ب. التركيب

يتكون هذا النظام الشبكي من:

- أنابيب (Tubules).
- حويصلات (Vesicles).

#### ج. الوظيفة العامة

- تُصنّع المواد داخلها.
- تُنقل المواد المصنّعة على شكل حويصلات إلى عضيات أخرى داخل الخلية.
- تصل هذه المواد إلى العضيات الأخرى حتى تؤدي وظائفها بصورة كاملة.
- تقوم بتصنيع الدهون (Fats) والبروتينات (Proteins) والكربوهيدرات (Carbohydrates).

#### د. الموقع

- توجد داخل السيتوبلازم.
- تمتد على نطاق واسع داخل الخلية، ويمكن رسمها في أماكن مختلفة من السيتوبلازم.
- ترتبط من جهة بمناطق محددة من النواة (Nucleus)، ومن جهة أخرى بالغشاء البلازمي، بحسب الرسم والتوضيح في المحاضرة.
- المهم في الرسم أن تظهر بوصفها شبكة مترابطة داخل الخلية، لا أن تُرسم في موضع واحد فقط.

#### هـ. سبب التسمية

- سميت إندوبلازمية لأن كلمة **إندو (Endo)** تعني داخل.
- وهي شبكة موجودة داخل السيتوبلازم، وتفرعاتها وتشابكاتها متصلة ببعضها.

### 5. أنواع الشبكة الإندوبلازمية

تنقسم الشبكة الإندوبلازمية إلى نوعين:

1. الشبكة الإندوبلازمية الخشنة (Rough Endoplasmic Reticulum).
2. الشبكة الإندوبلازمية الملساء (Smooth Endoplasmic Reticulum).

المحاضرة قدمت التقسيم، أما تفاصيل كل نوع فتُدرس في الدروس اللاحقة.

## 📖 التعريفات والمصطلحات

- **السيتوبلازم (Cytoplasm):** مادة معقدة التركيب توجد بين النواة والغشاء البلازمي، وتحتوي على العضيات والمواد غير الحية.
- **المحتويات الحية (Living Contents):** العضيات الموجودة داخل السيتوبلازم.
- **المحتويات غير الحية (Non-living Contents):** الجزيئات والمواد الناتجة من الأنشطة الحيوية والمتجمعة في السيتوبلازم.
- **العضيات (Organelles):** تراكيب حية موجودة داخل السيتوبلازم وتؤدي وظائف مختلفة.
- **الشبكة الإندوبلازمية (Endoplasmic Reticulum):** نظام شبكي مترابط داخل السيتوبلازم، يتكون من أنابيب وحويصلات.
- **الأنابيب (Tubules):** أجزاء أنبوبية تكوّن جزءاً من الشبكة الإندوبلازمية.
- **الحويصلات (Vesicles):** تراكيب صغيرة تنقل المواد المصنّعة إلى عضيات أخرى.
- **الشبكة الإندوبلازمية الخشنة (Rough Endoplasmic Reticulum):** أحد نوعي الشبكة الإندوبلازمية، وقدمه المدرس بوصفه نوعاً سيُدرس لاحقاً.
- **الشبكة الإندوبلازمية الملساء (Smooth Endoplasmic Reticulum):** النوع الثاني من الشبكة الإندوبلازمية، وتفاصيله ستُدرس لاحقاً.

## 🔢 القوانين / الصيغ / القواعد

- موقع السيتوبلازم = بين النواة والغشاء البلازمي.
- محتويات السيتوبلازم = محتويات حية + محتويات غير حية.
- المحتويات الحية = العضيات.
- المحتويات غير الحية = جزيئات ومواد ناتجة من الأنشطة الحيوية.
- الشبكة الإندوبلازمية = نظام مترابط من أنابيب وحويصلات.
- أنواع الشبكة الإندوبلازمية = خشنة + ملساء.
- وظيفة الشبكة العامة = تصنيع الدهون والبروتينات والكربوهيدرات ونقلها بالحويصلات.

