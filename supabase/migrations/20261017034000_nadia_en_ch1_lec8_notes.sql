- تحاط بغشائين: خارجي وداخلي.
- الأعراف طيات منشؤها الغشاء الداخلي، وتتجه نحو تجويف المايتوكوندريا.
- وظيفة الأعراف زيادة المساحة السطحية للغشاء الداخلي ورفع كفاءة التنفس وإنتاج الطاقة.
- الوظيفة الأساسية للمايتوكوندريا هي التنفس الخلوي، ويعقبه إنتاج ATP.
- تسمى بيت الطاقة لأنها تنتج ATP.

## 🧠 الخلاصة

