# المحاضرة الثامنة – المايتوكوندريا (Mitochondria)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة المايتوكوندريا بوصفها عضية خلوية موجودة في سيتوبلازم الخلايا حقيقية النواة. تتناول أشكالها وأبعادها وتوزيعها، ثم توضح تركيب الغشائين الخارجي والداخلي، والأعراف (Cristae)، والحشوة (Matrix)، ووظيفتها الأساسية في التنفس الخلوي وإنتاج طاقة ATP.

## 📚 المفاهيم والشرح التفصيلي

### 1. تعريف المايتوكوندريا وموقعها

- المايتوكوندريا (Mitochondria) عضية خلوية (Cellular Organelle).
- توجد داخل السيتوبلازم في الخلايا حقيقية النواة (Eukaryotic Cells).
- لا تمتلك شكلاً واحداً ثابتاً.

### 2. أشكال المايتوكوندريا وأبعادها

- قد تكون كروية الشكل (Spherical).
- قد تكون خيطية الشكل (Filamentous).
- يتراوح عرضها تقريباً بين 0.5 و1 ميكرومتر.
- قد يصل طولها إلى 10 ميكرومترات.

### 3. توزيع المايتوكوندريا وعددها

- يختلف توزيع المايتوكوندريا من خلية إلى أخرى.
- لا يكون ترتيبها وعددها متماثلين في جميع الخلايا.
- يعتمد عددها على حاجة الخلية إلى الطاقة.
- الخلية التي تحتاج كمية أكبر من الطاقة تحتوي عادةً على عدد أكبر من المايتوكوندريا.

## 🧬 تركيب المايتوكوندريا

### 1. الغشاء الخارجي (Outer Membrane)

- يحيط بالمايتوكوندريا من الخارج.
- يمثل الحد الخارجي للعضية.

### 2. الغشاء الداخلي (Inner Membrane)

- يقع داخل الغشاء الخارجي.
- يحتوي على طيات وانثناءات وانحناءات عديدة.
- تختلف هذه الطيات في الشكل والاتجاه.
- تتجه قمم الطيات والانحناءات نحو تجويف المايتوكوندريا.
- عند الرسم يجب إظهار الغشاء الداخلي متصلاً، مع طياته المتجهة إلى الداخل، وليس على شكل خطوط منفصلة أو غير منتظمة.

### 3. الأعراف (Cristae)

- الأعراف هي الطيات والانحناءات الناتجة من الغشاء الداخلي للمايتوكوندريا.
- المفرد يسمى Crista، والجمع يسمى Cristae.
- أصل الأعراف هو الغشاء الداخلي.
- تزيد الأعراف المساحة السطحية للغشاء الداخلي.
- زيادة المساحة السطحية ترفع كفاءة المايتوكوندريا في التنفس الخلوي وإنتاج الطاقة.

### 4. الحشوة (Matrix)

- تمثل المادة الموجودة داخل تجويف المايتوكوندريا.
- تحتوي على إنزيمات وريبوسومات ومواد أخرى.
- تُعد من التأشيرات الأساسية في رسم المايتوكوندريا.

## ⚙️ وظائف المايتوكوندريا

### الوظيفة الأساسية: التنفس الخلوي

- تؤدي المايتوكوندريا عملية التنفس الداخلي الخلوي (Intracellular Respiration).
- تُعد هذه الوظيفة أساسية؛ لأن إنتاج الطاقة يعتمد على حدوث التنفس الخلوي أولاً.
- تحتوي المايتوكوندريا على إنزيمات خاصة بعملية التنفس.

### إنتاج طاقة ATP

- ينتج عن التنفس الخلوي تكوين طاقة ATP.
- ATP هو الأدينوسين ثلاثي الفوسفات (Adenosine Triphosphate).
- تعتمد عملية إنتاج ATP على إتمام عملية التنفس الخلوي.

**سلسلة سهلة للحفظ:**

التنفس الخلوي داخل المايتوكوندريا → إنتاج ATP → توفير الطاقة للخلية

## 🔋 بيت الطاقة

- تسمى المايتوكوندريا بيت الطاقة أو محطة الطاقة في الخلية (Powerhouse / Energy House).
- سبب التسمية هو إنتاجها طاقة ATP.

## ✏️ تأشيرات الرسم المهمة

