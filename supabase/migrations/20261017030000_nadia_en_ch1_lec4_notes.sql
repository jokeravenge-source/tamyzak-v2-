# محاضرة 4: الغشاء البلازمي (Plasma Membrane)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة الغشاء البلازمي الموجود في الخلايا النباتية والحيوانية، وتوضح الفرق بينه وبين جدار الخلية، وصفاته ووظيفته، ثم تشرح تركيبه تحت المجهر الإلكتروني: طبقتان من الدهون المفسفرة، وبروتينات ناقلة تؤدي دوراً انتقائياً في إدخال المواد وإخراجها.

## 📚 المفاهيم والشرح التفصيلي

### 1. الغشاء البلازمي وجدار الخلية

- يوجد الغشاء البلازمي في الخلية النباتية (Plant Cell) والخلية الحيوانية (Animal Cell).
- الغشاء البلازمي يسمى أيضاً غشاء الخلية (Cell Membrane) أو البلازمالِمّا (Plasmalemma).
- يختلف الغشاء البلازمي تماماً عن جدار الخلية (Cell Wall).
- جدار الخلية مادة غير حية، أما الغشاء البلازمي فهو مادة حية (Living Material).
- جدار الخلية النباتية يرتبط بالسليلوز (Cellulose)، بينما الغشاء البلازمي غشاء مرن ورقيق.

### 2. صفات الغشاء البلازمي

- رقيق (Thin).
- مرن (Flexible).
- شبه منفذ (Semipermeable).
- اختياري النفاذية (Selectively Permeable).
- يحيط بالخلية وينظم ما يدخل إليها وما يخرج منها.

### 3. النفاذية الاختيارية

لا يسمح الغشاء البلازمي للمواد بالدخول والخروج بصورة عشوائية، بل يختار المواد حسب حاجة الخلية وتركيز المادة:

- يسمح بدخول المواد المفيدة التي تحتاج إليها الخلية.
- يخرج المواد السامة (Toxic Materials) أو غير المفيدة.
- يسمح بمرور الجزيئات الصغيرة (Small Particles)، ويمنع الجزيئات الأكبر بحسب اختياره.
- تعتمد عملية الاختيار على المادة وتركيزها وحاجة الخلية.

### 4. رؤية الغشاء البلازمي بالمجهر

- عند استخدام المجهر الضوئي (Light Microscope) يظهر الغشاء بصورة خط أو طبقتين مبسطتين، ولا يمكن دراسة تفاصيله الدقيقة.
- لدراسة تركيبه التفصيلي نستخدم المجهر الإلكتروني (Electron Microscope).
- يوضح المجهر الإلكتروني أن الغشاء البلازمي مكوّن من طبقتين (Two Layers).

### 5. التركيب الكيميائي للغشاء البلازمي

#### أ. الدهون المفسفرة (Phospholipids)

- يتكون الغشاء من طبقتين من الدهون المفسفرة.
- لكل جزيء دهن مفسفر نهايتان مختلفتان:
  - نهاية محبة للماء (Hydrophilic End).
  - نهاية كارهة للماء (Hydrophobic End).
- النهايات المحبة للماء تكون على تماس مع الماء الموجود خارج الخلية ومع الماء الموجود في السيتوبلازم (Cytoplasm).
- النهايات الكارهة للماء تتجه إلى الداخل، فتتقابل بين الطبقتين.

#### ب. البروتينات الناقلة (Carrier Proteins)

- توجد بروتينات خاصة تفصل طبقتي الدهون المفسفرة أو تعبرهما.
- تسمى البروتينات الناقلة (Carrier Proteins).
- تختلف في أحجامها ومواقعها:
  - بروتين كبير يمتد من بداية الطبقة إلى نهاية الطبقة الثانية.
  - بروتين يوجد في الوسط.
  - بروتين صغير يوجد على السطح الداخلي أو الخارجي.
- لكل نوع وظيفة معينة.
- تساعد البروتينات الناقلة على إدخال مواد تحتاج إليها الخلية أو إخراج مواد منها.

### 6. أنواع البروتينات بحسب انفتاحها

أكد المدرس حفظ الرسم القياسي والأرقام المرتبطة به:

- **البروتين 7:** مرتبط من الخارج ومفتوح من الداخل.
- **البروتين 8:** مرتبط من الداخل ومفتوح من الخارج.
- **البروتين 11:** مفتوح من الجهتين.

عند دخول مادة تحتاج إليها الخلية، تتحرك عبر البروتين الناقل، وقد يفتح البروتين من جهة ويغلق من جهة أخرى بحسب المادة وحركتها واختيار الغشاء وتركيز المادة.

## 📖 التعريفات والمصطلحات

- **الغشاء البلازمي (Plasma Membrane):** غشاء رقيق ومرن وشبه منفذ يحيط بالخلية وينظم دخول المواد وخروجها.
- **غشاء الخلية (Cell Membrane):** اسم آخر للغشاء البلازمي.
- **البلازمالِمّا (Plasmalemma):** اسم آخر للغشاء البلازمي.
- **شبه منفذ (Semipermeable):** يسمح بمرور بعض المواد ولا يسمح بمرور مواد أخرى.
- **اختياري النفاذية (Selectively Permeable):** يختار المواد التي تدخل إلى الخلية أو تخرج منها بحسب فائدتها وحاجتها وتركيزها.
- **الدهون المفسفرة (Phospholipids):** دهون تتكون منها طبقتا الغشاء البلازمي، ولها نهاية محبة للماء وأخرى كارهة للماء.
- **محب للماء (Hydrophilic):** نهاية تتلامس مع الماء.
- **كاره للماء (Hydrophobic):** نهاية لا تحب الماء وتتجه إلى داخل طبقتي الغشاء.
- **البروتينات الناقلة (Carrier Proteins):** بروتينات تساعد على نقل المواد إلى داخل الخلية أو خارجها.
- **المجهر الإلكتروني (Electron Microscope):** المجهر المستخدم لدراسة تفاصيل تركيب الغشاء البلازمي.

## 🔢 القوانين / الصيغ / القواعد

- تركيب الغشاء البلازمي = طبقتان من الدهون المفسفرة + بروتينات ناقلة.
- الدهون المفسفرة = نهاية محبة للماء + نهاية كارهة للماء.
- النهايات المحبة للماء تتجه نحو الماء خارج الخلية وداخل السيتوبلازم.
- النهايات الكارهة للماء تتقابل في وسط الغشاء.
- البروتين 7: مفتوح من الداخل.
- البروتين 8: مفتوح من الخارج.
- البروتين 11: مفتوح من الجهتين.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تمييز الغشاء عن جدار الخلية

- إذا كان التركيب رقيقاً ومرناً وحياً واختيارياً في إدخال المواد وإخراجها، فهو الغشاء البلازمي.
- إذا كان التركيب جداراً خارجياً مرتبطاً بالسليلوز في الخلية النباتية، فهو جدار الخلية.

### مثال 2: تحديد اتجاه الدهون المفسفرة

- **المعطيات:** طبقتان من الدهون المفسفرة.
- **الحل:** تتجه النهايات المحبة للماء نحو الماء خارج الخلية ونحو الماء في السيتوبلازم، بينما تتجه النهايات الكارهة للماء إلى الداخل وتتقابل في وسط الغشاء.

### مثال 3: دخول مادة إلى الخلية

- تدخل المادة التي تحتاج إليها الخلية عن طريق بروتين ناقل مناسب.
- يفتح البروتين من الجهة المناسبة، ثم يغلقها ويفتح من الجهة الأخرى.
- يعتمد ذلك على نوع المادة، وحركتها، وتركيزها، واختيار الغشاء.

