# المحاضرة الحادية والعشرون – الشرب الخلوي والإخراج الخلوي

## 🧭 نظرة عامة

تكمل هذه المحاضرة طرائق تبادل المواد عبر الغشاء البلازمي، وتشرح عمليتين تحتاجان إلى نشاط الغشاء:

1. **الشرب الخلوي (Pinocytosis):** إدخال المواد السائلة من خارج الخلية إلى داخلها.
2. **الإخراج الخلوي (Exocytosis):** طرح المواد أو إفرازها من داخل الخلية إلى خارجها.

# أولاً: الشرب الخلوي (Pinocytosis)

## 1. تعريف الشرب الخلوي

الشرب الخلوي هو عملية إدخال خلوي تأخذ بها الخلية مواد سائلة من الوسط الخارجي، إذ ينغلف جزء صغير من الغشاء البلازمي حول السائل ثم ينفصل مكوّناً حويصلة شرب خلوي داخل السيتوبلازم.

- يسمى **Cell Drinking**.
- ينقل مادة سائلة (Liquid Material).
- يكون اتجاه النقل من خارج الخلية إلى داخلها.

## 2. خطوات الشرب الخلوي

1. تلامس المادة السائلة السطح الخارجي للغشاء البلازمي.
2. يتكون انغلاف أو جيب صغير في الغشاء.
3. يحيط الغشاء بكمية من السائل الخارجي.
4. تقترب حافتا الغشاء وتلتحمان.
5. تنفصل الحويصلة عن الغشاء وتدخل السيتوبلازم.
6. تسمى الحويصلة المتكونة **حويصلة الشرب الخلوي (Pinocytic Vesicle)**.

**سلسلة الحفظ:**

مادة سائلة → جيب صغير → إحاطة → التحام → حويصلة داخل الخلية

## 3. لماذا يكون الجيب صغيراً؟

لأن المادة الداخلة سائلة ويمكن أخذ كمية صغيرة منها داخل حويصلة صغيرة، بخلاف البلعمة التي تتعامل مع جسم صلب أكبر وتحتاج إلى انغلاف غشائي أوسع.

## 4. رسم الشرب الخلوي

يجب أن يوضح الرسم بالتسلسل:

1. الغشاء البلازمي بطبقته الفوسفولبيدية الثنائية.
2. المادة السائلة خارج الخلية.
3. تكوّن جيب صغير في الغشاء.
4. إحاطة الجيب بكمية من السائل.
5. انفصال حويصلة صغيرة إلى داخل السيتوبلازم.

تكتب على الرسم المصطلحات الآتية:

- Outside the cell
- Inside the cell
- Plasma membrane
- Liquid material
- Small pocket
- Pinocytic vesicle

## 5. مقارنة الشرب الخلوي بالبلعمة

| الخاصية | الشرب الخلوي (Pinocytosis) | البلعمة (Phagocytosis) |
|---|---|---|
| معنى المصطلح | الشرب الخلوي | الأكل الخلوي |
| نوع المادة | سائلة | صلبة |
| حجم الانغلاف | جيب صغير | جيب كبير |
| الناتج | حويصلة شرب خلوي | فجوة غذائية |
| الاتجاه | من الخارج إلى الداخل | من الخارج إلى الداخل |
| الهضم | لا يكون هو الخطوة الرئيسة للمادة السائلة | تهضم المادة الصلبة بإنزيمات الجسيمات الحالة |

# ثانياً: الإخراج الخلوي (Exocytosis)

## 1. تعريف الإخراج الخلوي

الإخراج الخلوي عملية تقوم فيها الخلية بتحرير مواد من داخلها إلى الوسط الخارجي، وذلك باندماج الحويصلة أو الفجوة الحاوية للمادة مع الغشاء البلازمي ثم إطلاق محتوياتها خارج الخلية.

- يكون اتجاه النقل من داخل الخلية إلى خارجها.
- لا يقتصر على الفضلات؛ فقد تطرح الخلية مواد إفرازية نافعة.

## 2. أهمية الإخراج الخلوي

تؤدي العملية وظيفتين رئيستين:

### أ. طرح بقايا المواد غير المهضومة

- تبقى أجزاء غير مهضومة بعد تغذي بعض الخلايا بالبلعمة.
- توجد هذه البقايا داخل فجوة.
- تنتقل الفجوة نحو الغشاء البلازمي وتطرح بقاياها خارج الخلية.
- الأميبا مثال واضح على ذلك.

### ب. إفراز المواد المصنّعة داخل الخلية

تستعمل الخلايا الإفرازية الإخراج الخلوي لتحرير مواد مثل:

- الهرمونات.
- الإنزيمات.
- البروتينات الإفرازية.
- مواد أخرى بحسب نوع الخلية ووظيفتها.

## 3. خطوات الإخراج الخلوي

1. توجد المادة داخل حويصلة أو فجوة في السيتوبلازم.
2. تتحرك الحويصلة باتجاه الغشاء البلازمي.
3. يقترب غشاء الحويصلة من الغشاء البلازمي.
4. تندمج الطبقتان الغشائيتان مع المحافظة على ترتيب الفوسفولبيدات.
5. تتصل فجوة الحويصلة بالوسط الخارجي.
6. تتحرر المادة إلى خارج الخلية.
7. يصبح غشاء الحويصلة جزءاً من الغشاء البلازمي.

**سلسلة الحفظ:**

حويصلة داخلية → حركة نحو الغشاء → اندماج → انفتاح → تحرير المادة خارج الخلية

## 4. رسم الإخراج الخلوي

يرسم على أربع مراحل مترابطة:

1. حويصلة تحتوي على هرمون أو مادة غير مهضومة داخل الخلية.
2. انتقال الحويصلة نحو الغشاء البلازمي.
3. التصاق غشاء الحويصلة بالغشاء البلازمي واندماجهما.
4. انفتاح الحويصلة وتحرير المادة خارج الخلية.

### ملاحظات مهمة للرسم

- يمثل كل من غشاء الحويصلة والغشاء البلازمي بطبقتين فوسفولبيديتين.
- عند الاندماج تقابل الأجزاء المحبة للماء مثيلاتها، وكذلك الأجزاء الكارهة للماء.
- توضع أسهم تبين حركة الحويصلة وخروج المادة.
- يحدد بوضوح داخل الخلية وخارجها.
- يمكن كتابة **Hormones** للمادة الإفرازية أو **Undigested Food** للبقايا غير المهضومة.

## 5. مقارنة الإدخال الخلوي بالإخراج الخلوي

| الخاصية | الإدخال الخلوي (Endocytosis) | الإخراج الخلوي (Exocytosis) |
|---|---|---|
| اتجاه الحركة | من الخارج إلى الداخل | من الداخل إلى الخارج |
| دور الغشاء | ينغلف حول المادة | يندمج مع غشاء الحويصلة |
| النتيجة | تتكون حويصلة داخلية | تتحرر المادة خارج الخلية |
| أمثلة | البلعمة والشرب الخلوي | إفراز الهرمونات وطرح البقايا |

