# المحاضرة الحادية عشرة – الهيكل الخلوي (Cytoskeleton)

## 🧭 نظرة عامة

الهيكل الخلوي نظام داخلي مميز ينتشر في سيتوبلازم الخلايا حقيقية النواة. يتكون أساساً من الخيوط الدقيقة والنبيبات الدقيقة، ويدعم الخلية ويحافظ على شكلها ويساعد على نقل العضيات والمواد داخلها.

## 1. تعريف الهيكل الخلوي

- الهيكل الخلوي (Cytoskeleton) نظام من التراكيب البروتينية داخل الخلية.
- ينتشر في أنحاء السيتوبلازم ولا يقتصر على موضع واحد.
- يظهر في الخلايا النباتية والحيوانية حقيقية النواة.
- يضم في سياق المحاضرة:
  1. الخيوط الدقيقة (Microfilaments).
  2. النبيبات الدقيقة (Microtubules).
  3. الجسيم المركزي (Centrosome) بوصفه تركيباً منظماً للنبيبات الدقيقة.

## 2. وظائف الهيكل الخلوي العامة

1. إعطاء الدعم للخلية (Support).
2. المحافظة على شكل الخلية (Maintenance of Cell Shape).
3. نقل العضيات والمواد من موضع إلى آخر داخل الخلية (Intracellular Transport).

**سلسلة الحفظ:** دعم ← شكل الخلية ← نقل داخلي

## 3. الخيوط الدقيقة (Microfilaments)

### الوصف

- تراكيب خيطية رفيعة ومستقيمة.
- قطرها أصغر من قطر النبيبات الدقيقة، ويقارب 6 نانومتر وفق المحاضرة.
- شوهدت ودُرست بوضوح في الخلايا أو الألياف العضلية.

### التركيب الكيميائي

- تتكون الخيوط الدقيقة العضلية من بروتينات خاصة.
- من أهمها:
  - الأكتين (Actin).
  - المايوسين (Myosin).

### الوظيفة

- تسهم خيوط الأكتين والمايوسين في التمدد والتقلص أو الارتخاء العضلي.
- ترتبط بصورة أساسية بحركة الألياف العضلية.

## 4. النبيبات الدقيقة (Microtubules)

### الوصف والتركيب

- تراكيب أنبوبية دقيقة داخل الخلية.
- أكبر قطراً من الخيوط الدقيقة، ويقارب قطرها 25 نانومتر.
- تتكون كيميائياً من بروتين خاص يسمى التيوبيولين (Tubulin).

### وظائف النبيبات الدقيقة

1. تحريك الكروموسومات أثناء انقسام الخلية.
2. المساهمة في التنظيم الهيكلي للخلية.
3. نقل العضيات والمواد داخل السيتوبلازم.
4. تكوين ودعم الأهداب والأسواط في الخلايا التي تمتلكها.
5. تكوين الجسيم المركزي بالقرب من النواة في الخلايا الحيوانية وبعض الطحالب والفطريات البدائية وفق سياق المحاضرة.

## 5. الجسيم المركزي (Centrosome)

- تركيب مرتبط بالنبيبات الدقيقة.
- يوجد في سيتوبلازم الخلية الحيوانية بالقرب من النواة.
- يشارك في حركة الكروموسومات أثناء انقسام الخلية.
- تُستكمل تفاصيل تركيبه وآلية عمله في المحاضرة التالية.

