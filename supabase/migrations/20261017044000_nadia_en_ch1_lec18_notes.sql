- يمكن وصف الاتجاه بأنه من محلول قليل المذاب إلى محلول كثير المذاب.
- الأسموزية حالة خاصة من الانتشار.
- السيلوفان يمثل الغشاء الاختياري في التجربة.
- إضافة السكر داخل القمع تقلل تركيز الماء فيه.
- يتحرك الماء من الحوض إلى القمع، فيرتفع مستوى السائل داخل القمع.
- يعاكس الضغط الهيدروستاتيكي المتزايد استمرار دخول الماء.
- تتوقف الحركة الصافية عند توازن القوى، لا عند توقف حركة الجزيئات كلياً.

