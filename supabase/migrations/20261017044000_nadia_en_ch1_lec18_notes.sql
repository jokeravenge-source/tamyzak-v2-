# المحاضرة الثامنة عشرة – الأسموزية والضغط الأسموزي

## 🧭 نظرة عامة

تشرح المحاضرة الأسموزية بوصفها حركة جزيئات الماء عبر غشاء اختياري النفاذية نتيجة اختلاف تركيز الماء بين جهتين. ثم توضح الضغط الأسموزي وتجربة القمع والسيلوفان، وتبين كيف يرتفع الماء داخل القمع حتى يعاكس الضغط الهيدروستاتيكي الحركة الأسموزية الصافية.

## 1. تعريف الأسموزية (Osmosis)

الأسموزية هي الحركة الصافية لجزيئات الماء عبر غشاء اختياري النفاذية من منطقة ذات تركيز ماء أعلى ومذاب أقل إلى منطقة ذات تركيز ماء أقل ومذاب أعلى.

- تختص الأسموزية بحركة الماء.
- تتم عبر غشاء اختياري أو شبه نافذ.
- تحدث عند وجود اختلاف في تركيز الماء بين جانبي الغشاء.
- تعد حالة خاصة من حالات الانتشار.
- لا تحتاج إلى طاقة خلوية مباشرة.

## 2. اتجاه حركة الماء

يمكن حفظ اتجاه الحركة بطريقتين متكافئتين:

- من **تركيز ماء مرتفع** إلى **تركيز ماء منخفض**.
- من **تركيز مذاب منخفض** إلى **تركيز مذاب مرتفع**.

**سلسلة الحفظ:**

ماء أكثر ومذاب أقل → عبر الغشاء → ماء أقل ومذاب أكثر

## 3. لماذا تعد الأسموزية حالة من الانتشار؟

- في الانتشار تتحرك الجزيئات مع تدرج التركيز.
- في الأسموزية تتحرك جزيئات الماء مع تدرج تركيز الماء عبر غشاء اختياري النفاذية.
- لذلك تطبق الفكرة العامة نفسها، لكن الأسموزية تختص بالماء وتشترط وجود الغشاء.

## 4. الضغط الأسموزي (Osmotic Pressure)

- ينشأ الميل إلى دخول الماء عندما يختلف تركيز الماء والمذاب بين جانبي الغشاء.
- الضغط الأسموزي هو الضغط اللازم لمنع الحركة الصافية للماء عبر الغشاء بسبب فرق التركيز.
- كلما ارتفع تركيز المذاب في المحلول ازداد ميل الماء إلى الدخول إليه.

> وجود حركة أسموزية صافية يعني أن هناك فرقاً بين الوسطين يدفع الماء للحركة.

## 5. تجربة إثبات الأسموزية

### الأدوات والمواد

- قمع زجاجي (Glass Funnel).
- حوض زجاجي (Basin).
- غشاء سيلوفان اختياري النفاذية (Cellophane Membrane).
- ماء مقطر (Distilled Water).
- سكر لتكوين محلول سكري.

### إعداد التجربة

1. تغطى الفتحة الواسعة للقمع بغشاء السيلوفان ويثبت بإحكام.
2. يملأ القمع بالماء المقطر.
3. يوضع القمع داخل حوض يحتوي على ماء مقطر.
4. يضبط مستوى الماء في القمع والحوض ليكون متساوياً في البداية.
5. يضاف السكر إلى الماء داخل القمع، فيتكون محلول سكري.

### ماذا تغير بعد إضافة السكر؟

- قبل الإضافة: الماء المقطر على الجانبين، لذلك لا توجد حركة صافية ملحوظة.
- بعد الإضافة: ينخفض تركيز الماء داخل القمع بسبب وجود السكر.
- يصبح تركيز الماء في الحوض أعلى منه داخل القمع.
- يتحرك الماء من الحوض عبر السيلوفان إلى داخل القمع.

### المشاهدة

- ينخفض مستوى الماء في الحوض قليلاً.
- يرتفع مستوى السائل داخل ساق القمع.
- يثبت ذلك مرور الماء عبر الغشاء باتجاه المحلول السكري الأعلى تركيزاً بالمذاب.

## 6. الضغط الهيدروستاتيكي (Hydrostatic Pressure)

- مع دخول الماء إلى القمع يرتفع عمود السائل داخله.
- يولد ارتفاع عمود السائل ضغطاً هيدروستاتيكياً يعاكس دخول المزيد من الماء.
- يزداد هذا الضغط بازدياد ارتفاع عمود السائل.
- تتباطأ الحركة الصافية للماء تدريجياً.
- تتوقف الحركة الصافية عندما يتوازن الضغط الهيدروستاتيكي المعاكس مع القوة الدافعة أسموزياً.

**سلسلة التجربة:**

إضافة السكر → اختلاف التركيز → دخول الماء إلى القمع → ارتفاع عمود السائل → زيادة الضغط الهيدروستاتيكي → اتزان

## 7. معنى توقف الحركة الصافية

- لا يعني الاتزان أن جزيئات الماء توقفت تماماً.
- تستمر الجزيئات بالحركة في الاتجاهين.
- تكون كمية الماء العابرة في اتجاه مساوية تقريباً للكمية العابرة في الاتجاه المعاكس.
- لذلك لا يحدث تغير صافٍ إضافي في مستوى السائل.

## 🔬 مقارنة بين الانتشار والأسموزية

| الخاصية | الانتشار | الأسموزية |
|---|---|---|
| المادة المتحركة | جزيئات أو أيونات | جزيئات الماء فقط |
| اتجاه الحركة | من تركيز المادة الأعلى إلى الأقل | من تركيز الماء الأعلى إلى الأقل |
| الحاجة إلى غشاء | لا يشترط دائماً | يشترط غشاء اختياري/شبه نافذ |
| الطاقة الخلوية | لا تحتاج طاقة مباشرة | لا تحتاج طاقة مباشرة |
| النتيجة | توزيع أكثر اتزاناً للجسيمات | اتزان مائي بين الوسطين |

