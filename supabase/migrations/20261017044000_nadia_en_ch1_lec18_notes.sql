- المستوى متساوٍ في الجانبين.

### بعد إضافة السكر ومرور الوقت

- محلول سكري داخل القمع.
- أسهم حركة الماء من الحوض نحو القمع عبر السيلوفان.
- ارتفاع السائل داخل ساق القمع.
- انخفاض بسيط في مستوى ماء الحوض.

