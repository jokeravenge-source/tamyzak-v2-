# المحاضرة السادسة عشرة – تكوين البويضة والكيس الجنيني (Ovule and Embryo Sac Formation)

## 🧭 نظرة عامة سريعة

تتناول المحاضرة الجزء الأنثوي من الزهرة، ولا سيما المدقة (Pistil) والمبيض (Ovary) والبويضة (Ovule)، ثم تشرح بالتسلسل تكوّن البويضة وتكوين الكيس الجنيني (Embryo Sac). كما تربط بين المصطلحات: المتك (Anther) يمثل الجزء الذكري، في حين يمثل المبيض والبويضة الجزء الأنثوي. وينتهي تكوين الكيس الجنيني بظهور البويضة والخلايا المرافقة والنواتين القطبيتين.

## 📚 المفاهيم والشرح التفصيلي

### 1. تذكير بتكوين المتك وحبوب اللقاح

- يتكون المتك (Anther) من أربعة أكياس حاملة للأبواغ الدقيقة، وتسمى الأكياس البوغية الدقيقة (Microsporangia).
- تحتوي هذه الأكياس على الخلايا الأم للأبواغ الدقيقة (Microspore Mother Cells)، وتكون المجموعة الكروموسومية لها ثنائية (2n).
- تدخل الخلية الأم في الانقسام الاختزالي (Meiosis)، فتنتج أربع أبواغ دقيقة (Microspores).
- تدخل نواة كل بوغ دقيق في انقسام اعتيادي/خيطي (Mitosis)، فتتكون نواتان محاطتان بالسيتوبلازم:
  - النواة التوليدية (Generative Nucleus).
  - النواة الأنبوبية (Tube Nucleus).
- تسمى البنية الناتجة حبة اللقاح (Pollen Grain)، وتمثل المشيج الذكري غير الناضج (Immature Male Gametophyte)، لأنها لم تكوّن الأمشاج الذكرية بعد.

### 2. المدقة والمبيض والبويضة

- المدقة (Pistil) جزء أنثوي من الزهرة، وتتكون من الميسم (Stigma) والقلم/الأسلوب (Style) والمبيض (Ovary).
- الزهرة (Flower) مكوّنة من أوراق متحورة (Modified Leaves) متخصصة لأداء وظيفة التكاثر الجنسي (Sexual Reproduction)، وتختلف عن الأوراق الخضراء التي تؤدي البناء الضوئي (Photosynthesis).
- الأوراق المتحورة التي تكوّن المدقة تسمى الكربلة (Carpel).
- بحسب نوع الزهرة والنبات، قد تتكون المدقة من كربلة واحدة أو من عدة كرابل.
- داخل المبيض توجد البويضات (Ovules)، ولذلك فالمبيض ليس هو البويضة:
  - المبيض (Ovary): الجزء الرئيس من المدقة، ويحتوي على البويضات.
  - البويضة (Ovule): تركيب يوجد داخل المبيض، ويتكون داخله الكيس الجنيني والبيضة.
  - البيضة (Egg): خلية توجد داخل الكيس الجنيني.

### 3. المقابلة بين الجزء الذكري والجزء الأنثوي

- المدقة/المبيض يمثلان المشيجي الكبير أو الأنثوي (Megagametophyte) بحسب سياق المحاضرة.
- المتك (Anther) يمثل المشيجي الصغير أو الذكري (Microgametophyte)، لأن داخله تتكون حبوب اللقاح.
- المبيض (Ovary) يمثل المَبوغ الكبير (Megaspore) أو الجزء المرتبط به.
- البويضة (Ovule) تمثل المئبور الكبير/الكيس البوغي الكبير (Megasporangium)، وهو الكيس الذي تتكون داخله البوغة الكبيرة (Megaspore) ثم الكيس الجنيني.

### 4. بداية تكوّن البويضة

يحدث تكوّن البويضة بالتسلسل الآتي:

1. تبدأ البويضة بنتوء صغير (Small Projection) يخرج من جدار المبيض.
2. يرتبط هذا النتوء بجدار المبيض بواسطة عنق صغير قصير (Short Neck).
3. يسمى النسيج الداخلي للنتوء النوسيلة (Nucellus)، وهو النسيج الذي ستتكون داخله الخلية الأم للبوغة الكبيرة.
4. تبدأ أغلفة البويضة (Integuments) بتغطية النوسيلة.
5. قد يكون عدد الأغلفة طبقة واحدة أو طبقتين أو ثلاث طبقات، ويختلف ذلك بحسب نوع الزهرة والنبات.
6. الأغلفة عبارة عن طبقات من خلايا نسيجية تحيط بالنوسيلة، لكنها لا تغطيها تغطية كاملة.

### 5. النقير (Micropyle)

- عند تغليف النوسيلة بالأغلفة، تترك الأغلفة فتحة صغيرة عند قمة البويضة.
- تسمى هذه الفتحة النقير (Micropyle).
- يكون النقير غير مغطى بالكامل، ويؤدي وظيفة مهمة؛ إذ يبقى جاهزاً لاستقبال أنبوب اللقاح (Pollen Tube).
- يدخل أنبوب اللقاح من خلال النقير للوصول إلى البيضة وإتمام الإخصاب (Fertilization).
- لذلك فإن الأغلفة تمتد من قاعدة البويضة نحو القمة، لكنها لا تلتقي تماماً عند القمة، فتتكون فتحة النقير.

### 6. تكوين الخلية الأم للبوغة الكبيرة

- بعد تكوّن البويضة وتغليف النوسيلة، توجد داخلها خلية معقدة التركيب تسمى الخلية الأم للبوغة الكبيرة (Megaspore Mother Cell).
- تكون نواة هذه الخلية ثنائية المجموعة الكروموسومية (2n).
- تدخل الخلية الأم للبوغة الكبيرة في الانقسام الاختزالي (Meiosis).
- ينتج عن الانقسام الاختزالي أربع بوغات كبيرة (Megaspores)، ولكل واحدة نواة.
- تتحلل ثلاث بوغات كبيرة، وتبقى البوغة الكبيرة الرابعة فقط.
- البوغة الكبيرة الباقية هي التي تكمل نموها وتكوّن الكيس الجنيني.

### 7. تكوين الكيس الجنيني

بعد بقاء البوغة الكبيرة الرابعة:

1. تدخل نواة البوغة الكبيرة الباقية في ثلاثة انقسامات خيطية متتالية (Three Mitotic Divisions).
2. لا ينقسم السيتوبلازم مباشرة إلى خلايا مستقلة؛ بل تبقى النوى داخل تركيب خلوي واحد.
3. بعد الانقسامات الثلاثة تتكون ثماني نوى (Eight Nuclei).
4. لا يسمى التركيب بعد ذلك بوغة كبيرة؛ لأن البوغة الكبيرة كانت تحتوي على نواة واحدة، أما التركيب الجديد فيحتوي على ثماني نوى، ولذلك يسمى الكيس الجنيني (Embryo Sac).

### 8. ترتيب النوى الثماني داخل الكيس الجنيني

تتوزع النوى الثماني في ثلاث مناطق:

- ثلاث نوى قرب النقير (Micropyle)، أي في الطرف القريب من فتحة النقير.
- ثلاث نوى في الطرف المقابل للنقير، وتسمى النوى المقابلة (Antipodal Nuclei).
- نواتان في مركز الكيس الجنيني، وتسمى النواتين القطبيتين (Polar Nuclei).

### 9. تحوّل النوى إلى خلايا وتكوين جهاز البيضة

- النوى الثلاث القريبة من النقير تتحاط بالسيتوبلازم والأغشية، فتتحول إلى ثلاث خلايا.
- إحدى هذه الخلايا هي البيضة (Egg Cell)، والخليتان الأخريان هما الخليتان المساعدتان/السمتيتان (Synergids).
- النوى الثلاث الموجودة في الجهة المقابلة للنقير تتحول إلى ثلاث خلايا مقابلة (Antipodal Cells).
- النواتان القطبيتان في المركز لا تتحاطان بأغشية مستقلة ولا تتحولان إلى خليتين منفصلتين؛ بل تبقيان نواتين قطبيتين (Polar Nuclei) داخل الخلية المركزية.
- لذلك يتكون الكيس الجنيني من ست خلايا، إضافة إلى نواتين قطبيتين.

### 10. شكل الكيس الجنيني وموقعه

- يكون الكيس الجنيني تركيباً منحنياً أو مقوساً (Curved Structure) وقريباً من النقير.
- قد يأخذ الكيس الجنيني مواضع أو أشكالاً أخرى بحسب الرسم أو نوع النبات، لكن التركيب الذي ركزت عليه المحاضرة هو التركيب المنحني القريب من النقير.
- يصبح الكيس الجنيني هو المشيجي الأنثوي الناضج (Mature Female Gametophyte) بعد اكتمال تكوين البيضة والخلايا المرافقة والنوى القطبية.

## 📖 التعريفات والمصطلحات

- **المدقة (Pistil):** الجزء الأنثوي من الزهرة، ويتكون من الميسم والقلم والمبيض.
- **المبيض (Ovary):** الجزء الرئيس من المدقة، وتوجد داخله البويضات.
- **البويضة (Ovule):** تركيب يوجد داخل المبيض، وتحتوي داخله النوسيلة والكيس الجنيني.
- **البيضة (Egg Cell):** خلية أنثوية توجد داخل الكيس الجنيني.
- **الكربلة (Carpel):** ورقة متحورة تكوّن المدقة، وقد تكون المدقة مكوّنة من كربلة واحدة أو عدة كرابل.
- **المشيجي الكبير/الأنثوي (Megagametophyte):** الجزء الأنثوي المرتبط بالمبيض والبويضة في سياق المقارنة مع الجزء الذكري.
- **المشيجي الصغير/الذكري (Microgametophyte):** الجزء الذكري المرتبط بالمتك وحبوب اللقاح.
- **الكيس البوغي الكبير (Megasporangium):** الكيس الموجود داخل البويضة الذي تتكون داخله البوغة الكبيرة.
- **النوسيلة (Nucellus):** النسيج الداخلي في البويضة، وتحيط به أغلفة البويضة.
- **أغلفة البويضة (Integuments):** طبقات من الخلايا تحيط بالنوسيلة، وقد تكون طبقة أو طبقتين أو ثلاثاً.
- **النقير (Micropyle):** فتحة صغيرة عند قمة البويضة، تتركها الأغلفة لاستقبال أنبوب اللقاح.
- **الخلية الأم للبوغة الكبيرة (Megaspore Mother Cell):** خلية ثنائية المجموعة الكروموسومية تدخل الانقسام الاختزالي لتنتج أربع بوغات كبيرة.
- **البوغة الكبيرة (Megaspore):** إحدى الخلايا الناتجة من الانقسام الاختزالي للخلية الأم، وتبقى واحدة منها لتكوين الكيس الجنيني.
- **الكيس الجنيني (Embryo Sac):** التركيب الناتج من انقسامات نواة البوغة الكبيرة الباقية، ويضم ثماني نوى أولاً ثم ست خلايا ونواتين قطبيتين.
- **الخلايا المساعدة/السمتية (Synergids):** خليتان قرب النقير ترافقان البيضة ضمن جهاز البيضة.
- **الخلايا المقابلة (Antipodal Cells):** ثلاث خلايا تقع في الطرف المقابل للنقير.
- **النواتان القطبيتان (Polar Nuclei):** نواتان تقعان في مركز الكيس الجنيني ولا تتحولان إلى خليتين منفصلتين.
- **أنبوب اللقاح (Pollen Tube):** تركيب يدخل من النقير للوصول إلى البيضة وإتمام الإخصاب.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة تكوين البوغات الكبيرة

خلية أم للبوغة الكبيرة واحدة (2n) ⟶ انقسام اختزالي (Meiosis) ⟶ أربع بوغات كبيرة (n) ⟶ تتحلل ثلاث، وتبقى واحدة.

### قاعدة تكوين النوى الثماني

بوغة كبيرة باقية ذات نواة واحدة ⟶ ثلاثة انقسامات خيطية متتالية ⟶ ثماني نوى.

### قاعدة توزيع الكيس الجنيني

ثلاث نوى قرب النقير + ثلاث نوى في الجهة المقابلة + نواتان قطبيتان في المركز = ثماني نوى.

### قاعدة عدد مكونات الكيس الجنيني

ثلاث خلايا قرب النقير + ثلاث خلايا مقابلة + نواتان قطبيتان = ست خلايا ونواتان قطبيتان.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: عدد البوغ الكبيرة الناتجة

**المعطيات:** خلية أم للبوغة الكبيرة واحدة تدخل الانقسام الاختزالي.

**القانون:** الانقسام الاختزالي لخلية أم واحدة ينتج أربع بوغات كبيرة.

**الحل:**

1. تبدأ خلية أم للبوغة الكبيرة واحدة.
2. تدخل الانقسام الاختزالي.
3. تنتج أربع بوغات كبيرة.
4. تتحلل ثلاث بوغات كبيرة.

**الناتج النهائي:** تبقى بوغة كبيرة واحدة فعالة لتكوين الكيس الجنيني.

### مثال 2: عدد النوى بعد الانقسامات الخيطية

**المعطيات:** بوغة كبيرة واحدة باقية، ونواتها تدخل ثلاثة انقسامات خيطية متتالية.

**القانون:** كل انقسام خيطي يضاعف عدد النوى: 1 ⟶ 2 ⟶ 4 ⟶ 8.

**الناتج النهائي:** تتكون ثماني نوى داخل الكيس الجنيني.

### مثال 3: عدد الخلايا والنوى في الكيس الجنيني

**المعطيات:** كيس جنيني مكتمل يحتوي على ثلاث خلايا قرب النقير، وثلاث خلايا مقابلة، ونواتين قطبيتين.

**خطوات الحل:**

1. الخلايا القريبة من النقير = 3.
2. الخلايا المقابلة = 3.
3. النواتان القطبيتان = 2، ولا تعدّان خليتين مستقلتين.
4. مجموع الخلايا = 3 + 3 = 6 خلايا.
5. عدد النوى الكلي في التركيب = 6 نوى خلوية + نواتان قطبيتان = 8 نوى.

**الناتج النهائي:** الكيس الجنيني يحتوي على **6 خلايا و2 نواتين قطبيتين**، أي **8 نوى بالمجموع**.

## ⚠️ تنبيهات وأخطاء شائعة (ملاحظات وزارية)

- **مهم جداً:** المدقة (Pistil) ليست هي المبيض فقط؛ بل تضم الميسم والقلم والمبيض.
- **مهم للفراغات:** الأوراق المتحورة التي تكوّن المدقة تسمى الكربلة (Carpel).
- **مهم:** المبيض (Ovary) يحتوي على البويضات (Ovules)، ولا يصح مساواة المبيض بالبويضة أو بالبيضة.
- انتبه إلى الفرق بين **المبيض (Ovary)** و**البويضة (Ovule)** و**البيضة (Egg Cell)**؛ فهي ثلاثة تراكيب مختلفة.
- **مهم جداً:** المبيض يمثل الجزء/المشيجي الكبير (Mega)، بينما المتك يمثل الجزء/المشيجي الصغير (Micro) في المقارنة الواردة بالمحاضرة.
- البويضة تمثل الكيس البوغي الكبير (Megasporangium)، وفي داخله تتكون البوغة الكبيرة.
- تبدأ البويضة بنتوء صغير يخرج من جدار المبيض، ثم يثبت بعنق صغير قصير.
- أغلفة البويضة قد تكون طبقة واحدة أو طبقتين أو ثلاث طبقات بحسب نوع النبات.
- الأغلفة لا تغلق قمة البويضة بالكامل؛ إذ تترك فتحة النقير (Micropyle).
- **مهم وزارياً:** النقير هو الفتحة التي يدخل منها أنبوب اللقاح للوصول إلى البيضة.
- الخلية الأم للبوغة الكبيرة (Megaspore Mother Cell) ثنائية المجموعة الكروموسومية، أما البوغات الكبيرة الناتجة فهي أحادية المجموعة.
- من البوغات الكبيرة الأربع تتحلل ثلاث، وتبقى الرابعة فقط.
- لا تدخل الخلية الأم للبوغة الكبيرة في الانقسام الخيطي أولاً؛ بل تدخل الانقسام الاختزالي لتكوين أربع بوغات كبيرة.
- بعد بقاء البوغة الكبيرة الرابعة، تدخل نواتها في ثلاثة انقسامات خيطية لتكوين ثماني نوى.
- **تنبيه مهم:** النوى الثماني تتكون داخل خلية واحدة في البداية، ولا يعني ذلك وجود ثماني خلايا مباشرة.
- ثلاث نوى قرب النقير، وثلاث نوى في الجهة المقابلة، ونواتان في المركز.
- النواتان المركزيتان لا تتحولان إلى خليتين؛ بل تبقيان نواتين قطبيتين.
- عدد مكونات الكيس الجنيني النهائي هو ست خلايا ونواتان قطبيتان، وليس ثماني خلايا.
- تكوين الكيس الجنيني وتسلسل مراحله موضوع مهم ووزاري مكرر، ويجب حفظه بالتسلسل.

