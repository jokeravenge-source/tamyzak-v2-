# المحاضرة العشرون – النقل الفعال والبلعمة

## 🧭 نظرة عامة

تشرح المحاضرة طريقتين لنقل المواد عبر الغشاء البلازمي. الأولى هي النقل الفعال، الذي ينقل الأيونات أو الجزيئات عكس تدرج التركيز باستعمال ATP وبروتينات ناقلة. والثانية هي البلعمة، التي تبتلع بها بعض الخلايا مواد صلبة كبيرة وتكوّن حولها فجوة غذائية تهضمها إنزيمات الجسيمات الحالة.

# أولاً: النقل الفعال (Active Transport)

## 1. تعريف النقل الفعال

النقل الفعال هو انتقال الأيونات أو الجزيئات عبر الغشاء البلازمي من منطقة ذات تركيز منخفض إلى منطقة ذات تركيز مرتفع، بمساعدة بروتينات ناقلة وباستهلاك طاقة ATP.

**سلسلة الحفظ:**

تركيز منخفض → بروتين ناقل + ATP → تركيز مرتفع

## 2. لماذا يسمى نقلاً فعالاً؟

- تتحرك المادة عكس تدرج التركيز الطبيعي.
- لا تستطيع المادة إتمام الانتقال بالانتشار وحده.
- تحتاج العملية إلى طاقة.
- تحتاج إلى بروتين ناقل متخصص داخل الغشاء البلازمي.

## 3. المواد والخلايا التي تستعمله

- ينقل الأيونات والجزيئات التي تحتاج إليها الخلية.
- لا يعد الماء المثال الرئيس؛ فحركة الماء ترتبط بالأسموزية.
- تختلف الحاجة إلى النقل الفعال بحسب نوع الخلية ووظيفتها.
- من الخلايا التي تعتمد عليه بوضوح:
  - الخلايا العصبية.
  - الخلايا العضلية.
  - الخلايا التي تجمع أيونات معينة رغم ارتفاع تركيزها الداخلي.
- ذُكر الحديد مثالاً لمادة قد تحتاج بعض الخلايا إلى جمعها ضد تدرج التركيز.

## 4. متطلبات النقل الفعال

### أ. البروتينات الناقلة (Carrier Proteins)

- توجد داخل الطبقة الثنائية للغشاء البلازمي.
- تمتد عبر الغشاء لتصل بين سطحه الخارجي والداخلي.
- تمتلك مواقع ارتباط نوعية للأيونات أو الجزيئات.
- تستطيع تغيير شكلها والتحرك وظيفياً عبر الغشاء لنقل المادة.
- تلف هذه البروتينات أو فقدانها يعطل عملية النقل المرتبطة بها.

### ب. الطاقة

- تحتاج العملية إلى ATP.
- تنتج المايتوكوندريا معظم ATP المستعمل في الخلايا حقيقية النواة.
- تستخدم الطاقة لتغيير شكل البروتين الناقل ونقل المادة عكس تدرجها.

## 5. خطوات النقل الفعال

1. يرتبط الأيون أو الجزيء بالموقع المخصص على البروتين الناقل.
2. توفر الخلية طاقة ATP.
3. يتغير شكل البروتين الناقل ويتجه موقع الارتباط نحو السطح الآخر للغشاء.
4. تنفصل المادة عن الناقل وتتحرر في الجهة المقابلة.
5. يعود البروتين الناقل إلى حالته الأصلية ليكرر العملية.

## 6. رسم النقل الفعال

يجب أن يوضح الرسم:

- الطبقتين الفوسفولبيديتين للغشاء.
- الوسط خارج الخلية وداخلها.
- تركيزاً منخفضاً في جهة وتركيزاً مرتفعاً في الجهة المقابلة.
- بروتيناً ناقلاً ممتداً عبر الغشاء.
- ارتباط المادة بالناقل.
- رمز ATP أو الطاقة.
- تغير شكل الناقل وإطلاق المادة في الجهة الأخرى.
- سهماً يبين النقل من التركيز المنخفض إلى المرتفع.

## 🔬 مقارنة بين النقل السلبي والنقل الفعال

| الخاصية | النقل السلبي | النقل الفعال |
|---|---|---|
| اتجاه الحركة | مع تدرج التركيز | عكس تدرج التركيز |
| الطاقة | لا يحتاج ATP مباشرة | يحتاج ATP |
| البروتين الناقل | قد لا يحتاج أو قد يستعمل قنوات | يحتاج ناقلاً متخصصاً |
| مثال | الانتشار والأسموزية | تجميع الأيونات ضد تدرجها |

# ثانياً: البلعمة (Phagocytosis)

## 1. تعريف البلعمة

البلعمة شكل من أشكال الإدخال الخلوي، تحيط فيه الخلية بمادة صلبة كبيرة بواسطة الغشاء البلازمي ثم تدخلها في حويصلة أو فجوة داخل السيتوبلازم.

- تسمى أحياناً الأكل الخلوي (Cell Eating).
- تختص بالمواد الصلبة، وليست بالسوائل.

## 2. أمثلة الخلايا التي تقوم بالبلعمة

### الأميبا

- تستعمل البلعمة للحصول على الغذاء.
- تحيط بالمادة الغذائية الصلبة ثم تهضمها داخل فجوة غذائية.

### خلايا الدم البيضاء

- تستعمل البلعمة للدفاع عن الجسم وتنظيف الأنسجة.
- تبتلع:
  - الجراثيم والميكروبات.
  - بقايا الخلايا الميتة.
  - بعض الجسيمات الغريبة.

## 3. خطوات البلعمة

1. تلامس المادة الصلبة سطح الخلية.
2. يحدث انغلاف أو جيب في الغشاء البلازمي حول المادة.
3. يمتد الغشاء ليحيط بالمادة من الجهات المختلفة.
4. تنفصل القطعة الغشائية إلى داخل السيتوبلازم.
5. تتكون فجوة غذائية (Food Vacuole/Phagosome) تحتوي على المادة.
6. يلتحم جسيم حال بالفجوة.
7. تطلق الإنزيمات الحالة داخل الفجوة.
8. تهضم المادة وتستفيد الخلية من النواتج أو تتخلص من البقايا.

**سلسلة الحفظ:**

تلامس → انغلاف → إحاطة → انفصال → فجوة غذائية → جسيم حال → هضم

## 4. رسم البلعمة

يرسم التسلسل في مراحل:

1. مادة صلبة خارج الخلية.
2. انغلاف الغشاء البلازمي وتكوّن الجيب.
3. إحاطة الغشاء بالمادة.
4. انفصال الحويصلة داخل السيتوبلازم.
5. تكوّن الفجوة الغذائية.
6. التحام الجسيم الحال وإطلاق الإنزيمات.

يجب المحافظة على تمثيل الغشاء بوصفه طبقتين فوسفولبيديتين في الرسم التفصيلي.

## 5. العلاقة بين البلعمة والجسيمات الحالة

- البلعمة تدخل المادة الصلبة إلى الخلية لكنها لا تكمل هضمها وحدها.
- الجسيم الحال يزود الفجوة بالإنزيمات المحللة.
- يؤدي اتحاد الفجوة مع الجسيم الحال إلى هضم المادة الداخلة.

## ⚠️ نقاط مهمة للحفظ

- النقل الفعال انتقال من التركيز المنخفض إلى المرتفع.
- يحتاج النقل الفعال إلى ATP وبروتينات ناقلة.
- توجد البروتينات الناقلة داخل الغشاء البلازمي وتستطيع تغيير شكلها.
- ترتبط المادة بالناقل، ثم يتحرك الناقل وظيفياً، ثم يحررها في الجهة الأخرى.
- البلعمة إدخال خلوي للمواد الصلبة.
- الأميبا تستخدمها للتغذية، وخلايا الدم البيضاء تستخدمها للدفاع والتنظيف.
- يتكون جيب غشائي ثم فجوة غذائية حول المادة المبتلعة.
- تهضم الجسيمات الحالة محتويات الفجوة بإنزيماتها.

## 🧠 الخلاصة

ينقل النقل الفعال المواد عكس تدرج التركيز بواسطة بروتينات ناقلة وطاقة ATP، مما يسمح للخلية بجمع مواد تحتاج إليها حتى لو كان تركيزها الداخلي مرتفعاً. أما البلعمة فتدخل المواد الصلبة الكبيرة عن طريق إحاطتها بالغشاء وتكوين فجوة تهضم محتوياتها الجسيمات الحالة.

