# سابعاً: ارتباط التركيب بالوظيفة في الأغشية

استُعملت المايتوكوندريا مثالاً لفهم أن اختلاف أجزاء الغشاء يرتبط باختلاف الوظيفة:

| الجزء | الصفة أو الوظيفة الأساسية |
|---|---|
| الغشاء الخارجي | يشارك في تنظيم تبادل المواد بين المايتوكوندريا والسيتوبلازم |
| الغشاء الداخلي | كثير الانثناءات ويكوّن الأعراف (Cristae) |
| الأعراف | تزيد مساحة السطح المتاحة للتفاعلات المرتبطة بإنتاج الطاقة |
| الحشوة (Matrix) | تحتوي مواد وإنزيمات تشارك في التنفس الخلوي |

**الفكرة العامة:** اختلاف تركيب الغشاء ومساحة سطحه يخدم الوظيفة التي يؤديها العضو الخلوي.

