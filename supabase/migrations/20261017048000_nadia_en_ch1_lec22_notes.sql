# المحاضرة الثانية والعشرون – مراجعة تبادل المواد عبر الغشاء البلازمي

## 🧭 طبيعة المحاضرة

هذه محاضرة مراجعة وأسئلة تطبيقية لموضوع الغشاء البلازمي وتبادل المواد. تركز على النفاذية الاختيارية، الأسموزية، تجربة الضغط الأسموزي، أنواع المحاليل، النقل الفعّال، وأصل أغشية الحويصلات والفجوات.

# أولاً: النفاذية الاختيارية للغشاء البلازمي

## 1. معنى النفاذية الاختيارية

الغشاء البلازمي **اختياري النفاذية (Selectively Permeable)**؛ أي إنه يسمح بمرور بعض المواد ويحد من مرور مواد أخرى.

- لا تدخل جميع المواد الموجودة خارج الخلية بنسبة متساوية.
- يعتمد المرور على حجم المادة وطبيعتها وحاجة الخلية إليها.
- قد تحتاج بعض المواد إلى بروتينات ناقلة أو قنوات خاصة.
- تحافظ هذه الخاصية على ثبات البيئة الداخلية للخلية.

## 2. أهمية تبادل المواد

يمثل تبادل المواد أساساً للعمليات الخلوية، لأنه يساعد الخلية على:

1. إدخال الماء والمواد الغذائية والأيونات اللازمة.
2. طرح الفضلات والمواد الزائدة.
3. تنظيم تراكيز المواد داخل الخلية.
4. توفير مواد البناء اللازمة لتكوين البروتينات والدهون والكربوهيدرات وغيرها من مكونات المادة الحية.

# ثانياً: الأسموزية (Osmosis)

## 1. الفكرة الأساسية

الأسموزية هي حركة الماء عبر غشاء اختياري النفاذية من منطقة ذات تركيز ماء مرتفع وتركيز مذاب منخفض إلى منطقة ذات تركيز ماء منخفض وتركيز مذاب مرتفع.

**قاعدة مهمة:**

عند ذكر الأسموزية، تكون المادة المتحركة هي **الماء**.

## 2. العلاقة بين الماء والمذاب

- زيادة تركيز المذاب تعني انخفاض التركيز النسبي للماء.
- انخفاض تركيز المذاب يعني ارتفاع التركيز النسبي للماء.
- لذلك يتحرك الماء باتجاه المحلول الأعلى تركيزاً بالمذاب.

# ثالثاً: تجربة الضغط الأسموزي

تتكون التجربة من غشاء اختياري النفاذية يفصل بين وسطين، مع أنبوب يسمح بملاحظة تغير مستوى السائل.

## الحالة الأولى: ماء في الجهتين

- يكون الوسطان متماثلين في التركيب.
- تتحرك جزيئات الماء في الاتجاهين.
- لا توجد حركة صافية للماء ولا يتغير المستوى بصورة دائمة.
- لا يتكون فرق أسموزي مؤثر بين الجهتين.

## الحالة الثانية: إضافة السكر إلى إحدى الجهتين

1. تصبح الجهة المحتوية على السكر أعلى تركيزاً بالمذاب وأقل تركيزاً بالماء.
2. يتحرك الماء عبر الغشاء نحو محلول السكر.
3. يرتفع مستوى السائل في الأنبوب من جهة المحلول الأعلى تركيزاً.
4. يؤدي ارتفاع عمود السائل إلى توليد ضغط هيدروستاتيكي معاكس للحركة الأسموزية.
5. تستمر الحركة الصافية حتى يتعادل تأثير الضغط الهيدروستاتيكي مع الضغط الأسموزي.
6. عند التعادل يتوقف التغير الصافي في مستوى السائل، مع استمرار الحركة الجزيئية في الاتجاهين.

**سلسلة الحفظ:**

إضافة مذاب → فرق في تركيز الماء → أسموزية → ارتفاع عمود السائل → ضغط هيدروستاتيكي → اتزان

## 3. الضغط الأسموزي والضغط الهيدروستاتيكي

| المصطلح | المعنى في التجربة |
|---|---|
| الضغط الأسموزي (Osmotic Pressure) | القوة المرتبطة بميل الماء للانتقال نحو المحلول الأعلى تركيزاً بالمذاب |
| الضغط الهيدروستاتيكي (Hydrostatic Pressure) | الضغط الناتج عن ارتفاع عمود السائل، ويعاكس استمرار دخول الماء |
| حالة الاتزان | تتساوى التأثيرات المتعاكسة فلا تحدث حركة صافية للماء |

# رابعاً: أنواع المحاليل وتأثيرها في الخلية

عند تحديد نوع المحلول يجب الانتباه إلى أن الوصف يكون بمقارنة تركيز المذاب خارج الخلية بتركيزه داخلها.

## 1. المحلول متساوي التركيز (Isotonic Solution)

- تركيز المذاب خارج الخلية مساوٍ لتركيزه داخلها.
- يتحرك الماء في الاتجاهين بالمعدل نفسه.
- لا توجد حركة صافية للماء.
- يبقى حجم الخلية مستقراً.

## 2. المحلول مفرط التركيز (Hypertonic Solution)

- تركيز المذاب خارج الخلية أعلى منه داخلها.
- يكون تركيز الماء خارج الخلية أقل.
- يخرج الماء من الخلية.
- تفقد الخلية الماء وينخفض حجمها.

## 3. المحلول منخفض التركيز (Hypotonic Solution)

- تركيز المذاب خارج الخلية أقل منه داخلها.
- يكون تركيز الماء خارج الخلية أعلى.
- يدخل الماء إلى الخلية.
- يزداد حجم الخلية، وقد تتأثر إذا دخلت كمية كبيرة من الماء.

## 🔑 طريقة سريعة لحل الأسئلة

1. حدد هل المعطى يتحدث عن **المذاب** أم **الماء**.
2. قارن خارج الخلية بداخلها.
3. يتحرك الماء من تركيز الماء الأعلى إلى الأقل.
4. إذا خرج الماء انكمشت الخلية، وإذا دخل إليها ازداد حجمها.

# خامساً: مراجعة النقل الفعّال

## لماذا يعد النقل الفعّال خاصية للخلايا الحية؟

لأن العملية تحتاج إلى:

- بروتينات ناقلة متخصصة داخل الغشاء البلازمي.
- طاقة على صورة ATP.
- نشاط أيضي خلوي مستمر لتوفير الطاقة وتشغيل الناقلات.

توفر المايتوكوندريا معظم ATP اللازم، ولهذا يظهر النقل الفعّال بوضوح في الخلايا الحية ذات النشاط العالي.

**سلسلة الحفظ:**

ناقل متخصص + ATP → نقل المادة عكس تدرج التركيز

