6. خط استواء الخلية بصورة واضحة.

# ثانياً: الطور الانفصالي (Anaphase)

الطور الانفصالي هو المرحلة الثالثة من الانقسام الخيطي، واسمه يدل على الحدث الرئيس فيه: انفصال الكروماتيدين الشقيقين.

## 1. انقسام السنترومير وانفصال الكروماتيدين

- ينفصل الكروماتيدان الشقيقان عند منطقة السنترومير.
- بمجرد الانفصال لا يسمى كل جزء كروماتيداً شقيقاً، بل يصبح **كروموسوماً بنتياً مستقلاً**.

**Sister Chromatids → Separation → Daughter Chromosomes**

## 2. انتقال الكروموسومات إلى القطبين

- تتحرك مجموعة من الكروموسومات البنتية نحو أحد قطبي الخلية.
- تتحرك المجموعة المماثلة نحو القطب المقابل.
- تحصل كل جهة على مجموعة كاملة ومتماثلة من الكروموسومات.
- يضمن ذلك حصول الخليتين البنتين لاحقاً على العدد والنوع نفسيهما من الكروموسومات.

## رسم الطور الانفصالي

يجب أن يظهر:

1. انفصال السنتروميرات.
2. تحول كل كروماتيد سابق إلى كروموسوم بنتي.
3. مجموعتين متماثلتين تتحركان في اتجاهين متعاكسين.
4. ألياف المغزل مرتبطة بالكروموسومات.
5. وجود كل جسم مركزي عند أحد القطبين.
6. أسهماً توضح اتجاه الحركة نحو القطبين.

# ثالثاً: آلية حركة الكروموسومات

تعرض المحاضرة تفسيرين مقترحين لكيفية نقل ألياف المغزل للكروموسومات نحو القطبين.

## التفسير الأول: انكماش ألياف المغزل

- تستعمل ألياف المغزل طاقة ATP.
- تقصر أو تنكمش الألياف.
- يؤدي قصرها إلى سحب الكروموسومات المرتبطة بها نحو القطبين.

**ATP → Spindle Fiber Shortening → Chromosome Pulling → Cell Poles**

## التفسير الثاني: انزلاق الكروموسومات

- تعمل ألياف المغزل كمسارات للحركة.
- تنزلق الكروموسومات على امتداد هذه الألياف.
- تستمر الحركة حتى تصل الكروموسومات إلى قطبي الخلية.

**Spindle Fibers as Tracks → Chromosome Sliding → Cell Poles**

