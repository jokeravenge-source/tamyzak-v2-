# المحاضرة الثالثة والعشرون – التحلل السكري والتخمر

## 🧭 نظرة عامة

تشرح المحاضرة مصير جزيء الجلوكوز خلال **التحلل السكري (Glycolysis)**، ثم تتابع مصير حامض البيروفيك في غياب الأوكسجين من خلال نوعين من التخمر:

1. التخمر الكحولي (Alcoholic Fermentation).
2. تخمر حامض اللاكتيك (Lactic Acid Fermentation).

# أولاً: التحلل السكري (Glycolysis)

## 1. مكان حدوثه

يحدث التحلل السكري داخل **السيتوبلازم**، وتساعد إنزيمات موجودة فيه على إتمام سلسلة التفاعلات.

## 2. الهدف العام

يتحول جزيء واحد من الجلوكوز إلى جزيئين من حامض البيروفيك، مع إنتاج ATP وحوامل هيدروجين مختزلة يشار إليها في المنهج بـ `2H`.

## 3. مرحلة استهلاك الطاقة

1. يدخل الجلوكوز إلى الخلية.
2. تضاف إليه مجموعة فوسفات لحبسه داخل الخلية، ويستهلك لذلك جزيء ATP واحد.
3. تتحول السلسلة المغلقة للجلوكوز إلى سلسلة مفتوحة حتى تصبح قابلة لسلسلة التفاعلات اللاحقة.
4. تضاف مجموعة فوسفات أخرى مع استهلاك جزيء ATP ثانٍ.

**إجمالي ATP المستهلك = 2 ATP**

## 4. مرحلة الانشطار

- ينشطر المركب السكري سداسي الكربون إلى مركبين ثلاثيي الكربون.
- يظهر في المخطط أولاً:
  - فوسفوكليسر ألديهايد (Phosphoglyceraldehyde).
  - داي هيدروكسي أسيتون فوسفات (Dihydroxyacetone Phosphate).
- يتحول المركب الثاني لاحقاً إلى فوسفوكليسر ألديهايد، لذلك تستمر التفاعلات على جزيئين منه.

## 5. مرحلة إنتاج الطاقة

تتعرض جزيئتا فوسفوكليسر ألديهايد لسلسلة من التفاعلات، وينتج عنها:

- جزيئان من حامض البيروفيك.
- `2H` بحسب ترميز المنهج.
- 4 ATP إجمالاً.

## 6. حساب صافي ATP

| البيان | عدد جزيئات ATP |
|---|---:|
| ATP المنتج | 4 |
| ATP المستهلك | 2 |
| صافي الربح المباشر | 2 |

**صافي ATP = 4 − 2 = 2 ATP**

وبحسب حساب الطاقة المعتمد في المحاضرة، يعطي كل `2H` ما يعادل 3 ATP؛ لذلك يمثل جزيئا `2H` ما يعادل 6 ATP عند دخولهما مسار إنتاج الطاقة الهوائي.

## 7. النواتج النهائية للتحلل السكري

من جزيء جلوكوز واحد ينتج:

- 2 Pyruvic Acid.
- 2H.
- صافي 2 ATP مباشرة.

**سلسلة الحفظ:**

Glucose → Glycolysis → 2 Pyruvic Acid + 2H + Net 2 ATP

