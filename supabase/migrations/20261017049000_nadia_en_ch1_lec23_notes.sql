# ثالثاً: التنفس اللاهوائي والتخمر

## 1. تعريف عام

التخمر مسار لا هوائي تستفيد منه الخلايا أو الكائنات عند غياب الأوكسجين، ولا يتضمن دورة كربس.

- لا يحتاج إلى الأوكسجين.
- يحدث في السيتوبلازم.
- يبدأ بالجلوكوز والتحلل السكري.
- صافي الطاقة المباشرة الناتجة من جزيء جلوكوز واحد هو 2 ATP.

## 2. أنواع التخمر

1. التخمر الكحولي.
2. تخمر حامض اللاكتيك.

# رابعاً: التخمر الكحولي (Alcoholic Fermentation)

## 1. أمثلة حدوثه

يحدث في:

- الخمائر (Yeasts).
- بعض النباتات الخضراء عند وجودها في ظروف يغيب عنها الأوكسجين.
- بعض أنواع البكتيريا.

## 2. خطوات التخمر الكحولي

### الخطوة الأولى: التحلل السكري

Glucose → 2 Pyruvic Acid + 2H + Net 2 ATP

### الخطوة الثانية: نزع ثاني أوكسيد الكربون

- يفقد كل جزيء من حامض البيروفيك جزيئاً من CO₂.
- بما أن الناتج جزيئان من حامض البيروفيك، يتحرر **2CO₂**.
- يتكون جزيئان من الأسيتالديهايد (Acetaldehyde).

2 Pyruvic Acid → 2 Acetaldehyde + 2CO₂

### الخطوة الثالثة: الاختزال

- يختزل الأسيتالديهايد بواسطة `2H` الناتجة من التحلل السكري.
- يتكون جزيئان من الكحول الأثيلي (Ethyl Alcohol/Ethanol).

2 Acetaldehyde + 2H → 2 Ethyl Alcohol

## 3. المحصلة

Glucose → 2 Ethyl Alcohol + 2CO₂ + Net 2 ATP

## 4. أسئلة الأصل المهمة

| السؤال | الجواب |
|---|---|
| ما أصل حامض البيروفيك؟ | الجلوكوز بعد التحلل السكري |
| ما أصل الأسيتالديهايد؟ | حامض البيروفيك بعد نزع CO₂ |
| ما أصل الكحول الأثيلي؟ | الأسيتالديهايد بعد اختزاله بـ 2H |
| ما مقدار صافي الطاقة؟ | 2 ATP |

# خامساً: تخمر حامض اللاكتيك (Lactic Acid Fermentation)

## 1. أمثلة حدوثه

يحدث في:

- الخلايا العضلية عند الإجهاد أو الإعياء العضلي ونقص وصول الأوكسجين.
- بعض أنواع البكتيريا.

## 2. خطوات تخمر حامض اللاكتيك

### الخطوة الأولى: التحلل السكري

Glucose → 2 Pyruvic Acid + 2H + Net 2 ATP

### الخطوة الثانية: الاختزال المباشر

- لا تحدث خطوة نزع CO₂.
- لا يتكون الأسيتالديهايد.
- يختزل حامض البيروفيك مباشرة بواسطة `2H`.
- يتكون جزيئان من حامض اللاكتيك.

2 Pyruvic Acid + 2H → 2 Lactic Acid

## 3. المحصلة

Glucose → 2 Lactic Acid + Net 2 ATP

## 4. سؤال الأصل المهم

**ما أصل حامض اللاكتيك؟**

أصله حامض البيروفيك بعد اختزاله مباشرة بواسطة `2H` الناتجة من التحلل السكري.

