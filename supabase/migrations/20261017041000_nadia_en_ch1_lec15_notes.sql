# المحاضرة الخامسة عشرة – شبكة الكروماتين والكروموسومات

## 🧭 نظرة عامة

تستكمل المحاضرة مكونات النواة بشرح شبكة الكروماتين، وتوضح كيف تتغير هيئة المادة الوراثية بحسب حالة الخلية من خيوط كروماتينية إلى كروموسومات واضحة، ثم إلى كروماتيدين شقيقين بعد تضاعف DNA. كما تشرح علاقة الكروموسومات بالجينات والصفات الوراثية، والفرق بين العدد الكروموسومي في الخلايا الجسمية والأمشاج.

## 1. معنى الكروماتين (Chromatin)

- الكروماتين هو DNA ملتف حول بروتينات خاصة.
- يظهر داخل نواة الخلية غير المنقسمة على هيئة خيوط دقيقة.
- تسمى هذه الخيوط مجتمعة شبكة الكروماتين (Chromatin Network).
- لا تعني كلمة "شبكة" أن الخيوط متساوية أو منتظمة؛ فقد تختلف في الطول والترتيب.

## 2. تعريف شبكة الكروماتين

- شبكة من خيوط دقيقة غير منتظمة ومتشابكة فيما بينها.
- توجد داخل نواة الخلية حقيقية النواة.
- تتكون أساساً من DNA مرتبط بالبروتينات.
- تظهر بهذه الصورة عندما تكون الخلية في الطور البيني ولا تكون الكروموسومات متكثفة.

## 3. من الكروماتين إلى الكروموسوم

عندما تتهيأ الخلية للانقسام:

1. تتكثف خيوط الكروماتين وتنتظم.
2. تصبح أقصر وأكثر سمكاً ووضوحاً.
3. تظهر على هيئة تراكيب عصوية تسمى الكروموسومات (Chromosomes).

**قاعدة الحفظ:**

- خلية غير منقسمة → كروماتين منتشر.
- خلية متهيئة للانقسام → كروموسومات متكثفة.

## 4. الكروماتيدان الشقيقان (Sister Chromatids)

- يتضاعف DNA قبل انقسام الخلية.
- يصبح الكروموسوم المتضاعف مكوناً من نسختين متماثلتين.
- تسمى كل نسخة كروماتيداً (Chromatid).
- تسمى النسختان معاً كروماتيدين شقيقين (Sister Chromatids).
- ينفصل الكروماتيدان أثناء الانقسام، ويتجه كل واحد إلى خلية بنت.

## 🔄 العلاقة بين المصطلحات

| المصطلح | حالة المادة الوراثية |
|---|---|
| Chromatin | DNA منتشر على هيئة خيوط في النواة |
| Chromosome | كروماتين متكثف وواضح أثناء التهيؤ والانقسام |
| Chromatid | إحدى نسختي الكروموسوم بعد تضاعف DNA |
| Sister Chromatids | كروماتيدان متماثلان ناتجان عن تضاعف كروموسوم واحد |

## 5. الجينات والصفات الوراثية

- تحمل الكروموسومات الجينات (Genes).
- الجينات وحدات وراثية تسهم في تحديد صفات الكائن الحي.
- من أمثلة الصفات: الطول، ولون العين، ولون الشعر، ولون البشرة.
- تنتقل الجينات والصفات الوراثية من الآباء إلى الأبناء عبر الكروموسومات.

## 6. أهمية الكروموسومات

تؤدي الكروموسومات دوراً أساسياً في:

- الوراثة (Heredity/Genetics).
- التكاثر (Reproduction).
- التباين بين الأفراد (Variation).
- الطفرات الوراثية (Mutations).

**تعليل مهم:** تعد الكروموسومات مهمة لأنها تحمل الجينات وتنقل المعلومات والصفات الوراثية من جيل إلى آخر.

## 7. العدد الكروموسومي الثابت

- لكل نوع من الكائنات الحية عدد كروموسومي ثابت ومميز.
- ثبات العدد يخص النوع، ولا يعني أن الأنواع المختلفة تمتلك العدد نفسه.
- العدد الكبير من الكروموسومات لا يعني بالضرورة أن الكائن أكثر تطوراً.

## 8. الخلايا الجسمية والأمشاج

### الخلايا الجسمية (Somatic Cells)

- تمثل معظم خلايا الجسم.
- تحمل العدد الثنائي من الكروموسومات (2n).

### الأمشاج (Gametes)

- هي الخلايا الجنسية: البيضة والنطفة.
- تحمل نصف عدد كروموسومات الخلايا الجسمية (n).

### مثال الإنسان

- الخلية الجسمية: 46 كروموسوماً.
- البيضة: 23 كروموسوماً.
- النطفة: 23 كروموسوماً.
- بعد الإخصاب: 23 + 23 = 46 كروموسوماً في اللاقحة.

**قاعدة الحساب:** عدد كروموسومات المشيج = نصف عدد كروموسومات الخلية الجسمية.

