# المحاضرة الحادية والعشرون – الثمرة وأنواعها وتركيبها (Fruit Structure and Types)

## 🧭 نظرة عامة سريعة

تتناول المحاضرة الثمرة (Fruit) ابتداءً من تعريفها وأصلها بعد الإخصاب، ثم تشرح تركيب الثمرة ذي الطبقات الثلاث: الإكسوكارب (Exocarp)، والميزوكارب (Mesocarp)، والإندوكارب (Endocarp). كما تشرح أنواع الثمار بحسب عدد الأزهار والكرابل الداخلة في تكوينها: الثمرة البسيطة (Simple Fruit)، والثمرة المتجمعة (Aggregate Fruit)، والثمرة المركبة أو المتعددة (Compound/Multiple Fruit)، مع الأمثلة والرسومات التي ركز عليها المدرس.

## 📚 المفاهيم والشرح التفصيلي

### 1. مراجعة مختصرة قبل دراسة الثمرة

- المتك (Anther) جزء من السداة (Stamen)، ويكوّن حبوب اللقاح (Pollen Grains).
- تنشأ حبوب اللقاح من الخلية الأم للبوغة الدقيقة (Microspore Mother Cell) بعد الانقسام الاختزالي (Meiosis).
- تنتج أربع أبواغ دقيقة (Microspores)، ثم تتكون النواة التوليدية والنواة الأنبوبية.
- المبيض (Ovary) جزء من المدقة (Pistil)، وداخله البويضات (Ovules).
- تتكون البويضة من نتوء صغير يخرج من جدار المبيض، ثم تتكون أغلفتها والنوسيلة (Nucellus).
- تدخل الخلية الأم للبوغة الكبيرة (Megaspore Mother Cell) الانقسام الاختزالي، فتنتج أربع بوغات كبيرة، تتحلل ثلاث منها وتبقى الرابعة.
- تنقسم نواة البوغة الكبيرة الباقية ثلاث مرات خيطياً، فتنتج ثماني نوى تكوّن الكيس الجنيني (Embryo Sac).
- يحدث الإخصاب المزدوج (Double Fertilization): يتكون الجنين من اللاقحة، ويتكون الإندوسبيرم (Endosperm) من الاتحاد الثاني.
- تتحول البويضة بعد اكتمال الجنين إلى بذرة (Seed)، وتتحول أغلفة البويضة إلى غلاف البذرة (Seed Coat).

### 2. تعريف الثمرة وأصلها

الثمرة (Fruit) هي **مبيض ناضج (Mature Ovary) مع محتوياته وأغلفته**.

- المبيض هو الجزء الرئيس الذي يتحول إلى ثمرة بعد الإخصاب.
- محتويات المبيض تشمل البذور (Seeds) الناتجة من تحول البويضات.
- أغلفة المبيض تتحول إلى طبقات الثمرة.
- لذلك فإن الثمرة والبذرة تتكونان بعد الإخصاب، وتكون الثمرة مبيضاً ناضجاً يحتوي على البذور.

### 3. الطبقات الثلاث للثمرة

تتكون الثمرة من ثلاث طبقات رئيسة:

#### أ. الإكسوكارب/القشرة الخارجية (Exocarp)

- الطبقة الخارجية للثمرة.
- تسمى القشرة أو الغلاف الخارجي (Outer Skin/Covering).
- تكون هي الطبقة التي نراها من الخارج.

#### ب. الميزوكارب/الطبقة الوسطى (Mesocarp)

- الطبقة الواقعة بين الإكسوكارب والإندوكارب.
- تكون غالباً المنطقة اللحمية في الثمرة.
- تسمى المادة اللحمية (Fleshy Material)، وهي الجزء الذي يؤكل في كثير من الثمار.

#### ج. الإندوكارب/الطبقة الداخلية (Endocarp)

- الطبقة الداخلية من جدار الثمرة.
- قد تكون صلبة أو قاسية، وتحيط بالبذرة.
- تمثل في بعض الثمار النواة أو الجزء الحجري (Stone/Pit).
- توجد البذرة داخل الإندوكارب أو ضمن المنطقة التي يحميها.

### 4. الثمرة البسيطة (Simple Fruit)

- تتكون الثمرة البسيطة من زهرة واحدة (One Flower).
- قد تتكون من كربلة واحدة أو من عدة كرابل، لكن تبقى جميعها تابعة لزهرة واحدة.
- قد تكون الكرابل متحدة أو منفصلة بحسب تركيب الزهرة.
- القاعدة الأساسية: **زهرة واحدة ⟶ ثمرة بسيطة**.
- أمثلة المحاضرة:
  - المشمش (Apricot).
  - الطماطم (Tomato).
  - الخيار (Cucumber).
  - البرتقال (Orange).
- المهم في المثال ليس عدد الكرابل، بل أن الثمرة ناتجة من زهرة واحدة.

### 5. الثمرة المتجمعة (Aggregate Fruit)

- تتكون الثمرة المتجمعة من زهرة واحدة، لكنها تحتوي على العديد من الكرابل أو المدقات المنفصلة.
- تكون الكرابل منفصلة عن بعضها، وكل كربلة قد تكوّن ثميرة/جزءاً من الثمرة.
- ترتبط هذه الأجزاء كلها بتخت واحد (One Receptacle).
- القاعدة الأساسية: **زهرة واحدة + كرابل عديدة منفصلة ⟶ ثمرة متجمعة**.
- المثال المذكور في المحاضرة هو التوت الأسود (Blackberry).
- عند النظر إلى التوت الأسود، نرى دوائر أو وحدات عديدة؛ كل وحدة تمثل ثميرة ناتجة من كربلة، لكنها جميعاً متصلة بتخت واحد تابع لزهرة واحدة.

### 6. الثمرة المركبة أو المتعددة (Compound/Multiple Fruit)

- تتكون الثمرة المركبة من عدة أزهار (Many Flowers)، وليس من زهرة واحدة.
- تمتلك النورة أو المجموعة الزهرية عدة أزهار وكرابل.
- تتصل الأزهار أو الثمار الناتجة مع بعضها، فتظهر في النهاية كثمرة واحدة مركبة أو متعددة.
- القاعدة الأساسية: **أزهار عديدة ⟶ ثمرة مركبة/متعددة**.
- المثال المذكور في المحاضرة هو الأناناس (Pineapple).
- كل قطعة أو جزء ظاهر في ثمرة الأناناس يمثل زهرة، وجميع الأزهار مرتبطة معاً في تركيب ثمري واحد.

### 7. تركيب ثمرة الأناناس

- عند قطع الأناناس طولياً أو فتحه بالطريقة الموضحة، يظهر تركيب مركزي يسمى القلب (Core).
- القلب يتكون من نسيج وعائي (Vascular Tissue) يضم الخشب واللحاء (Xylem and Phloem).
- يحتوي القلب على ألياف (Fibers)، لذلك يكون قاسياً وصعب المضغ والبلع، ويُزال غالباً.
- حول القلب توجد غرف أو حجرات (Chambers).
- كل غرفة تمثل زهرة، وتمثل أيضاً المبيض التابع لتلك الزهرة.
- كل مبيض يتحول إلى ثمرة، ولذلك تكون الثمرة الناتجة ثمرة مركبة/متعددة.
- ترتبط الأجزاء كلها بالقلب، وليس بتخت واحد بالمعنى الخاص بالثمرة المتجمعة؛ لأن أصلها عدة أزهار.

### 8. الفرق بين الثمار الثلاث

| النوع | عدد الأزهار | عدد الكرابل | طريقة الارتباط | المثال المذكور |
|---|---:|---:|---|---|
| الثمرة البسيطة (Simple Fruit) | زهرة واحدة | كربلة واحدة أو عدة كرابل | ناتجة من زهرة واحدة | المشمش والطماطم والخيار والبرتقال |
| الثمرة المتجمعة (Aggregate Fruit) | زهرة واحدة | كرابل عديدة منفصلة | ترتبط بتخت واحد | التوت الأسود |
| الثمرة المركبة/المتعددة (Compound/Multiple Fruit) | أزهار عديدة | كرابل عديدة تابعة لأزهار متعددة | ترتبط في تركيب ثمري واحد | الأناناس |

### 9. الثمرة الكاذبة (False Fruit)

- ذكرت المحاضرة الثمرة الكاذبة (False Fruit) ضمن المراجعة السابقة.
- من أمثلتها المذكورة التفاح (Apple) والتوت/البلاك بيري بحسب سياق الشرح.
- الثمرة الكاذبة هي ثمرة يدخل في تكوينها جزء من الزهرة أو تركيب آخر غير المبيض وحده، ولذلك لا تكون ناتجة من المبيض فقط.
- المطلوب امتحانياً هو حفظ التعريف والأمثلة التي حددها المنهج والمدرس.

### 10. وظائف تراكيب الزهرة والثمرة في المراجعة

- المبيض (Ovary) يتحول إلى ثمرة.
- البويضات (Ovules) تتحول إلى بذور.
- الجنين (Embryo) يتكون بعد الإخصاب ويصبح داخل البذرة.
- الإندوسبيرم (Endosperm) يكوّن نسيجاً خازناً للغذاء.
- بعض التراكيب الجنينية تنمو إلى الجذير والسويق والفلقتين.
- بعد تحول المبيض إلى ثمرة، تصبح الثمرة حاوية للبذور.

## 📖 التعريفات والمصطلحات

- **الثمرة (Fruit):** مبيض ناضج مع محتوياته وأغلفته.
- **المبيض الناضج (Mature Ovary):** المبيض بعد الإخصاب والنمو، ويتحول إلى ثمرة.
- **البذرة (Seed):** التركيب الناتج من تحول البويضة، ويكون موجوداً داخل الثمرة.
- **الإكسوكارب/القشرة الخارجية (Exocarp):** الطبقة الخارجية من جدار الثمرة.
- **الميزوكارب/الطبقة الوسطى (Mesocarp):** الطبقة الوسطى اللحمية بين الإكسوكارب والإندوكارب.
- **الإندوكارب/الطبقة الداخلية (Endocarp):** الطبقة الداخلية من جدار الثمرة، وقد تكون صلبة وتحيط بالبذرة.
- **الثمرة البسيطة (Simple Fruit):** ثمرة ناتجة من زهرة واحدة، سواء كانت ذات كربلة واحدة أو عدة كرابل.
- **الثمرة المتجمعة (Aggregate Fruit):** ثمرة ناتجة من زهرة واحدة ذات كرابل عديدة منفصلة، ترتبط بتخت واحد.
- **الثمرة المركبة/المتعددة (Compound/Multiple Fruit):** ثمرة ناتجة من عدة أزهار مرتبطة معاً.
- **الثمرة الكاذبة (False Fruit):** ثمرة يدخل في تكوينها جزء غير المبيض أو أجزاء أخرى من الزهرة، فلا تكون ناتجة من المبيض وحده.
- **التخت (Receptacle):** التركيب الذي ترتبط به كرابل الثمرة المتجمعة.
- **القلب (Core):** النسيج المركزي في ثمرة الأناناس، ويضم أوعية الخشب واللحاء وأليافاً تجعله قاسياً.
- **النسيج الوعائي (Vascular Tissue):** نسيج يضم الخشب واللحاء، ويساعد على النقل داخل النبات.
- **الزهرة الواحدة (One Flower):** وحدة زهرية واحدة قد تكوّن ثمرة بسيطة أو ثمرة متجمعة بحسب عدد الكرابل.
- **الأزهار العديدة (Many Flowers):** مجموعة أزهار تشترك في تكوين ثمرة مركبة أو متعددة.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة تكوين الثمرة

المبيض الناضج + محتوياته + أغلفته = ثمرة.

### قاعدة أصل البذرة والثمرة

البويضة ⟶ البذرة، والمبيض ⟶ الثمرة.

### قاعدة الثمرة البسيطة

زهرة واحدة ⟶ ثمرة بسيطة.

### قاعدة الثمرة المتجمعة

زهرة واحدة + كرابل عديدة منفصلة + تخت واحد ⟶ ثمرة متجمعة.

### قاعدة الثمرة المركبة/المتعددة

أزهار عديدة + كرابل عديدة مرتبطة ⟶ ثمرة مركبة/متعددة.

### قاعدة طبقات جدار الثمرة

من الخارج إلى الداخل: الإكسوكارب ⟶ الميزوكارب ⟶ الإندوكارب.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تعريف الثمرة

**السؤال:** عرّف الثمرة.

**الإجابة:** الثمرة هي مبيض ناضج مع محتوياته وأغلفته.

### مثال 2: أصل الثمرة والبذرة

**المعطيات:** مبيض وبويضات بعد الإخصاب.

**القاعدة:** المبيض يتحول إلى ثمرة، والبويضات تتحول إلى بذور.

**الناتج النهائي:** الثمرة أصلها المبيض، والبذور أصلها البويضات.

### مثال 3: تحديد طبقات الثمرة

**المعطيات:** ثمرة لها قشرة خارجية ومنطقة لحمية وطبقة داخلية صلبة.

**الحل من الخارج إلى الداخل:**

1. القشرة الخارجية = الإكسوكارب (Exocarp).
2. المنطقة اللحمية = الميزوكارب (Mesocarp).
3. الطبقة الداخلية الصلبة = الإندوكارب (Endocarp).

### مثال 4: تصنيف المشمش والطماطم والخيار والبرتقال

**المعطيات:** الثمار ناتجة من زهرة واحدة.

**القاعدة:** كل ثمرة ناتجة من زهرة واحدة تصنف ثمرة بسيطة.

**الناتج النهائي:** المشمش والطماطم والخيار والبرتقال أمثلة على الثمار البسيطة.

### مثال 5: تصنيف التوت الأسود

**المعطيات:** عدة كرابل منفصلة تابعة لزهرة واحدة، وكل جزء متصل بتخت واحد.

**القاعدة:** زهرة واحدة ذات كرابل عديدة منفصلة متصلة بتخت واحد = ثمرة متجمعة.

**الناتج النهائي:** التوت الأسود (Blackberry) ثمرة متجمعة.

### مثال 6: تصنيف الأناناس

**المعطيات:** ثمرة تتكون من أجزاء عديدة، وكل جزء يمثل زهرة، وجميعها مرتبطة معاً.

**القاعدة:** الثمرة الناتجة من أزهار عديدة تسمى ثمرة مركبة أو متعددة.

**الناتج النهائي:** الأناناس (Pineapple) ثمرة مركبة/متعددة.

