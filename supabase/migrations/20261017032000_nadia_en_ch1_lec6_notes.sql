# المحاضرة السادسة – الشبكة الإندوبلازمية الخشنة والملساء

## 🧭 نظرة عامة سريعة

تشرح المحاضرة نوعي الشبكة الإندوبلازمية (Endoplasmic Reticulum): الشبكة الخشنة (Rough ER) والشبكة الملساء (Smooth ER)، وكيفية التمييز بينهما من خلال وجود الريبوسومات أو غيابها، ثم توضح الوظائف الأساسية لكل نوع وأماكن ظهور الشبكة الملساء بصورة واضحة داخل الجسم.

## 📚 المفاهيم والشرح التفصيلي

### 1. ترابط الشبكة الإندوبلازمية

- الشبكة الإندوبلازمية نظام من التفرعات المتشابكة والمترابطة داخل السيتوبلازم.
- يمكن أن يظهر جزء من الشبكة خشناً وجزء آخر أملساً؛ لأن تفرعاتها تتصل وتتشابك فيما بينها.
- قد يُرسم النوعان منفصلين للتوضيح، أو ضمن شبكة واحدة مقسمة إلى جزء خشن وجزء أملس.

### 2. الشبكة الإندوبلازمية الخشنة (Rough Endoplasmic Reticulum)

- توجد الريبوسومات (Ribosomes) على الأسطح الخارجية لنبيبات الشبكة.
- وجود الريبوسومات يعطي الشبكة مظهراً خشناً ومحبباً (Rough and Granular Appearance).
- عند الرسم يجب وضع الريبوسومات على سطح النبيبات، وليس داخلها.

### 3. وظائف الشبكة الإندوبلازمية الخشنة

#### أ. بناء البروتينات

- تنتج الشبكة الخشنة البروتينات وتشارك في بنائها.
- يعود ذلك إلى وجود الريبوسومات على سطحها؛ لأن الريبوسومات مسؤولة عن تصنيع البروتين.

#### ب. نقل المواد

- تعمل الشبكة بوصفها نظاماً لنقل المواد من منطقة إلى أخرى داخل الخلية.
- تنقل الشبكة الخشنة البروتينات التي تُصنع عليها.
- يمكن أن تُنقل المواد إلى عضيات أخرى، وخصوصاً جهاز كولجي (Golgi Apparatus).

#### ج. الدعم والإسناد

- تكوّن شبكة هيكلية داخل السيتوبلازم.
- تمنح المادة البينية السيتوبلازمية دعماً وإسناداً.

### 4. الشبكة الإندوبلازمية الملساء (Smooth Endoplasmic Reticulum)

- لا توجد ريبوسومات على أسطح نبيباتها.
- لذلك يكون مظهرها ناعماً وتسمى الشبكة الإندوبلازمية الملساء.
- عدم وجود الريبوسومات يعني أن وظيفتها لا تختص ببناء البروتينات.

### 5. وظائف الشبكة الإندوبلازمية الملساء

#### أ. نقل المواد

- تنقل مواد مختلفة داخل السيتوبلازم بحسب حاجة الخلية.
- لا تختص بنقل البروتينات المصنّعة على الريبوسومات مثل الشبكة الخشنة.

#### ب. الدعم والإسناد

- تسهم في تكوين شبكة هيكلية تدعم المادة البينية الموجودة داخل السيتوبلازم.

#### ج. بناء الدهون وخزنها

- تختص بصناعة الدهون (Fats/Lipids).
- تساعد على تركيز الدهون وخزنها داخل خلايا معينة.
- كثرة الشبكة الملساء في خلية ما ترتبط بزيادة نشاط تصنيع الدهون وخزنها.

#### د. إفراز الهرمونات الستيرويدية

- تسهم في إفراز الهرمونات الستيرويدية (Steroid Hormones).
- من أمثلتها: الإستروجين (Estrogen)، والبروجستيرون (Progesterone)، والتستوستيرون (Testosterone).
- تظهر الشبكة الملساء بوضوح في خلايا المبيض (Ovary)، والخصية (Testis)، والغدد الكظرية (Adrenal Glands).

#### هـ. إزالة السمية

- تؤدي دوراً مهماً في إزالة سمية الأدوية والعقاقير والمواد المخدرة (Detoxification of Drugs and Medications).
- تتركز بكثرة في خلايا الكبد (Liver Cells) لارتباط الكبد بعملية إزالة السمية من الجسم.

## ⚠️ نقاط مهمة للحفظ

- الشبكة الخشنة: ريبوسومات على السطح، لذلك مظهرها خشن ومحبب.
- الشبكة الملساء: لا توجد ريبوسومات على سطحها، لذلك مظهرها ناعم.
- الريبوسومات تُرسم على سطح نبيبات الشبكة الخشنة وليس داخلها.
- الخشنة تختص ببناء البروتينات ونقلها.
- الملساء تختص ببناء الدهون وخزنها، وإفراز الهرمونات الستيرويدية، وإزالة السمية.
- تظهر الشبكة الملساء بوضوح في خلايا المبيض والخصية والغدد الكظرية، وتتركز في خلايا الكبد لإزالة السمية.

## 🧠 الخلاصة

- الشبكة الإندوبلازمية شبكة مترابطة داخل السيتوبلازم وتتكون من نوعين: خشنة وملساء.
- الخشنة تحمل ريبوسومات على سطحها، وتبني البروتينات وتنقلها وتدعم المادة السيتوبلازمية.
- الملساء لا تحمل ريبوسومات، وتنقل المواد وتدعم الخلية وتصنع الدهون وتخزنها.
- ترتبط الشبكة الملساء بإفراز الهرمونات الستيرويدية وإزالة سمية الأدوية والعقاقير.

