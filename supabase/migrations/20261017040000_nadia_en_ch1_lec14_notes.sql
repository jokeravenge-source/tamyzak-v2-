# المحاضرة الرابعة عشرة – النواة: الأهمية والتركيب

## 🧭 نظرة عامة

تبدأ المحاضرة دراسة النواة في الخلايا حقيقية النواة، وتوضح أهميتها لبقاء الخلية وسيطرتها على فعالياتها. ثم تشرح اختلاف شكل النواة وحجمها وعددها وموقعها، وتعرض ثلاثة من مكوناتها: الغلاف النووي، والبلازم النووي، والنوية. أما شبكة الكروماتين فتُستكمل في المحاضرة التالية.

## 1. أهمية النواة (Nucleus)

- النواة أكبر عضية واضحة في كثير من الخلايا حقيقية النواة.
- تعد مركز السيطرة والتنظيم في الخلية.
- ضرورية لحياة الخلية واستمرار فعالياتها.
- تعتمد الخلية على التبادل المستمر للمواد بين النواة والسيتوبلازم.
- عند فقدان النواة تتوقف عمليات تنظيمية وتبادلية أساسية، ولذلك لا تستمر الخلية مدة طويلة.

### مثال مهم

- كرية الدم الحمراء البالغة (Adult Red Blood Cell) خلية عديمة النواة.
- يجب ذكر كلمة **البالغة**؛ لأن الخلية الحمراء الفتية تمتلك نواة قبل اكتمال نضجها.
- تعيش كرية الدم الحمراء البالغة مدة محدودة ثم تتحلل ولا تنقسم.

## 2. خصائص النواة

### أ. شكل النواة

- يختلف شكل النواة باختلاف شكل الخلية.
- من أشكالها المذكورة:
  - بيضوية (Oval).
  - كروية (Spherical).
  - مفصصة (Lobed).
  - غير منتظمة (Irregular).
- تمثل خلايا الدم البيضاء مثالاً مهماً للأنوية المفصصة أو المتنوعة الشكل.

**قاعدة الحفظ:** شكل النواة يعتمد على شكل الخلية.

### ب. حجم النواة

- يختلف حجم النواة باختلاف حجم الخلية.

**قاعدة الحفظ:** حجم النواة يعتمد على حجم الخلية.

### ج. عدد الأنوية

- تحتوي نحو 95% من الخلايا على نواة واحدة، وتسمى وحيدة النواة (Mononucleate).
- قد تحتوي بعض الخلايا على نواتين، وتسمى ثنائية النواة (Binucleate).
- من الأمثلة المذكورة: بعض خلايا الكبد وبعض الخلايا الغضروفية.

### د. موقع النواة

- لا يكون موقع النواة ثابتاً في جميع الخلايا.
- تكون مركزية في الخلايا الجنينية أو الجذعية.
- تكون جانبية أو محيطية في بعض الخلايا المتخصصة.
- من أمثلة الموقع المحيطي:
  - الخلايا الدهنية (Fat Cells).
  - بعض الخلايا المخاطية الإفرازية (Mucous Secretory Cells).

## 3. مكونات النواة

تتكون النواة من أربعة أجزاء رئيسة:

1. الغلاف أو الغشاء النووي (Nuclear Envelope/Membrane).
2. البلازم النووي (Nucleoplasm).
3. النوية (Nucleolus).
4. شبكة الكروماتين (Chromatin Network).

## 4. الغلاف النووي (Nuclear Envelope)

### الوصف والموقع

- غلاف رقيق مزدوج (Thin Double Membrane).
- يحيط بالنواة في الخلايا حقيقية النواة.
- يفصل محتويات النواة عن السيتوبلازم.
- لا يوجد غلاف نووي حقيقي في الخلايا بدائية النواة؛ إذ تكون مادتها الوراثية حرة في السيتوبلازم.

### الثقوب النووية

- يحتوي الغلاف النووي على ثقوب دقيقة تسمى الثقوب النووية أو المسامات الدقيقة (Nuclear Pores/Micropores).
- تسمح هذه الثقوب بمرور المواد والجزيئات عبر الغلاف النووي.

### الوظيفة

- ينظم تبادل المواد بين النواة والسيتوبلازم.
- تسمح المسامات النووية بالعبور الانتقائي للمواد الداخلة إلى النواة والخارجة منها.

**تعليل مهم:** ينظم الغلاف النووي التبادل لاحتوائه على ثقوب نووية دقيقة تسمح بمرور المواد.

## 5. البلازم النووي (Nucleoplasm)

### التعريف

- مادة سائلة جيلاتينية عديمة اللون (Colorless Gelatinous Liquid).
- تملأ الحيز الداخلي للنواة.

### الوظيفة

- يمثل الوسط الذي تنتظم فيه محتويات النواة.
- توجد داخله:
  - النوية.
  - شبكة الكروماتين.

## 6. النوية (Nucleolus)

### العدد

- تحتوي معظم الأنوية على نوية واحدة.
- قد تحتوي بعض الأنوية على أكثر من نوية.
- المثال المذكور: قد تحتوي بعض خلايا البصل على أربع نويات.

### الوصف والموقع

- تركيب كروي كبير وواضح داخل النواة.
- يوجد مغموراً في البلازم النووي.

### التركيب الكيميائي

- تتكون النوية أساساً من البروتين وRNA.

### الوظيفة

- تؤدي دوراً مهماً في تكوين الريبوسومات.
- تُصنع فيها مكونات الريبوسومات ثم تنتقل لتشارك في تكوين الريبوسومات الوظيفية.

