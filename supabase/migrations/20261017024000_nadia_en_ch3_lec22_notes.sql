# المحاضرة الثانية والعشرون – انتشار البذور والثمار (Seed and Fruit Dispersal)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة كيفية انتقال البذور والثمار من النبات الأم إلى أماكن أخرى، اعتماداً على تراكيب خاصة في البذرة أو الثمرة، وعلى عوامل بيئية خارجية. ركز المدرس على ثلاثة عوامل وزارية: الرياح (Wind)، الحيوانات (Animals)، والماء (Water).

## 📚 المفاهيم والشرح التفصيلي

### 1. مراجعة الثمرة

- الثمرة (Fruit) هي مبيض ناضج (Mature Ovary) مع محتوياته وأغلفته.
- تحتوي الثمرة على البذور (Seeds)، ويتكون جدارها من:
  1. الإكسوكارب/الغلاف الخارجي (Exocarp).
  2. الميزوكارب/الغلاف الأوسط (Mesocarp).
  3. الإندوكارب/الغلاف الداخلي (Endocarp).
- الثمرة البسيطة (Simple Fruit) تتكون من زهرة واحدة.
- الثمرة المتجمعة (Aggregate Fruit) تتكون من زهرة واحدة ذات كرابل عديدة منفصلة وترتبط بتخت واحد، ومثالها التوت الأسود (Blackberry).
- الثمرة المركبة أو المتعددة (Compound/Multiple Fruit) تتكون من أزهار عديدة، ومثالها الأناناس (Pineapple).

### 2. تعريف انتشار البذور والثمار

انتشار البذور والثمار (Seed and Fruit Dispersal) هو انتقال البذور أو الثمار من النبات الأم إلى مكان آخر بعيد أو إلى بيئة مشابهة للبيئة الأصلية.

### 3. التراكيب التي تساعد على الانتشار

- توجد في بعض البذور والثمار أجزاء خاصة تساعدها على الانتقال.
- من هذه الأجزاء:
  - الأجنحة (Wings).
  - التراكيب التي تشبه المظلة (Umbrella-like Structures).
  - الأشواك أو الكلاليب (Bristles/Hooks).
  - التجاويف الهوائية (Air Vacuums/Air Cavities).
- تؤثر بنية البذرة أو الثمرة في طريقة انتشارها، كما يؤثر وزنها وحجمها.
- كلما قل الوزن، زادت سهولة الانتشار.
- كلما صغر الحجم، زادت قابلية الانتشار.
- الثمار والبذور الكبيرة أو الثقيلة تكون أقل قابلية للانتشار.

### 4. العوامل الخارجية للانتشار

- الرياح (Wind).
- الطيور (Birds).
- الحيوانات (Animals).
- طريقة انفتاح الثمرة (Fruit Opening/Dehiscence).
- الماء (Water).
- ركزت المحاضرة على الرياح والحيوانات والماء، ولكل عامل تعليل وأمثلة محددة.

## 🌬️ أولاً: الانتشار بواسطة الرياح (Wind Dispersal)

### آلية الانتشار

1. تحمل الرياح البذور أو الثمار من النبات الأم.
2. تنتقل إلى مكان بعيد أو إلى بيئة مشابهة.
3. تساعد التراكيب الخاصة على بقاء البذرة أو الثمرة في الهواء.

### صفات البذور والثمار المنتشرة بالرياح

- خفيفة الوزن (Light in Weight).
- تحتوي على أجنحة (Wings)، أو تراكيب تشبه المظلة.
- قد تكون على شكل مظلة أو تحمل تراكيب تساعدها على الانجراف.

### أمثلة

- نبات البردي (Papyrus Plant).
- الحشائش (Grasses).
- الأعشاب (Herbs).
- بعض نباتات الحدائق.
- بعض النباتات الصحراوية.
- الثمار المجنحة (Winged Fruits).

### التعليل

**لماذا تنتشر هذه النباتات بالرياح بسهولة؟** لأنها خفيفة الوزن وتحتوي على أجنحة أو تراكيب مظلية تساعد الرياح على حملها ونقلها بعيداً عن النبات الأم.

## 🐾 ثانياً: الانتشار بواسطة الحيوانات (Animal Dispersal)

### آلية الانتشار

1. تحتوي الثمرة أو البذرة على أشواك (Bristles/Prickles) أو كلاليب/خطاطيف (Hooks).
2. تلتصق هذه التراكيب بجلد الحيوان أو شعره.
3. ينقل الحيوان البذرة أو الثمرة أثناء حركته.
4. تصل إلى مكان بعيد عن النبات الأم، ثم تنفصل هناك.

### التعليل

**لماذا تنقل الحيوانات هذه البذور والثمار؟** لأنها تحتوي على أشواك أو كلاليب تساعدها على الالتصاق بجلد الحيوانات أو شعرها، فتنتقل معها إلى أماكن أخرى.

### ملاحظة مصطلحية

إذا نُسيت كلمة الأشواك (Bristles/Prickles)، يمكن استعمال كلمة الكلاليب أو الخطاطيف (Hooks) لأنها تؤدي المعنى نفسه في الشرح.

## 🌊 ثالثاً: الانتشار بواسطة الماء (Water Dispersal)

### آلية الانتشار

- يحدث في النباتات المائية (Aquatic Plants) أو النباتات القريبة من الماء.
- تنقل تيارات الماء البذور والثمار من مكان إلى آخر.
- يجب أن تكون البذرة أو الثمرة قادرة على الطفو فوق سطح الماء.

### مثال جوز الهند (Coconut)

- جوز الهند ليس خفيف الوزن، ومع ذلك ينتشر بواسطة الماء.
- يحتوي على تجاويف أو فراغات هوائية (Air Vacuums/Air Cavities).
- هذه التجاويف مملوءة بالهواء.
- تساعده على الطفو فوق سطح الماء ومنع غرقه.
- تنقله تيارات الماء إلى أماكن أخرى، وقد يستقر قرب الماء وينمو هناك.

### التعليل

**لماذا يستطيع جوز الهند الانتقال بالماء رغم وزنه؟** لأنه يحتوي على تجاويف مملوءة بالهواء تساعده على الطفو فوق سطح الماء، ثم تنقله تيارات الماء.

