## 📖 التعريفات والمصطلحات

- **انتشار البذور والثمار (Seed and Fruit Dispersal):** انتقال البذور والثمار من النبات الأم إلى أماكن أخرى.
- **الرياح (Wind):** عامل ينقل البذور والثمار الخفيفة أو ذات الأجنحة.
- **الحيوانات (Animals):** عامل ينقل البذور والثمار التي تلتصق بجلده أو شعره.
- **الماء (Water):** عامل ينقل البذور والثمار القابلة للطفو.
- **الثمار المجنحة (Winged Fruits):** ثمار تمتلك أجنحة تساعدها على الانتقال بالرياح.
- **الأشواك (Bristles/Prickles):** تراكيب تساعد على الالتصاق بالحيوان.
- **الكلاليب/الخطاطيف (Hooks):** تراكيب تشبه الخطاف تتمسك بجلد الحيوان أو شعره.
- **التجاويف الهوائية (Air Vacuums/Air Cavities):** فراغات مملوءة بالهواء تساعد على الطفو.
- **النباتات المائية (Aquatic Plants):** نباتات تعيش داخل الماء أو قربه.
- **النبات الأم (Parent Plant):** النبات الذي تتكون عليه البذور أو الثمار قبل انتشارها.

## 🔢 القوانين / الصيغ / القواعد

- بذرة/ثمرة خفيفة + أجنحة أو شكل مظلي ⟶ انتشار بالرياح.
- بذرة/ثمرة ذات أشواك أو كلاليب + جلد/شعر الحيوان ⟶ انتشار بالحيوانات.
- بذرة/ثمرة ذات تجاويف مملوءة بالهواء ⟶ طفو ⟶ انتشار بالماء.
- وزن أقل أو حجم أصغر ⟶ قابلية انتشار أكبر.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: نبات البردي والرياح

**المعطيات:** بذور أو ثمار خفيفة تحتوي على تراكيب تساعدها على الحركة في الهواء.

**العامل:** الرياح.

**الحل:** تحمل الرياح البذور الخفيفة، وتساعد الأجنحة أو التراكيب المظلية على بقائها في الهواء ونقلها بعيداً.

**الناتج:** تنتشر بواسطة الرياح.

### مثال 2: ثمرة ذات كلاليب والحيوانات

**المعطيات:** ثمرة تحتوي على أشواك أو كلاليب.

**الحل:** تلتصق بجلد الحيوان أو شعره، وينقلها الحيوان إلى مكان آخر.

**الناتج:** تنتشر بواسطة الحيوانات.

### مثال 3: جوز الهند والماء

**المعطيات:** جوز الهند ثقيل لكنه يحتوي على تجاويف هوائية.

**الحل:** تبقيه التجاويف مملوءاً بالهواء، فيطفو فوق سطح الماء وتنقله التيارات.

**الناتج:** ينتشر بواسطة الماء.

## ⚠️ تنبيهات وأخطاء شائعة (ملاحظات وزارية)

- **مهم جداً:** احفظ العوامل الثلاثة: الرياح، الحيوانات، الماء.
- الرياح تحتاج خفة الوزن ووجود الأجنحة أو الشكل المظلي.
- الحيوانات تحتاج أشواكاً أو كلاليب تلتصق بالجلد أو الشعر.
- الماء يحتاج تراكيب تساعد على الطفو، وأهمها التجاويف الهوائية.
- جوز الهند ثقيل، لكنه ينتشر بالماء بسبب تجاويفه المملوءة بالهواء، وليس بسبب خفة الوزن.
- لا تذكر الحيوانات وحدها؛ اذكر الأشواك أو الكلاليب والالتصاق بجلد الحيوان أو شعره.
- لا تذكر الرياح وحدها في تعليل البردي؛ يجب ذكر خفة الوزن والأجنحة أو الشكل المظلي.
- الوزن والحجم مهمان: انخفاضهما يزيد الانتشار.
- طريقة انفتاح الثمرة قد تساعد أيضاً على انتشار البذور.
- أكد المدرس أهمية حفظ التعاليل والتعدادات كما وردت في المنهج وعدم الخروج عن أمثلته.

