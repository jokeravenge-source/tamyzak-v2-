# المحاضرة العاشرة – الجسيمات الحالة (Lysosomes)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة الجسيمات الحالة بوصفها حويصلات محاطة بغشاء واحد وتحتوي على أكثر من 40 نوعاً من الإنزيمات الحالة. تؤدي هذه العضيات الهضم داخل الخلية، وتنظف السيتوبلازم، وتسهم في التحول الشكلي والتحلل الذاتي وإعادة تدوير المواد في الطبيعة.

## 📚 التركيب والموقع

### 1. تعريف الجسيم الحال

- الجسيمات الحالة (Lysosomes) حويصلات (Vesicles) توجد داخل الخلية.
- يحاط كل جسيم حال بغشاء واحد (Single Membrane).
- يحتوي على أكثر من 40 نوعاً من الإنزيمات الحالة أو المحللة (Lytic/Hydrolytic Enzymes).

### 2. الوظيفة العامة

- الوظيفة العامة للجسيمات الحالة هي الهضم داخل الخلية (Intracellular Digestion).
- تعمل الإنزيمات داخل الخلية التابعة لها، ولا تنتقل لهضم خلية مجاورة.
- قد تهضم مادة دخلت الخلية، أو تركيباً تالفاً، أو محتويات الخلية نفسها عندما يصدر أمر التحلل الذاتي.

### 3. موقعها وانتشارها

- توجد في معظم الخلايا حقيقية النواة، وليس في جميعها بصورة مطلقة.
- ذكرت المحاضرة الخمائر مثالاً لخلايا لا تحتوي على جسيمات حالة.
- تكون واضحة وكثيرة في الخلايا القادرة على البلعمة (Phagocytosis).
- من أمثلتها الخلايا العدلة (Neutrophils)، وهي نوع من خلايا الدم البيضاء.
- تبتلع الخلايا العدلة الميكروبات مثل البكتيريا، ثم تهضمها الجسيمات الحالة وتقتلها.

## 🧹 وظائف الجسيمات الحالة

### 1. عامل تنظيف للخلية

تنظف الجسيمات الحالة سيتوبلازم الخلية بهضم:

- جزيئات الغذاء.
- العضيات التالفة مثل المايتوكوندريا.
- الأحياء المجهرية التي تدخل الخلية.
- المواد عديمة الفائدة والشوائب الأخرى.

ولهذا توصف بأنها **عامل نظافة الخلية (Cell Cleaner)**.

### 2. دورها في التحول الشكلي

- التحول الشكلي (Metamorphosis) هو تحول الحيوان من شكل إلى شكل آخر أثناء نموه.
- المثال الأساسي هو اختفاء ذيل يرقة الضفدع عند تحولها إلى ضفدع بالغ.
- تطلق الجسيمات الحالة إنزيماتها داخل خلايا الذيل.
- تهضم الإنزيمات محتويات كل خلية وعضياتها، فتتحلل الخلايا ويختفي الذيل تدريجياً.
- يحدث الهضم داخل الخلية نفسها، ولا تهضم الإنزيمات الخلايا المجاورة عشوائياً.

### 3. تحطيم الخلايا الميتة أو التالفة

- تحطم الجسيمات الحالة الخلايا بعد موتها أو تلفها.
- تساعد بذلك على تنظيف المكان وإتاحة المجال لتكوين خلايا جديدة.
- تتم العملية بإطلاق الإنزيمات الحالة وهضم مكونات الخلية.

### 4. إعادة تدوير المواد في الطبيعة

- تسهم الجسيمات الحالة في تحلل أجسام الكائنات بعد موتها.
- تحول عملية التحلل المواد العضوية إلى مواد أبسط يمكن أن تعود إلى البيئة.
- تستفيد كائنات حية أخرى من هذه المواد، فيتحقق التوازن وإعادة التدوير في الطبيعة.

## ♻️ التحلل الذاتي (Autolysis)

- التحلل الذاتي هو هضم الخلية لمحتوياتها بوساطة إنزيمات جسيماتها الحالة.
- يقتصر تأثير الإنزيمات على الخلية التي أطلقتها وفق تنظيم الخلية.
- يرتبط التحلل الذاتي بـ:
  - اختفاء أعضاء مؤقتة أثناء التحول الشكلي، مثل ذيل يرقة الضفدع.
  - التخلص من الخلايا الميتة أو التالفة.
  - تحلل أجسام الكائنات بعد موتها.
  - إعادة تدوير المواد في الطبيعة.

## 🍽️ آلية هضم مادة داخل الخلية

1. يحيط الغشاء البلازمي بالمادة الصلبة الداخلة إلى الخلية.
2. تتكون فجوة (Vacuole) تحتوي على المادة.
3. يتحرك الجسيم الحال باتجاه الفجوة ويلتحم بها.
4. يطلق الجسيم الحال إنزيماته المحللة داخل الفجوة.
5. تهضم المادة وتتحول إلى مواد أبسط أو سائلة.
6. تنتقل المواد المفيدة إلى السيتوبلازم لتستفيد منها الخلية.

**سلسلة الحفظ:**

مادة تدخل الخلية ← فجوة ← التحام الجسيم الحال ← إطلاق الإنزيمات ← هضم المادة ← استفادة الخلية

## 🧬 علاقة الشبكة الإندوبلازمية وجهاز كولجي

- تنتقل حويصلات من الشبكة الإندوبلازمية الخشنة والملساء إلى جهاز كولجي.
- يعالج جهاز كولجي المواد ويعبئها في حويصلات.
- قد تتجه بعض الحويصلات نحو الغشاء البلازمي لإفراز محتوياتها خارج الخلية.
- تتكون الجسيمات الحالة في صورة حويصلات تحمل الإنزيمات اللازمة للهضم داخل الخلية.

## ✏️ الرسم والتأشيرات المهمة

عند رسم آلية عمل الجسيم الحال يفضل ترتيب الأجزاء كما يأتي:

1. الغشاء البلازمي (Plasma Membrane).
2. النواة والنوية (Nucleus and Nucleolus).
3. الشبكة الإندوبلازمية الخشنة والملساء.
4. جهاز كولجي.
5. الحويصلات الخارجة من الشبكة والمتجهة إلى كولجي.
6. الجسيم الحال المحاط بغشاء واحد.
7. الفجوة المحتوية على المادة الداخلة.
8. التحام الجسيم الحال بالفجوة وهضم محتوياتها.

