# المحاضرة السادسة والعشرون – الأيض: الهدم والبناء

## 🧭 نظرة عامة

تربط هذه المحاضرة بين نوعين متكاملين من عمليات الأيض:

1. **عمليات الهدم (Catabolism):** تفكيك المواد المعقدة مثل الجلوكوز وتحرير الطاقة.
2. **عمليات البناء (Anabolism):** تكوين مواد عضوية معقدة من مواد أبسط مع استهلاك الطاقة.

وتستخدم المحاضرة التنفس الخلوي مثالاً للهدم، والتركيب الضوئي واختزال ثاني أوكسيد الكربون مثالاً للبناء.

# أولاً: مصير حامض البيروفيك

بعد التحلل السكري يتكون جزيئان من حامض البيروفيك من جزيء جلوكوز واحد.

| الحالة | مصير حامض البيروفيك |
|---|---|
| غياب الأوكسجين | يدخل في التخمر الكحولي أو تخمر حامض اللاكتيك |
| توفر الأوكسجين | ينتقل إلى المايتوكوندريا ويدخل المسار الهوائي ودورة كربس |

يتحول كل جزيء من حامض البيروفيك إلى جزيء أسيتيل يدخل دورة كربس؛ لذلك يؤدي جزيئا البيروفيك الناتجان من جزيء جلوكوز واحد إلى دوران دورة كربس مرتين.

**قاعدة الحفظ:**

1 Glucose → 2 Pyruvic Acid → 2 Acetyl Units → 2 Krebs Cycles

# ثانياً: الهدم والتنفس الخلوي

## 1. المعادلة العامة للتنفس الهوائي

وفق حساب الطاقة المعتمد في المنهج:

Glucose + Oxygen → Carbon Dioxide + Water + 38 ATP

وبالصيغة الرمزية:

C₆H₁₂O₆ + 6O₂ → 6CO₂ + 6H₂O + 38 ATP

## 2. لماذا يعد التنفس عملية هدم؟

- يبدأ بمادة عضوية معقدة هي الجلوكوز.
- يكسر الجلوكوز إلى مواد أبسط.
- يحرر الطاقة ويخزن جزءاً منها في ATP.
- ينتج فضلات أهمها CO₂، إضافة إلى الماء.

## 3. الناتج المطلوب والفضلات

| الناتج | أهميته أو مصيره |
|---|---|
| ATP | الطاقة التي تستفيد منها الخلية |
| CO₂ | الفضلة الرئيسة المؤكد عليها في المحاضرة، وتطرح مع الزفير في الإنسان |
| H₂O | ناتج أيضي؛ وقد يطرح الزائد منه بطرائق متعددة مثل البول والعرق وبخار الماء |

## 4. استعمالات طاقة ATP

لا يكفي في الإجابة القول إن الخلية تستفيد من الطاقة بصورة عامة؛ ومن أمثلة استعمالها:

1. حركة العضلات.
2. تشغيل العمليات المختلفة في خلايا وأعضاء الجسم.
3. إتمام العمليات البيولوجية المعقدة التي تحتاج إلى طاقة.

# ثالثاً: الاستفادة من ثاني أوكسيد الكربون

يعد CO₂ فضلة لعمليات الهدم في كثير من الكائنات، لكنه مادة أولية مهمة للنباتات.

- تطلق الحيوانات والإنسان CO₂ الناتج من التنفس إلى الهواء.
- تمتص النباتات CO₂ من الهواء.
- يدخل الغاز إلى الورقة عبر الثغور (Stomata).
- تستعمله الخلية النباتية في عمليات البناء خلال التركيب الضوئي.

# رابعاً: تثبيت واختزال CO₂

## 1. لماذا يجب تثبيت CO₂؟

ثاني أوكسيد الكربون غاز يمكنه الدخول والخروج بسهولة عبر الثغور؛ لذلك تحول الخلية النباتية CO₂ إلى مادة عضوية غير غازية للاحتفاظ بكربونه داخل الخلية.

تسمى هذه العملية **اختزال أو تثبيت ثاني أوكسيد الكربون (CO₂ Reduction/Fixation)**.

## 2. النتيجة

يتحول كربون CO₂ إلى:

- سكر (Sugar).
- كربوهيدرات (Carbohydrate).
- مادة عضوية (Organic Material).

## 3. المعادلة العامة للتركيب الضوئي

Carbon Dioxide + Water + Solar Energy → Glucose + Oxygen

وبالصيغة الرمزية:

6CO₂ + 6H₂O + Light Energy → C₆H₁₂O₆ + 6O₂

# خامساً: لماذا يعد التركيب الضوئي عملية بناء؟

- يبدأ بمواد بسيطة: CO₂ والماء.
- يكون مادة معقدة هي الجلوكوز.
- يحتاج إلى طاقة ضوئية.
- يخزن الطاقة في الروابط الكيميائية للمادة العضوية.

**سلسلة الحفظ:**

مواد بسيطة + طاقة → مادة عضوية معقدة

# سادساً: دور البلاستيدة الخضراء

تحدث عملية التركيب الضوئي في البلاستيدة الخضراء (Chloroplast)، التي تضم منطقتين أساسيتين:

| التركيب | دوره في التركيب الضوئي |
|---|---|
| الكرانا (Grana) | تضم أغشية الثايلاكويد التي تحتوي على الكلوروفيل، وتحدث عليها التفاعلات الضوئية |
| الستروما (Stroma) | الحشوة التي تحدث فيها تفاعلات اختزال CO₂ وتكوين السكر |

# سابعاً: التفاعلات الضوئية (Light Reactions)

## المكان

تحدث على أغشية الثايلاكويد المكوِّنة للكرانا.

## الخطوات الرئيسة

1. يمتص الكلوروفيل ضوء الشمس.
2. تنشّط الطاقة الضوئية جزيئات الكلوروفيل.
3. يستعمل جزء من الطاقة في شطر الماء.
4. يتحرر الأوكسجين بوصفه ناتجاً جانبياً.
5. ينقل الهيدروجين والإلكترونات بواسطة نواقل مناسبة.
6. تتحول الطاقة الضوئية إلى طاقة كيميائية قابلة للاستعمال في المرحلة التالية.

**التحول الطاقي:**

Light Energy → Chemical Energy

# ثامناً: التفاعلات اللاضوئية (Dark Reactions)

## المكان

تحدث في الستروما.

## الفكرة الأساسية

- تستخدم الطاقة الكيميائية المتكونة في التفاعلات الضوئية.
- تستعمل CO₂ مادة أولية.
- تختزل CO₂ وتثبته في صورة مركبات عضوية.
- ينتهي المسار بتكوين السكر.

لا يعني اسم التفاعلات اللاضوئية أنها لا تحدث إلا ليلاً، بل يعني أنها لا تعتمد مباشرة على الضوء، وإنما تعتمد على الطاقة الكيميائية التي كوّنتها التفاعلات الضوئية.

# تاسعاً: مقارنة الهدم بالبناء

| وجه المقارنة | الهدم (Catabolism) | البناء (Anabolism) |
|---|---|---|
| طبيعة العملية | تفكيك مواد معقدة | تكوين مواد معقدة |
| الطاقة | يحرر الطاقة | يحتاج إلى الطاقة |
| المثال | التنفس الخلوي | التركيب الضوئي |
| تحول الكربون | جلوكوز → CO₂ | CO₂ → جلوكوز |
| المواد | معقدة إلى بسيطة | بسيطة إلى معقدة |

