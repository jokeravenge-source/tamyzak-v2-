- رؤية العضيات الداخلية أو الفيروسات أو الجزيئات العضوية ⟵ المجهر الإلكتروني.

### مثال 2: التركيب الكيميائي لجدار البكتيريا

- **المطلوب:** ذكر مكونات الجدار.
- **الإجابة:** بروتينات + دهون + سكريات متعددة.

### مثال 3: رسم البكتيريا

- نرسم الكبسولة، ثم جدار الخلية، ثم الغشاء البلازمي، ثم السيتوبلازم والنيوكليويد والريبوسومات، ثم نضيف الفيمبريا والأسواط.

