# محاضرة 2 – الفصل الأول: حجم الخلية والخلايا بدائية النواة

## 🧭 نظرة عامة سريعة

تتناول المحاضرة أحجام الخلايا، والمجهر الضوئي (Light Microscope) والمجهر الإلكتروني (Electron Microscope)، ثم تشرح الخلايا بدائية النواة (Prokaryotic Cells) مع صفات البكتيريا (Bacteria) وتركيبها ورسمها، وأهم الفروق بين الطحالب الخضر المزرقة والبكتيريا.

## 📚 المفاهيم والشرح التفصيلي

### 1. حجم الخلية (Cell Size)

- تختلف الخلايا في أحجامها، لكن معظمها صغير ويحتاج إلى مجهر لرؤيته.
- بيضة الضفدع (Frog Egg) مثال يمكن رؤيته بالعين المجردة، وقطرها **1 مليمتر (1 mm)**.
- الخلية البشرية (Human Cell) قد يكون حجمها **100 ميكرومتر (100 µm) أو أقل**.
- يجب حفظ الرقم مع وحدته؛ فقد يأتي في سؤال فراغات.

### 2. التراكيب الخاصة في الخلية

تمتلك الخلايا مكونات وتراكيب خاصة تزيد كفاءة أداء وظائفها المختلفة؛ فكل تركيب يمتلك صفات تساعد الخلية على إنجاز عملها بكفاءة أعلى.

⚠️ **تعليل مهم:** تمتلك الخلايا صفات وتراكيب مميزة حتى تزيد كفاءة عمل الخلية.

### 3. المجاهر

#### المجهر الضوئي (Light Microscope)

- يُظهر الخلية وشكلها وحجمها الخارجي.
- لا يُظهر التراكيب الداخلية الدقيقة بوضوح.

#### المجهر الإلكتروني (Electron Microscope)

يُستخدم لرؤية:

1. العضيات الداخلية (Internal Organelles)، مثل المايتوكوندريا (Mitochondria).
2. الفيروسات (Viruses).
3. الأجزاء أو الجزيئات العضوية (Organic Parts/Molecules).

⚠️ **وزاري:** يمكن رؤية الخلية بالمجهر الضوئي، أما التراكيب الداخلية الدقيقة فتحتاج إلى المجهر الإلكتروني.

### 4. الخلايا بدائية النواة (Prokaryotic Cells)

- توصف بأنها غير متطورة أو بدائية.
- مادتها النووية غير محاطة بغشاء نووي (Nuclear Membrane) أو غلاف نووي (Nuclear Envelope).
- توجد المادة النووية في منطقة تسمى المنطقة النووية (Nuclear Region) أو النيوكليويد (Nucleoid Zone).
- لا تمتلك عضيات غشائية (Membrane-bound Organelles).
- تحتوي على الريبوسومات (Ribosomes)، وهي حبيبات صغيرة كثيرة العدد وغير محاطة بغشاء.

### 5. أمثلة بدائيات النواة

الأمثلة المحفوظة هي:

1. الطحالب الخضر المزرقة (Blue-green Algae).
2. البكتيريا (Bacteria).
3. المايكوبلازما (Mycoplasma).

وتتبع هذه الأمثلة مملكة المنيرة (Kingdom Monera).

### 6. البكتيريا (Bacteria)

البكتيريا خلية بدائية النواة، وتتكون من التراكيب الآتية:

#### أ. الكبسولة (Capsule)

- قد تحيط بالخلية البكتيرية من الخارج، لكنها لا تكون موجودة دائماً.
- تتكون عند سوء الظروف البيئية، مثل ارتفاع أو انخفاض الحرارة الشديد أو عدم توفر الغذاء.
- وظيفتها حماية الخلية من الهلاك أو الموت.

#### ب. جدار الخلية (Cell Wall)

- جدار خارجي صلب (Solid Cell Wall) يحيط بالخلية البكتيرية.
- تركيبه الكيميائي يتكون من البروتينات (Proteins)، والدهون (Lipids)، والسكريات المتعددة (Polysaccharides).

⚠️ عند السؤال عن التركيب الكيميائي لجدار الخلية البكتيرية، تُذكر هذه المكونات الثلاثة.

#### ج. الغشاء البلازمي (Plasma Membrane/Plasmalemma)

- يقع تحت جدار الخلية ويحيط بالسيتوبلازم (Cytoplasm).
- هو غشاء شبه منفذ (Semipermeable) وانتقائي النفاذية (Selectively Permeable).
- يسمح بدخول المواد المفيدة التي تحتاج إليها الخلية، ويُخرج المواد الضارة أو غير اللازمة.

#### د. السيتوبلازم (Cytoplasm)

- يوجد داخل الغشاء البلازمي.
- في الخلية البكتيرية توجد فيه المنطقة النووية (Nucleoid) والريبوسومات (Ribosomes).
- لا توجد فيه عضيات غشائية.

#### هـ. الريبوسومات (Ribosomes)

- حبيبات صغيرة كثيرة العدد.
- غير محاطة بغشاء (Non-membranous).

#### و. ملحقات الخلية (Cell Appendages)

1. الأسواط (Flagella): طويلة وتساعد على الحركة.
2. الأهداب (Cilia): قصيرة ومنتشرة على جسم الخلية.
3. الفيمبريا أو الأهداب الجنسية (Fimbriae/Sex Pili): ملحقات جنسية.

### 7. الفرق بين الطحالب الخضر المزرقة والبكتيريا

| وجه المقارنة | الطحالب الخضر المزرقة | البكتيريا |
|---|---|---|
| الكلوروفيل (Chlorophyll) | تحتوي على كلوروفيل | لا تحتوي على كلوروفيل وفق المقارنة في المحاضرة |
| الغلاف الخارجي | قشرة جيلاتينية (Gelatinous Covering) | كبسولة (Capsule) عند الظروف غير الملائمة |

### 8. رسم الخلية البكتيرية

يرسم الطالب التراكيب من الخارج إلى الداخل كالآتي:

1. الكبسولة (Capsule) إن وُجدت.
2. جدار الخلية الصلب (Cell Wall).
3. الغشاء البلازمي (Plasma Membrane).
4. السيتوبلازم (Cytoplasm).
5. النيوكليويد أو المنطقة النووية (Nucleoid).
6. الريبوسومات (Ribosomes) على شكل حبيبات.
7. الفيمبريا/الأهداب الجنسية قصيرة ومنتشرة.
8. الأسواط طويلة للحركة.

## 📖 التعريفات والمصطلحات

- **الخلية بدائية النواة (Prokaryotic Cell):** خلية لا تكون مادتها النووية محاطة بغشاء نووي ولا تحتوي على عضيات غشائية.
- **النيوكليويد (Nucleoid):** المنطقة التي توجد فيها المادة النووية في الخلية بدائية النواة.
- **المجهر الضوئي (Light Microscope):** مجهر يُظهر الخلية وشكلها وحجمها الخارجي.
- **المجهر الإلكتروني (Electron Microscope):** مجهر يُظهر التراكيب الداخلية الدقيقة والفيروسات والجزيئات العضوية.
- **الكبسولة (Capsule):** غلاف قد يحيط بالبكتيريا عند الظروف غير الملائمة ويحميها.
- **جدار الخلية (Cell Wall):** غلاف خارجي صلب يحيط بالخلية البكتيرية.
- **الغشاء البلازمي (Plasma Membrane):** غشاء شبه منفذ وانتقائي ينظم دخول المواد وخروجها.
- **السيتوبلازم (Cytoplasm):** المادة الداخلية التي توجد فيها المنطقة النووية والريبوسومات.
- **الريبوسومات (Ribosomes):** حبيبات صغيرة كثيرة العدد وغير غشائية.
- **الأسواط (Flagella):** تراكيب طويلة تساعد البكتيريا على الحركة.
- **الأهداب (Cilia):** تراكيب قصيرة تنتشر على جسم الخلية.
- **الفيمبريا/الأهداب الجنسية (Fimbriae/Sex Pili):** ملحقات جنسية في الخلية البكتيرية.

## 🔢 القوانين / الصيغ / القواعد

- قطر بيضة الضفدع = **1 mm**.
- حجم الخلية البشرية = **100 µm أو أقل**.
- الخلية بدائية النواة = مادة نووية غير محاطة بغشاء + نيوكليويد + ريبوسومات + لا عضيات غشائية.
- جدار البكتيريا = بروتينات + دهون + سكريات متعددة.

