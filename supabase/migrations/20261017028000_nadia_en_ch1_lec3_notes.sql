# محاضرة 3 – الفصل الأول: الخلايا حقيقية النواة وجدار الخلية النباتية

## 🧭 نظرة عامة سريعة

تشرح المحاضرة الفرق بين الخلايا بدائية النواة (Prokaryotic Cells) والخلايا حقيقية النواة (Eukaryotic Cells)، وممالك الكائنات التي تضم الخلايا حقيقية النواة، وأشكالها وأحجامها، ثم تبدأ بدراسة مكونات الخلية حقيقية النواة، مع التركيز على جدار الخلية النباتية (Plant Cell Wall) وموقعه ووظائفه ومكوناته: الصفيحة الوسطى، والجدار الأولي، والجدار الثانوي، وتركيبها الكيميائي.

## 📚 المفاهيم والشرح التفصيلي

### 1. الخلايا حقيقية النواة (Eukaryotic Cells)

- الخلايا حقيقية النواة هي المقابل للخلايا بدائية النواة (Prokaryotic Cells).
- تمتلك نواة حقيقية (True Nucleus) محاطة بغشاء، وتمتلك عضيات غشائية (Membrane-bound Organelles).
- الممالك الأربع التي ذُكرت وتضم كائنات حقيقية النواة هي:
  1. مملكة الطلائعيات (Protista).
  2. مملكة الفطريات (Fungi).
  3. مملكة النباتات (Plants).
  4. مملكة الحيوانات (Animals).

⚠️ **تنبيه:** جميع الخلايا التابعة لهذه الممالك هي خلايا حقيقية النواة.

### 2. أشكال الخلايا حقيقية النواة

تختلف أشكال خلايا الكائنات الحية حقيقية النواة، ومن الأشكال المذكورة:

- كروية (Spherical).
- بيضوية (Oval).
- مكعبة (Cubical).
- نجمية (Stellate).
- مغزلية (Fusiform).
- أنبوبية (Tubular).

### 3. تغير شكل الخلية: مثال الأميبا

- الأميبا (Amoeba) كائن حي وحيد الخلية (Unicellular Organism).
- لا يكون شكلها ثابتاً، بل تستطيع تغييره من وقت إلى آخر.
- تغيّر الأميبا شكلها بوصفه تكيفاً (Adaptation) لأداء وظيفة معينة.

⚠️ **تعليل مهم:** تغيّر بعض الكائنات الحية شكلها لأن تغيير الشكل تكيف يساعدها على أداء وظيفة معينة.

### 4. حجم الخلايا حقيقية النواة ومساحة السطح

- الخلايا حقيقية النواة أكبر عموماً من الخلايا بدائية النواة.
- قد تكون الخلية حقيقية النواة وحيدة الخلية، ومع ذلك تحتاج إلى مجهر (Microscope) لرؤيتها.
- كِبَر الخلية يؤدي إلى زيادة مساحة سطحها (Surface Area).
- زيادة مساحة السطح تعني زيادة مساحة الغشاء البلازمي (Plasma Membrane).
- تحتاج الخلية إلى مساحة سطح واسعة لكي تزيد عملية تبادل المواد (Exchange of Materials) بينها وبين البيئة المحيطة.
- تحتاج الخلايا النباتية والحيوانية إلى تبادل المواد مع البيئة، ولذلك ترتبط زيادة مساحة السطح بكفاءة وظائفها.

⚠️ **تعليل مهم:** تحتاج الخلايا حقيقية النواة إلى مساحة سطح أكبر لتوفير مساحة كافية لتبادل المواد بينها وبين البيئة.

### 5. الأجزاء الرئيسة في الخلية حقيقية النواة

الأجزاء الرئيسة التي ركزت عليها المحاضرة هي:

1. الغشاء البلازمي (Plasma Membrane).
2. السيتوبلازم (Cytoplasm).
3. النواة (Nucleus).

#### أ. الخلية النباتية والخلية الحيوانية

- الخلية النباتية (Plant Cell) تمتلك جدار خلية (Cell Wall) خارج الغشاء البلازمي.
- الخلية الحيوانية (Animal Cell) تمتلك الغشاء البلازمي فقط من جهة الغلاف الخارجي، ولا تمتلك جدار خلية.
- الغشاء البلازمي موجود في الخلايا النباتية والحيوانية.
- السيتوبلازم والنواة من المكونات الرئيسة في كلا النوعين.

### 6. جدار الخلية النباتية (Plant Cell Wall)

#### أ. الموقع والعلاقة بالغشاء البلازمي

- يحيط جدار الخلية بالخلية النباتية من الخارج.
- يغلف الغشاء البلازمي (Plasma Membrane)، ويكون الغشاء البلازمي إلى الداخل منه.
- لذلك يكون ترتيب الغلاف من الخارج إلى الداخل: جدار الخلية ثم الغشاء البلازمي ثم السيتوبلازم.

#### ب. الوظيفة

- الوظيفة الرئيسة لجدار الخلية هي الحماية (Protection) والدعم (Support).
- يحمي ما يقع داخل الخلية النباتية، ولا سيما الغشاء البلازمي والسيتوبلازم.
- يمنح الأجزاء الداخلية دعماً ويحافظ على الخلية النباتية.

#### ج. طبيعة الجدار النباتي مقارنة بالبكتيري

- جدار الخلية البكتيرية (Bacterial Cell Wall) صلب (Solid Wall).
- جدار الخلية النباتية سميك (Thick Wall) لكنه ليس صلباً بالمعنى الذي ركز عليه المدرس عند وصف الجدار البكتيري؛ ويرتبط ذلك بالمواد التي يتكون منها.

### 7. مكونات جدار الخلية النباتية

يتكون جدار الخلية النباتية من ثلاث طبقات/أجزاء مهمة:

1. الصفيحة الوسطى (Middle Lamella).
2. الجدار الأولي (Primary Wall).
3. الجدار الثانوي (Secondary Wall).

#### أ. الصفيحة الوسطى (Middle Lamella)

- تقع بين جدار خلية نباتية وجدار الخلية النباتية المجاورة.
- تفصل بين الجدارين وتربط الخلايا النباتية المتجاورة ضمن النسيج النباتي.

#### ب. الجدار الأولي (Primary Wall)

- يوجد في الخلايا الفتية أو الصغيرة التي ما زالت في طور النمو الأولي (Primary Growth).
- يُعد جزءاً من جدار الخلية في بداية نمو النبات.
- عند السؤال عن التركيب الكيميائي للخلايا الفتية، يكون السليلوز (Cellulose) هو المادة المذكورة.

#### ج. الجدار الثانوي (Secondary Wall)

- يتكون عندما تكبر الخلية ويزداد عمرها، أي عندما تصبح أقدم (Older).
- يُضاف إلى السليلوز مادة أخرى هي اللجنين (Lignin).
- يؤدي وجود اللجنين إلى زيادة سمك الجدار، ولذلك يدل ظهور الطبقة الثانوية على أن الخلية أكبر عمراً.

### 8. التركيب الكيميائي لجدار الخلية النباتية

- في الخلية الفتية: يتكون الجدار من السليلوز (Cellulose).
- في الخلية الأكبر عمراً: يضاف اللجنين (Lignin) إلى السليلوز.
- لذلك تكون الصيغة الوصفية للخلية القديمة: **سليلوز + لجنين**.

⚠️ **تنبيه وزاري:** إذا سأل السؤال عن نوع الجدار، أجب بالصفيحة الوسطى والجدار الأولي والجدار الثانوي. أما إذا سأل عن التركيب الكيميائي، فأجب بالسليلوز، ويضاف اللجنين عند كون الخلية أكبر عمراً.

## 📖 التعريفات والمصطلحات

- **الخلايا حقيقية النواة (Eukaryotic Cells):** خلايا تمتلك نواة حقيقية وعضيات غشائية، وتوجد في الطلائعيات والفطريات والنباتات والحيوانات.
- **النواة الحقيقية (True Nucleus):** نواة محاطة بغشاء نووي داخل الخلية.
- **العضيات الغشائية (Membrane-bound Organelles):** تراكيب خلوية محاطة بأغشية داخل الخلية حقيقية النواة.
- **الكائن وحيد الخلية (Unicellular Organism):** كائن يتكون من خلية واحدة، مثل الأميبا.
- **التكيف (Adaptation):** تغير أو صفة تساعد الكائن الحي على أداء وظيفة معينة.
- **مساحة السطح (Surface Area):** المساحة المتاحة على سطح الخلية، وزيادتها تساعد على تبادل المواد.
- **جدار الخلية (Cell Wall):** غلاف خارجي يحيط بالخلية النباتية ويوفر لها الحماية والدعم.
- **الصفيحة الوسطى (Middle Lamella):** طبقة تقع بين جدارَي خليتين نباتيتين متجاورتين.
- **الجدار الأولي (Primary Wall):** جدار يوجد في الخلايا الفتية أثناء النمو الأولي.
- **الجدار الثانوي (Secondary Wall):** جدار يضاف عند تقدم الخلية في العمر، ويرتبط بإضافة اللجنين إلى السليلوز.
- **السليلوز (Cellulose):** مادة مذكورة بوصفها مكوناً كيميائياً لجدار الخلية، ولا سيما في الخلايا الفتية.
- **اللجنين (Lignin):** مادة تضاف إلى السليلوز في الخلايا الأكبر عمراً، فتزيد سمك الجدار.

## 🔢 القوانين / الصيغ / القواعد

- الخلية حقيقية النواة = نواة حقيقية + عضيات غشائية.
- الخلية النباتية = جدار خلية + غشاء بلازمي + سيتوبلازم + نواة.
- الخلية الحيوانية = غشاء بلازمي + سيتوبلازم + نواة، ولا يوجد جدار خلية.
- ترتيب الغلاف النباتي من الخارج إلى الداخل = جدار الخلية ← الغشاء البلازمي ← السيتوبلازم.
- مكونات جدار الخلية النباتية = صفيحة وسطى + جدار أولي + جدار ثانوي.
- الخلية الفتية: سليلوز.
- الخلية الأكبر عمراً: سليلوز + لجنين.

