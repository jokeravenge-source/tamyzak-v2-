# المحاضرة السابعة والعشرون – الطور البيني والطور التمهيدي

## 🧭 نظرة عامة

تبدأ المحاضرة بمراجعة أنواع الانقسام، ثم تشرح استعداد الخلية للانقسام الخيطي المتساوي خلال الطور البيني، وبعده أحداث الطور التمهيدي بوصفه أول أطوار الانقسام النووي.

# أولاً: مراجعة أنواع الانقسام

## 1. الانقسام المباشر (Amitosis/Direct Division)

- يحدث دون تغيرات نووية واضحة ومعقدة.
- تنقسم المادة النووية ثم السيتوبلازم بصورة مباشرة نسبياً.
- من أمثلته الانقسام في البكتيريا بحسب تصنيف المنهج.

## 2. الانقسام الخيطي المتساوي (Mitosis)

- يسمى انقساماً غير مباشر لأنه يمر بأطوار متتابعة.
- يسمى خيطياً لظهور خيوط المغزل.
- يحدث في الخلايا الجسمية (Somatic Cells).
- تنتج منه خليتان تشبهان الخلية الأم في عدد الكروموسومات ونوعها.
- في الإنسان تحمل كل خلية جسمية ناتجة 46 كروموسوماً.

## 3. الانقسام الاختزالي (Meiosis)

- نوع آخر من الانقسام يرتبط بتكوين الخلايا الجنسية.
- يختلف في غايته ونواتجه عن الانقسام الخيطي المتساوي.

# ثانياً: الطور البيني (Interphase)

## 1. تعريفه وموقعه

الطور البيني طور تحضيري تتهيأ خلاله الخلية للانقسام، لكنه **ليس واحداً من أطوار الانقسام الخيطي الأربعة**.

- يسبق الطور التمهيدي.
- تظهر فيه علامات تدل على استعداد الخلية للانقسام.
- تبقى المادة الوراثية في صورة خيوط كروماتين غير متكثفة.

## 2. أحداث الطور البيني الأربعة

### الحدث الأول: ازدياد حجم النواة

- تكون نواة الخلية المستعدة للانقسام أكبر حجماً مقارنة بأنوية الخلايا غير المستعدة.
- يمكن ملاحظة هذه الصفة عند مقارنة خلايا متعددة تحت المجهر.

### الحدث الثاني: تصنيع مواد البناء

تصنع الخلية كميات كبيرة من:

- الأحماض النووية.
- البروتينات.
- السكريات ومواد أخرى تحتاج إليها للاستعداد للانقسام.

يجب أن يسبق تصنيع هذه المواد عملية تضاعف DNA لأنها تمثل المواد الأولية اللازمة للبناء.

### الحدث الثالث: تضاعف DNA

- يتضاعف DNA داخل خيوط الكروماتين.
- يحتوي كل خيط كروماتين بعد التضاعف على النسخة الأصلية ونسخة مطابقة جديدة.
- لا تكون المادة الوراثية في هذه المرحلة كروموسومات قصيرة واضحة بعد، بل تبقى خيوط كروماتين.
- الهدف هو توفير نسخة كاملة من المعلومات الوراثية لكل خلية بنت.

### الحدث الرابع: تضاعف الجسيم المركزي

- يتضاعف الجسيم المركزي (Centrosome) في الخلية الحيوانية.
- يصبح لدى الخلية جسمان مركزيان قبل بدء الانقسام النووي.
- يحدث **التضاعف** في الطور البيني، أما **الحركة نحو القطبين** فتحدث في الطور التمهيدي.

## 3. لماذا يتضاعف DNA؟

لأن الخلية الأم ستنتج خليتين بنتين، وكل خلية تحتاج إلى نسخة كاملة ومتماثلة من المادة الوراثية وعدد الكروموسومات نفسه.

## 4. ملاحظات الرسم في الطور البيني

- ترسم نواة كبيرة واضحة.
- يرسم الغشاء النووي والنوية بصورة واضحة.
- تمثل المادة الوراثية بخيوط كروماتين، لا بكروموسومات X متكثفة.
- يمكن تبسيط الرسم باستعمال أربعة خيوط كروماتين بدلاً من رسم 46 كروموسوماً.
- يرسم جسيمان مركزيان بعد تضاعف الجسيم المركزي.

# ثالثاً: أطوار الانقسام الخيطي

بعد انتهاء الطور البيني تبدأ مراحل الانقسام النووي الأربعة بالترتيب:

1. الطور التمهيدي (Prophase).
2. الطور الاستوائي (Metaphase).
3. الطور الانفصالي (Anaphase).
4. الطور النهائي (Telophase).

يتبع الانقسام النووي عادة انقسام السيتوبلازم (Cytokinesis).

# رابعاً: الطور التمهيدي (Prophase)

الطور التمهيدي هو أول أطوار الانقسام الخيطي المتساوي، وتحدث خلاله تغيرات واضحة في المادة الوراثية ومكونات النواة والجهاز المغزلي.

## 1. تكثف خيوط الكروماتين

- تتكثف خيوط أو شبكة الكروماتين.
- تصبح أقصر وأسمك وأكثر وضوحاً.
- تظهر على صورة كروموسومات متميزة تحت المجهر.

**Chromatin Threads → Short, Thick Chromosomes**

## 2. ظهور الكروماتيدين الشقيقين

- يظهر كل كروموسوم مكوناً من كروماتيدين شقيقين متماثلين.
- يمثل أحدهما المادة الأصلية والآخر النسخة الناتجة من تضاعف DNA.
- يحمل كل كروماتيد جزيء DNA.

## 3. ارتباط الكروماتيدين بالسنترومير

- يرتبط الكروماتيدان الشقيقان عند منطقة تسمى السنترومير (Centromere).
- يحافظ السنترومير على ارتباطهما إلى أن يحين وقت انفصالهما.

## 4. حركة الجسمين المركزيين

- يبدأ الجسمان المركزيان المتضاعفان بالحركة في اتجاهين متعاكسين.
- يصل كل واحد منهما إلى أحد قطبي الخلية.

**التمييز الامتحاني:**

- Centrosome duplication → Interphase.
- Centrosome movement to opposite poles → Prophase.

## 5. تكوين الألياف النجمية والمغزلية

يمتد من كل جسم مركزي نوعان من الخيوط:

### الألياف النجمية (Astral Fibers)

- خيوط قصيرة تنتشر حول الجسم المركزي بشكل نجمي.

### ألياف المغزل (Spindle Fibers)

- خيوط أطول تمتد باتجاه داخل الخلية.
- تسهم لاحقاً في حركة الكروموسومات وفصلها.

## 6. اختفاء النوية والغشاء النووي

- تبدأ النوية بالاختفاء.
- يبدأ الغشاء النووي بالتفكك تدريجياً.
- يختفيان بصورة كاملة مع نهاية الطور التمهيدي.

