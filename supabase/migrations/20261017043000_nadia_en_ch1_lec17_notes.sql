# المحاضرة السابعة عشرة – النفاذية وأنواع الأغشية

## 🧭 نظرة عامة

تشرح المحاضرة مفهوم النفاذية بوصفه تبادل المواد بين الخلية وبيئتها عبر الغشاء البلازمي. ثم تعرض شرط دخول المادة إلى الخلية وشرط خروجها منها، وتصنف الأغشية إلى أربعة أنواع بحسب قدرتها على السماح بمرور المواد، وتنتهي بالعوامل الداخلية والخارجية المؤثرة في نفاذية الغشاء.

## 1. تعريف النفاذية (Permeability)

النفاذية هي قابلية الغشاء للسماح بتبادل المواد بين الخلية وبيئتها عبر الغشاء البلازمي.

- قد تدخل مادة غذائية من الوسط المحيط إلى الخلية.
- وقد تخرج فضلات أو مواد أخرى من الخلية إلى الوسط الخارجي.
- لا تعبر جميع المواد بالطريقة أو المقدار نفسيهما؛ إذ تتحكم خصائص الغشاء وطبيعة المادة في العبور.

## 2. القاعدتان الأساسيتان للنفاذية

### القاعدة الأولى: دخول المادة إلى الخلية

لكي تدخل مادة موجودة في البيئة المحيطة:

1. تكون المادة خارج الخلية.
2. تذوب أولاً في الماء الموجود في الوسط المحيط.
3. تصبح في صورة مناسبة للعبور عبر الغشاء البلازمي.
4. تدخل إلى داخل الخلية.

**سلسلة الحفظ:** مادة خارجية ← تذوب في ماء الوسط ← تعبر الغشاء ← تدخل الخلية

### القاعدة الثانية: خروج المادة من الخلية

لكي تخرج مادة أو فضلات من داخل الخلية:

1. توجد المادة داخل السيتوبلازم.
2. تذوب في ماء السيتوبلازم.
3. تعبر الغشاء البلازمي.
4. تنتقل إلى البيئة الخارجية.

**سلسلة الحفظ:** مادة داخلية ← تذوب في ماء السيتوبلازم ← تعبر الغشاء ← تخرج من الخلية

## 3. أنواع الأغشية حسب النفاذية

### أ. الغشاء تام النفاذية (Permeable Membrane)

- يسمح بمرور المواد بحرية في الاتجاهين.
- لا يمنع الجزيئات بناءً على تركيبها أو حجمها في التعريف المبسط الوارد في المحاضرة.
- يحدث تبادل المواد عبره بسهولة.

### ب. الغشاء نصف النافذ (Semipermeable Membrane)

- يسمح بمرور المذيب بدرجة أكبر من المذاب.
- لا تمر جزيئات المذاب والمذيب بالمقدار نفسه.
- يكون مرور الماء، بوصفه المذيب، أكبر من مرور مواد مذابة مثل الملح أو السكر.
- ذُكر الغشاء البلازمي مثالاً في سياق المحاضرة.

### ج. الغشاء اختياري النفاذية (Selectively Permeable Membrane)

- يسمح بعبور مواد معينة ويمنع أو يحد من عبور مواد أخرى.
- يرتبط الاختيار بحجم الجزيئات وخصائصها وحاجة الخلية إليها.
- تمر المواد الصغيرة أو المناسبة للغشاء بسهولة أكبر من الجزيئات الكبيرة أو غير المناسبة.
- الغشاء البلازمي هو المثال الأساس.

### د. الغشاء غير النافذ (Impermeable Membrane)

- لا يسمح بمرور المواد عبره.
- المثال المذكور في المحاضرة: النايلون (Nylon).

