## 4. الفرق بين نصف النافذ واختياري النفاذية

### نصف النافذ

- يركز الوصف على الفرق بين مرور المذيب والمذاب.
- يعبر المذيب بمقدار أكبر من المذاب.

### اختياري النفاذية

- يركز الوصف على اختيار الغشاء للمواد.
- يعتمد المرور على صفات المادة، مثل الحجم والطبيعة الكيميائية، وعلى تنظيم الغشاء.

> قد يوصف الغشاء البلازمي بأنه نصف نافذ في سياقات مبسطة، لكن وصفه الأدق وظيفياً هو **اختياري النفاذية**.

## 5. العوامل المؤثرة في نفاذية الغشاء البلازمي

تتأثر النفاذية بعوامل داخلية وخارجية.

### العوامل الداخلية (Internal Factors)

- نوع المادة الموجودة داخل الخلية.
- كمية المادة وتركيزها.
- تركيب الغشاء وحالة الخلية.
- طبيعة السيتوبلازم ومحتواه المائي.

### العوامل الخارجية (External Factors)

- درجة الحرارة (Temperature).
- الأس الهيدروجيني (pH).
- كمية الماء في البيئة.
- توفر الأوكسجين.
- نوع المواد وتركيزها في الوسط المحيط.

## 6. العلاقة بين الانتشار والنفاذية

- النفاذية تصف قدرة الغشاء على السماح بمرور المواد.
- الانتشار يصف حركة الجزيئات أو الأيونات من تركيز عالٍ إلى تركيز منخفض.
- لكي تعبر مادة بالانتشار خلال الغشاء، يجب أن يسمح الغشاء بنفاذها.

## ⚠️ نقاط مهمة للحفظ

- النفاذية تبادل مواد بين الخلية وبيئتها عبر الغشاء البلازمي.
- المادة الداخلة تذوب أولاً في ماء الوسط الخارجي.
- المادة الخارجة تذوب أولاً في ماء السيتوبلازم.
- أنواع الأغشية أربعة: تام النفاذية، نصف نافذ، اختياري النفاذية، وغير نافذ.
- الغشاء نصف النافذ يسمح للمذيب أكثر من المذاب.
- الغشاء اختياري النفاذية يختار المواد بحسب خصائصها.
- الغشاء البلازمي اختياري النفاذية.
- النايلون مثال الغشاء غير النافذ المذكور في المحاضرة.
- تتأثر نفاذية الغشاء بعوامل داخلية وخارجية.

