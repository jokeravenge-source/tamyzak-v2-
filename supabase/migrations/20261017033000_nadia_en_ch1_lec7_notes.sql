# المحاضرة السابعة – جهاز كولجي (Golgi Apparatus)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة جهاز كولجي بوصفه جهازاً إفرازياً داخل الخلية، وتوضح سبب تسميته، وصعوبة تحديد موقعه، واختلاف شكله وحجمه بحسب نوع الخلية والكائن الحي. كما تشرح مكوناته الثلاثة ووظائفه في الخلايا الحيوانية والنباتية وعلاقته بالشبكة الإندوبلازمية الخشنة.

## 📚 المفاهيم والشرح التفصيلي

### 1. تعريف جهاز كولجي

- جهاز كولجي (Golgi Apparatus) جهاز إفرازي (Secretory Apparatus).
- لا تتمثل وظيفته الأساسية في إنتاج البروتين من البداية، بل يتعامل مع البروتينات القادمة من الشبكة الإندوبلازمية الخشنة ثم يهيئها للإفراز.
- يسهم في إفراز البروتينات والهرمونات والإنزيمات.

### 2. سبب التسمية والاكتشاف

- سُمي جهاز كولجي نسبة إلى العالم كاميلو كولجي (Camillo Golgi).
- وصفه عندما كان يدرس خلية عصبية (Neuron) باستعمال صبغة خاصة.
- لاحظ منطقة ذات تركيب مميز داخل الخلية الحيوانية، ثم وصف هذا التركيب الذي حمل اسمه.

### 3. موقع جهاز كولجي وشكله

- يوجد جهاز كولجي في أماكن محددة داخل الخلية، لكن يصعب تحديد موقع ثابت ودقيق له.
- يختلف موقعه باختلاف الخلية.
- يختلف شكله وحجمه بحسب:
  - نوع الخلية.
  - نوع الكائن الحي.
- لذلك لا يمكن اعتماد شكل أو حجم واحد ثابت لجهاز كولجي في جميع الخلايا.

## 🧬 مكونات جهاز كولجي

يتكون جهاز كولجي بصورة عامة من ثلاثة أجزاء، وتكون هذه الأجزاء محاطة بغشاء رقيق أملس.

### 1. الصهاريج (Cisternae)

- هي أكياس أو ردهات غشائية مفلطحة ومتراصة.
- يتراوح عددها عادةً بين 3 و10 صهاريج.
- يختلف عدد الصهاريج حسب نوع الخلية ونوع الكائن الحي.
- تمثل الصهاريج الجزء الأكثر وضوحاً وتمييزاً عند رسم جهاز كولجي.

### 2. الحويصلات (Vesicles)

- تراكيب صغيرة الحجم.
- تظهر قرب الصهاريج.
- تكون أصغر من الفجوات.

### 3. الفجوات (Vacuoles)

- تراكيب أكبر حجماً من الحويصلات.
- تمثل الجزء الثالث من مكونات جهاز كولجي.

## ⚙️ وظائف جهاز كولجي

### أولاً: في الخلية الحيوانية

- يستقبل البروتينات القادمة من الشبكة الإندوبلازمية الخشنة.
- يتعامل مع البروتينات ويكوّن منها تراكيب بروتينية معقدة قبل إفرازها.
- يفرز أنواعاً مختلفة من المواد، ومنها:
  - البروتينات.
  - الهرمونات.
  - الإنزيمات.
- لذلك يوصف بأنه جهاز إفرازي.

### العلاقة مع الشبكة الإندوبلازمية الخشنة

- تصنع الشبكة الإندوبلازمية الخشنة البروتينات وتنقلها.
- تصل هذه البروتينات إلى جهاز كولجي.
- يتولى جهاز كولجي تهيئتها وإفرازها.

**سلسلة سهلة للحفظ:**

الشبكة الإندوبلازمية الخشنة → بروتينات → جهاز كولجي → تهيئة وإفراز

### ثانياً: في الخلية النباتية

- يسمى التركيب المشابه لجهاز كولجي في الخلية النباتية الدكتيوسوم (Dictyosome).
- يسهم الدكتيوسوم في بناء السليلوز (Cellulose).
- يسهم أيضاً في بناء بعض مكونات جدار الخلية النباتية.

