# المحاضرة الثالثة عشرة – الفجوات والمتضمنات السيتوبلازمية

## 🧭 نظرة عامة

تشرح المحاضرة الفجوات بوصفها أكياساً غشائية توجد في الخلايا، ثم تميز أنواعها ووظائفها في الطليعيات والخلايا النباتية والحيوانية. كما تعرض المتضمنات السيتوبلازمية غير الحية، وطرق تكوّنها وأهم صورها وأمثلتها.

# أولاً: الفجوات (Vacuoles)

## 1. التعريف العام

- الفجوات أكياس غشائية (Membranous Sacs).
- يحيط بها غشاء يفصل محتوياتها عن السيتوبلازم.
- تختلف في الحجم والعدد والمحتوى والوظيفة بحسب نوع الخلية والكائن الحي.
- تظهر الفجوات في الخلايا النباتية بوضوح أكبر من الخلايا الحيوانية.

## 2. الفجوة المتقلصة (Contractile Vacuole)

### الموقع

- توجد في بعض كائنات مملكة الطليعيات التي تعيش في الماء العذب.
- المثالان الرئيسان في المحاضرة:
  - الأميبا (Amoeba).
  - الباراميسيوم (Paramecium).

### الوظيفة

- تجمع الماء الزائد داخل الخلية ثم تطرده إلى الخارج.
- تطرح بعض المواد الإخراجية الذائبة مع الماء.
- تحافظ على الاتزان المائي وتمنع انتفاخ الخلية أو انفجارها.

**سلسلة الحفظ:** ماء زائد ← تجمعه الفجوة ← تقلص ← طرح الماء والفضلات

### المحتوى

- ماء زائد (Excess Water).
- مواد إخراجية مذابة (Dissolved Excretory Materials).

## 3. الفجوة الغذائية (Food Vacuole)

### الموقع والمنشأ

- توجد في طليعيات مثل الأميبا والباراميسيوم.
- تتكون عندما يحيط غشاء الكائن بالمادة الغذائية ويدخلها إلى الخلية.
- تنفصل الحويصلة المحتوية على الغذاء عن الغشاء مكونة فجوة غذائية.
- تعد فجوة مؤقتة وليست تركيباً دائماً.

### الهضم داخلها

1. تتكون الفجوة حول المادة الغذائية.
2. يلتحم بها جسيم حال (Lysosome).
3. تطلق الإنزيمات الحالة داخل الفجوة.
4. تهضم المادة الغذائية وتتحول إلى مواد أبسط وذائبة.
5. تمتص الخلية نواتج الهضم وتستفيد منها.

## 4. الفجوة الخازنة أو فجوة العصير الخلوي

### الأسماء والموقع

- تسمى الفجوة الخازنة (Storage Vacuole).
- وتسمى أيضاً فجوة العصير الخلوي (Cell-Sap Vacuole).
- توجد بوضوح في سيتوبلازم الخلايا النباتية.
- تكون الفجوات النباتية عادة أكبر وأكثر وضوحاً من الفجوات في الخلايا الحيوانية.

### المحتوى والوظيفة

- تحتوي على العصير الخلوي (Cell Sap).
- العصير الخلوي ماء تذوب فيه مواد متنوعة.
- تسهم الفجوة في خزن الماء والمواد الذائبة والمحافظة على خصائص الخلية النباتية.

