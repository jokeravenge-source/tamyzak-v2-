# ثانياً: المتضمنات السيتوبلازمية غير الحية

## 1. تعريفها وطبيعتها

- هي مواد أو نواتج غير حية توجد داخل السيتوبلازم.
- تكون في أغلب الحالات مؤقتة، وقد تبقى مخزونة في بعض الخلايا.
- قد تتكون نتيجة نشاطات الأيض، أو نتيجة ترسب مواد ومخلفات داخل الخلية.

## 2. طرق التكوّن

1. نواتج العمليات الأيضية (Metabolic Products).
2. مواد أو مخلفات مترسبة ومتراكمة (Deposited Materials).

## 3. صور المتضمنات السيتوبلازمية

### أ. قطرات الدهون (Fat Droplets)

- تمثل مواد دهنية مخزونة.
- توجد بصورة واضحة في الخلايا أو النسيج الدهني (Adipose Tissue).
- قد توجد أيضاً في خلايا الكبد.

### ب. حبيبات الكلايكوجين (Glycogen Granules)

- تمثل خزيناً كربوهيدراتياً داخل الخلية.
- توجد بصورة بارزة في خلايا الكبد (Liver Cells).

### ج. حبيبات البروتين الإفرازية

- لا تخزن الخلايا الاعتيادية البروتين بالطريقة نفسها التي تخزن بها الدهون والكلايكوجين.
- تخزن بعض الخلايا الغدية الإفرازية البروتين مؤقتاً قبل إفرازه إلى خارج الخلية.

### د. المواد الصبغية أو الملونة (Pigments)

- قد تظهر على هيئة مواد ملونة أو مخلفات صبغية.
- المثال المذكور: الصبغات الموجودة في خلايا الجلد.

### هـ. حبيبات المواد الفعالة

- قد تضم إنزيمات أو هرمونات أو فيتامينات مخزونة في الخلية.
- تحاط بعض هذه المواد بغشاء.
- قد تكون الحبيبات كروية أو بيضوية أو ذات مظهر حبيبي.
- المثال المذكور في المحاضرة: الحبيبات الموجودة في الخلايا العصبية (Neuron Granules).

