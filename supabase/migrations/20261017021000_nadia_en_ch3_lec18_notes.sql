# المحاضرة الثامنة عشرة – الإخصاب وتكوين الجنين (Fertilization and Embryo Development)

## 🧭 نظرة عامة سريعة

تبدأ المحاضرة من المرحلة التي يصل فيها أنبوب اللقاح (Pollen Tube) إلى البويضة (Ovule) عبر النقير (Micropyle)، ثم تشرح الإخصاب المزدوج (Double Fertilization)، وتكوين اللاقحة (Zygote) والإندوسبيرم (Endosperm). بعد ذلك تتناول نمو الجنين (Embryo) على ست مراحل متتابعة في نباتات ذوات الفلقتين (Dicotyledons)، ابتداءً من اللاقحة، مروراً بمرحلة الجنين متعدد الخلايا، والكرة الصغيرة، والمرحلة القلبية، ومرحلة التوربيدو، وانتهاءً بالجنين الناضج داخل البذرة.

## 📚 المفاهيم والشرح التفصيلي

### 1. وصول أنبوب اللقاح إلى البويضة

- بعد نمو أنبوب اللقاح عبر الميسم (Stigma) والقلم (Style) والمبيض (Ovary)، يصل إلى البويضة (Ovule).
- يدخل أنبوب اللقاح إلى البويضة من خلال النقير (Micropyle)، وهي الفتحة الموجودة في أغلفة البويضة.
- بعد دخوله يقابل الكيس الجنيني (Embryo Sac).
- يحتوي أنبوب اللقاح على مشيجين ذكريين (Two Male Gametes)، إضافة إلى النواة الأنبوبية (Tube Nucleus) التي ينتهي دورها بعد وصول الأنبوب.

### 2. الإخصاب المزدوج

يحدث داخل الكيس الجنيني إخصابان:

#### الإخصاب الأول: تكوين اللاقحة

1. يتحد أحد المشيجين الذكريين مع البيضة (Egg Cell).
2. يسمى هذا الاتحاد اندماجاً/اتحاداً (Fusion/Union).
3. تتكون اللاقحة (Zygote).
4. تكون اللاقحة ثنائية المجموعة الكروموسومية (2n).

#### الإخصاب الثاني: تكوين الإندوسبيرم

1. يتحد المشيج الذكري الثاني مع النواتين القطبيتين (Polar Nuclei) الموجودتين في الخلية المركزية.
2. ينتج عن اتحاد نواتين أحاديتين مع مشيج ذكري أحادي نواة ثلاثية المجموعة الكروموسومية (3n).
3. تتكون نواة الإندوسبيرم الأولية (Primary Endosperm Nucleus).
4. يبدأ الإندوسبيرم (Endosperm) بالتكوين ويؤدي وظيفة غذائية للجنين.

### 3. تعريف الإخصاب المزدوج

الإخصاب المزدوج (Double Fertilization) هو حدوث عمليتي اتحاد داخل الكيس الجنيني؛ اتحاد مشيج ذكري مع البيضة لتكوين اللاقحة، واتحاد المشيج الذكري الثاني مع النواتين القطبيتين لتكوين نواة الإندوسبيرم الأولية ثم الإندوسبيرم.

### 4. ما بعد الإخصاب

بعد اكتمال الإخصاب تحدث الخطوات الآتية:

1. تختفي الخلايا المساعدة (Synergids)؛ لأن دورها انتهى.
2. تبدأ اللاقحة (2n) بالنمو والانقسام.
3. يزداد عدد خلايا اللاقحة، وتتحول تدريجياً إلى جنين (Embryo).
4. يبدأ الجنين بالتمايز (Differentiation) إلى أجزاء مختلفة:
   - الجذير (Radicle).
   - السويقة الجنينية/الساق الجنينية (Plumule/Hypocotyl بحسب موضعها في الرسم).
   - الأوراق الجنينية أو الفلقتان (Cotyledons).
5. يستمر الجنين بالنمو من مرحلة إلى أخرى حتى يصبح جنيناً ناضجاً داخل البذرة.

### 5. وظيفة الإندوسبيرم

- الإندوسبيرم (Endosperm) نسيج غذائي يوجد داخل الكيس الجنيني.
- تركيبه ثلاثي المجموعة الكروموسومية (3n).
- يتكون من اتحاد المشيج الذكري الثاني مع النواتين القطبيتين.
- وظيفته خزن الغذاء وتغذية الجنين خلال فترة نموه.
- يدخل الإندوسبيرم في انقسامات خيطية (Mitosis) متعددة، لا في انقسام واحد فقط، حتى يزيد عدد خلاياه وقدرته على خزن المواد الغذائية.
- يستهلك الجنين الإندوسبيرم تدريجياً، ولذلك يقل حجمه في المراحل المتقدمة من تكوين الجنين.

### 6. بداية نمو اللاقحة والجنين

- اللاقحة خلية واحدة ناتجة من الإخصاب الأول.
- تدخل اللاقحة في الانقسام الخيطي (Mitosis)، فتتحول من خلية واحدة إلى تركيب متعدد الخلايا.
- في البداية تكون الخلايا غير متمايزة (Undifferentiated Cells).
- لا يكون الجنين في البداية مكوّناً من جذير أو سويق أو وريقة واضحة، بل يكون كتلة من الخلايا غير المتخصصة.
- مع استمرار النمو تبدأ الخلايا بالتخصص، فتظهر الأجزاء التي ستؤدي وظائف الجذر والساق والأوراق.

## 🧬 مراحل تكوين جنين ذوات الفلقتين

### المرحلة الأولى: اللاقحة (Zygote Stage)

- تبدأ بعد الإخصاب الأول.
- تكون اللاقحة خلية واحدة ثنائية المجموعة الكروموسومية (2n).
- يحيط بها الإندوسبيرم الذي يبدأ بتكوين الغذاء.
- تدخل اللاقحة في الانقسام الخيطي لتكوين خلايا الجنين.

### المرحلة الثانية: الجنين متعدد الخلايا (Multicellular Embryo)

- تتحول اللاقحة من خلية واحدة إلى كتلة متعددة الخلايا.
- يكون الجنين في هذه المرحلة غير متمايز.
- لا تظهر فيه أجزاء الجذير والسويق والفلقتين بصورة واضحة.
- يحيط الإندوسبيرم بالجنين ويزوّده بالغذاء.

### المرحلة الثالثة: مرحلة الكرة الصغيرة (Small Ball Stage)

- يصبح الجنين على شكل كرة صغيرة (Small Ball).
- يبقى الجنين كتلة من الخلايا، لكن يبدأ بالانتقال من الشكل العام إلى شكل أكثر تنظيماً.
- يستمر الإندوسبيرم في أداء وظيفته الغذائية.

### المرحلة الرابعة: المرحلة القلبية (Heart-shaped Stage)

- يصبح الجنين على شكل قلب (Heart-shaped Embryo).
- تبدأ الفلقتان (Cotyledons) بالظهور بوضوح، فتظهر منطقتان بارزتان في أعلى الجنين.
- تبدأ مناطق الجذير والساق والوريقة بالتمايز.
- يبدأ الإندوسبيرم بالانخفاض؛ لأن الجنين يستهلك المواد الغذائية المخزونة فيه.

### المرحلة الخامسة: مرحلة التوربيدو (Torpedo Stage)

- يصبح الجنين على شكل توربيدو أو جسم ممدود (Torpedo-shaped Embryo).
- تزداد وضوحاً الفلقتان.
- يظهر السويق (Shoot Axis) والجذير (Radicle) بصورة أوضح.
- تظهر المنطقة القمية (Apical Region) المرتبطة بنمو الساق والجذر.
- يتناقص الإندوسبيرم أكثر مع استمرار استهلاك الغذاء.

### المرحلة السادسة: الجنين الناضج (Mature Embryo)

- يصبح الجنين مكتمل التمايز داخل البذرة.
- تكون الفلقتان واضحتين، لأن النبات من ذوات الفلقتين.
- تظهر الأجزاء الرئيسة:
  - الجذير (Radicle) الذي يمثل الجذر الأولي.
  - السويق/الساق الجنينية (Plumule/Shoot Axis).
  - الفلقتان (Two Cotyledons).
  - الأوراق الجنينية/الوريقات (Embryonic Leaves).
- تتحول أغلفة البويضة إلى غلاف البذرة (Seed Coat) مع استمرار تطور البويضة إلى بذرة.
- يبقى جزء قليل من الإندوسبيرم في البداية، ثم قد يختفي بعد استهلاك الجنين له.
- يصبح الجنين جاهزاً داخل البذرة، وتكون البذرة مكوّنة من غلاف بذرة وجنين وما تبقى من الغذاء المخزون.

## 📖 التعريفات والمصطلحات

- **الإخصاب (Fertilization):** اتحاد مشيج ذكري مع الخلية الأنثوية أو النواتين القطبيتين داخل الكيس الجنيني.
- **الإخصاب المزدوج (Double Fertilization):** حدوث اتحادين داخل الكيس الجنيني؛ الأول يكوّن اللاقحة والثاني يكوّن الإندوسبيرم.
- **اللاقحة (Zygote):** الخلية الثنائية الناتجة من اتحاد المشيج الذكري مع البيضة.
- **الإندوسبيرم (Endosperm):** نسيج غذائي ثلاثي المجموعة الكروموسومية يتكون من اتحاد المشيج الذكري الثاني مع النواتين القطبيتين.
- **نواة الإندوسبيرم الأولية (Primary Endosperm Nucleus):** النواة الناتجة من الاتحاد الثاني في الإخصاب المزدوج، وتبدأ بتكوين الإندوسبيرم.
- **المشيجان الذكريان (Two Male Gametes):** خليتان تنتجان من انقسام النواة التوليدية، ويشارك كل منهما في أحد اتحادي الإخصاب.
- **الخلايا المساعدة (Synergids):** خلايا موجودة قرب البيضة، تختفي بعد انتهاء دورها في عملية الإخصاب.
- **الجنين (Embryo):** التركيب النامي الناتج من انقسامات اللاقحة، ويتمايز إلى جذير وسويق وفلقتين وأوراق جنينية.
- **الجذير (Radicle):** الجزء الجنيني الذي يتطور إلى الجذر الأولي.
- **السويق/محور الساق (Plumule/Shoot Axis):** الجزء الجنيني الذي يتطور إلى الساق والأجزاء الهوائية.
- **الفلقة (Cotyledon):** ورقة جنينية، ويحتوي جنين ذوات الفلقتين على فلقتين.
- **مرحلة الكرة الصغيرة (Small Ball Stage):** مرحلة يكون فيها الجنين على شكل كرة صغيرة.
- **المرحلة القلبية (Heart-shaped Stage):** مرحلة يظهر فيها الجنين على شكل قلب وتبرز الفلقتان.
- **مرحلة التوربيدو (Torpedo Stage):** مرحلة يصبح فيها الجنين ممدوداً على شكل توربيدو وتزداد وضوح أجزائه.
- **الجنين الناضج (Mature Embryo):** المرحلة النهائية التي يكتمل فيها تمايز الجذير والسويق والفلقتين والأوراق الجنينية.
- **غلاف البذرة (Seed Coat):** الغلاف الناتج من تطور أغلفة البويضة، ويحيط بالجنين داخل البذرة.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة الإخصاب المزدوج

مشيج ذكري (n) + بيضة (n) ⟶ لاقحة (2n).

مشيج ذكري (n) + نواتان قطبيتان (n + n) ⟶ نواة إندوسبيرم أولية (3n) ⟶ إندوسبيرم (3n).

### قاعدة عدد الإخصابات

اتحادان داخل الكيس الجنيني = إخصاب مزدوج.

### قاعدة نمو الجنين

لاقحة واحدة ⟶ انقسامات خيطية متتالية ⟶ جنين متعدد الخلايا ⟶ تمايز إلى جذير وسويق وفلقتين وأوراق جنينية.

### تسلسل مراحل جنين ذوات الفلقتين

اللاقحة ⟶ جنين متعدد الخلايا ⟶ كرة صغيرة ⟶ شكل قلبي ⟶ توربيدو ⟶ جنين ناضج.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تحديد ناتج الاتحاد الأول

**المعطيات:** اتحاد مشيج ذكري مع البيضة.

**القانون:** مشيج ذكري (n) + بيضة (n) = لاقحة (2n).

**الناتج النهائي:** تتكون اللاقحة (Zygote) ثنائية المجموعة الكروموسومية.

### مثال 2: تحديد ناتج الاتحاد الثاني

**المعطيات:** اتحاد المشيج الذكري الثاني مع النواتين القطبيتين.

**القانون:** n + n + n = 3n.

**الناتج النهائي:** تتكون نواة الإندوسبيرم الأولية، ثم يتكون الإندوسبيرم الثلاثي الذي يخزن الغذاء للجنين.

### مثال 3: تفسير اختفاء الخلايا المساعدة

**السؤال:** ماذا يحدث للخلايا المساعدة بعد الإخصاب؟

**الإجابة:** تختفي الخلايا المساعدة؛ لأن وظيفتها انتهت بعد وصول أنبوب اللقاح وحدوث الإخصاب.

### مثال 4: ترتيب مراحل تكوين الجنين

**المعطيات:** لاقحة، شكل قلبي، توربيدو، جنين متعدد الخلايا، كرة صغيرة، جنين ناضج.

**خطوات الترتيب:**

1. اللاقحة.
2. الجنين متعدد الخلايا.
3. الكرة الصغيرة.
4. الشكل القلبي.
5. شكل التوربيدو.
6. الجنين الناضج.

**الناتج النهائي:** هذا هو التسلسل الصحيح لمراحل تكوين جنين ذوات الفلقتين.

### مثال 5: لماذا يقل الإندوسبيرم في المراحل المتقدمة؟

**الإجابة:** لأن الجنين يستهلك الإندوسبيرم بوصفه نسيجاً خازناً للغذاء، ولذلك يقل حجمه تدريجياً خلال نمو الجنين.

## ⚠️ تنبيهات وأخطاء شائعة (ملاحظات وزارية)

- **مهم جداً ووزاري:** الإخصاب المزدوج يتضمن اتحادين، وليس اتحاداً واحداً.
- الاتحاد الأول يكون بين مشيج ذكري والبيضة، وينتج اللاقحة (2n).
- الاتحاد الثاني يكون بين المشيج الذكري الثاني والنواتين القطبيتين، وينتج الإندوسبيرم (3n).
- لا تخلط بين اللاقحة (Zygote) والإندوسبيرم (Endosperm): اللاقحة تكوّن الجنين، والإندوسبيرم يغذي الجنين.
- بعد الإخصاب تختفي الخلايا المساعدة (Synergids) وينتهي دورها.
- **مهم:** النواة الأنبوبية لا تكون هي التي تكوّن المشيجين الذكريين؛ النواة التوليدية هي التي تنقسم وتكوّنهما.
- الإندوسبيرم نسيج خازن للغذاء، ويدخل في انقسامات خيطية متعددة لزيادة عدد خلاياه.
- **مهم جداً:** احفظ مراحل الجنين بالتسلسل مع رسوماتها: لاقحة، متعدد الخلايا، كرة صغيرة، قلبي، توربيدو، ناضج.
- مرحلة الشكل القلبي مهمة لأنها تتميز بظهور الفلقتين.
- مرحلة التوربيدو تتميز باستطالة الجنين ووضوح الجذير والسويق والفلقتين.
- في الجنين الناضج تظهر الفلقتان والجذير والسويق والأوراق الجنينية بوضوح.
- تتحول أغلفة البويضة إلى غلاف البذرة.
- يقل الإندوسبيرم تدريجياً بسبب استهلاك الجنين للغذاء المخزون فيه.
- لا تكتب أن الجنين في بدايته متمايز إلى جذير وسويق ووريقات؛ في المراحل الأولى يكون كتلة من خلايا غير متمايزة.
- عند سؤال: ماذا يحدث بعد الإخصاب؟ اذكر اختفاء الخلايا المساعدة، ونمو اللاقحة، وزيادة عدد خلايا الجنين، ثم تمايزه إلى أجزائه.

## 🧠 الخلاصة

- يحدث الإخصاب المزدوج داخل الكيس الجنيني: اتحاد أول يكوّن اللاقحة، واتحاد ثانٍ يكوّن الإندوسبيرم.
- اللاقحة ثنائية المجموعة (2n)، والإندوسبيرم ثلاثي المجموعة (3n) ويغذي الجنين.
