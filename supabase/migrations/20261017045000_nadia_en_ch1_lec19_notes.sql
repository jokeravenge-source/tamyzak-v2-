## 🧠 طريقة سريعة لعدم الخلط

- **Hypotonic:** المذاب خارج الخلية منخفض، لذلك الماء يدخل الخلية.
- **Hypertonic:** المذاب خارج الخلية مرتفع، لذلك الماء يخرج من الخلية.
- **Isotonic:** التراكيز متقاربة، لذلك لا توجد حركة صافية.

> صفتا Hypotonic وHypertonic تصفان تركيز **المذاب في المحلول الخارجي** مقارنة بمحتوى الخلية.

