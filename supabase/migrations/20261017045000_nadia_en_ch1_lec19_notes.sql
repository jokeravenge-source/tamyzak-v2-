# المحاضرة التاسعة عشرة – المحاليل الأسموزية والبلزمة

## 🧭 نظرة عامة

تطبق المحاضرة مفهوم الأسموزية على الخلايا الحية، وتقارن تأثير المحلول المتساوي التوتر وناقص التوتر ومفرط التوتر في الخلايا الحيوانية والنباتية. كما تشرح البلزمة في الخلايا النباتية وإمكانية عكسها بإزالة البلزمة.

## 1. أساس تصنيف المحاليل

تصنف المحاليل بالمقارنة مع تركيز المذاب داخل الخلية، وليس اعتماداً على اسم المادة وحده.

- زيادة تركيز المذاب تعني انخفاض التركيز النسبي للماء.
- انخفاض تركيز المذاب يعني ارتفاع التركيز النسبي للماء.
- يتحرك الماء أسموزياً من الوسط الأعلى في تركيز الماء إلى الوسط الأقل فيه.

## 2. المحلول المتساوي التوتر (Isotonic Solution)

### التعريف

- تركيز المذاب خارج الخلية مساوٍ تقريباً لتركيزه داخلها.
- تركيز الماء متقارب على جانبي الغشاء.

### حركة الماء

- يدخل الماء ويخرج بالمعدل نفسه تقريباً.
- لا توجد حركة صافية للماء في اتجاه واحد.

### التأثير في الخلية الحيوانية

- تحافظ الخلية على حجمها وشكلها الطبيعيين.
- لا تكتسب ماءً صافياً ولا تفقده.

### التأثير في الخلية النباتية

- لا يحدث دخول صافٍ أو خروج صافٍ للماء.
- لا تكون الخلية ممتلئة بأقصى ضغط امتلاء، وقد تبدو رخوة مقارنة بحالتها في المحلول ناقص التوتر.

**رسم الأسهم:** عدد متساوٍ من الأسهم الداخلة والخارجة.

## 3. المحلول ناقص التوتر (Hypotonic Solution)

### التعريف

- تركيز المذاب خارج الخلية أقل من تركيزه داخلها.
- تركيز الماء خارج الخلية أعلى من تركيزه داخلها.

### حركة الماء

- يدخل ماء إلى الخلية أكثر مما يخرج منها.

### التأثير في الخلية الحيوانية

- تنتفخ الخلية بسبب اكتساب الماء.
- قد تتمزق أو تنفجر إذا استمر دخول الماء بكميات كبيرة، وتسمى العملية التحلل الخلوي (Cytolysis).

### التأثير في الخلية النباتية

- يدخل الماء إلى الفجوة العصارية فتتسع.
- تصبح الخلية ممتلئة أو متورمة (Turgid).
- يمنع الجدار الخلوي الصلب انفجارها في الظروف الاعتيادية.

**رسم الأسهم:** أسهم داخلة أكثر من الأسهم الخارجة.

## 4. المحلول مفرط التوتر (Hypertonic Solution)

### التعريف

- تركيز المذاب خارج الخلية أعلى من تركيزه داخلها.
- تركيز الماء خارج الخلية أقل من تركيزه داخلها.

### حركة الماء

- يخرج ماء من الخلية أكثر مما يدخل إليها.

### التأثير في الخلية الحيوانية

- تفقد الخلية الماء.
- تنكمش وتتجعد (Crenation/Shrinkage).
- قد تتضرر أو تموت إذا استمر فقدان الماء.

### التأثير في الخلية النباتية

- يخرج الماء أساساً من الفجوة العصارية.
- تنكمش الفجوة ويقل حجم المحتوى الخلوي.
- يبتعد الغشاء البلازمي عن الجدار الخلوي.
- يبقى الجدار الخلوي محافظاً على الشكل الخارجي العام.
- تسمى هذه العملية البلزمة (Plasmolysis).

**رسم الأسهم:** أسهم خارجة أكثر من الأسهم الداخلة.

## 5. البلزمة (Plasmolysis)

البلزمة هي انكماش محتويات الخلية النباتية وابتعاد الغشاء البلازمي عن الجدار الخلوي نتيجة فقدان الماء عند وضع الخلية في محلول مفرط التوتر.

### تسلسل البلزمة

محلول مفرط التوتر → خروج الماء → انكماش الفجوة → انكماش السيتوبلازم → ابتعاد الغشاء عن الجدار

## 6. إزالة البلزمة (Deplasmolysis)

إزالة البلزمة هي عودة الخلية النباتية المبلزمة إلى حالتها السابقة عند نقلها إلى الماء أو إلى محلول أقل تركيزاً بالمذاب.

### التسلسل

1. تنقل الخلية المبلزمة إلى الماء.
2. يدخل الماء أسموزياً إلى الخلية.
3. تمتلئ الفجوة العصارية من جديد.
4. يتمدد السيتوبلازم ويقترب الغشاء البلازمي من الجدار.
5. تستعيد الخلية حالتها الطبيعية إذا لم يكن الضرر دائماً.

