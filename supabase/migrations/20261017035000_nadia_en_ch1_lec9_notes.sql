# المحاضرة التاسعة – البلاستيدات (Plastids)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة البلاستيدات بوصفها عضيات خلوية موجودة في سيتوبلازم الخلايا النباتية. توضح اختلافها في الشكل والحجم واللون والصبغات، وتقسمها إلى البلاستيدات الملونة وعديمة اللون والخضراء، ثم تشرح تركيب البلاستيدة الخضراء ووظيفة السدى والجرانا والثايلاكويدات في عملية التركيب الضوئي.

## 📚 المفاهيم والشرح التفصيلي

### 1. تعريف البلاستيدات وموقعها

- البلاستيدات (Plastids) عضيات خلوية.
- توجد داخل سيتوبلازم الخلايا النباتية فقط.
- تختلف البلاستيدات بحسب نوع النبات والخلية في:
  - الشكل.
  - الحجم.
  - اللون.
  - الصبغات الموجودة داخلها.

### 2. أشكال البلاستيدات

من الأشكال المذكورة للبلاستيدات:

- بيضوية (Oval).
- كأسية (Cup-shaped).
- نجمية (Stellate).
- حلزونية (Spiral).

## 🧬 أنواع البلاستيدات

### 1. البلاستيدات الملونة (Chromoplasts)

- تحتوي على صبغات مختلفة.
- قد تظهر باللون الأحمر أو البرتقالي أو الأصفر.
- تمنح الألوان للثمار والأزهار.

### 2. البلاستيدات عديمة اللون (Leucoplasts)

- بلاستيدات عديمة اللون (Colorless Plastids).
- تمثل مراكز لتحويل الجلوكوز وخزن المواد الغذائية.
- يمكن أن يتحول الجلوكوز، وهو سكر أحادي، إلى مادة عديدة السكريات مثل النشا (Starch).
- يرتبط هذا النوع بخزن النشا والدهون والبروتينات.
- يسمى النشا أيضاً المادة البيضاء (White Matter) في سياق المحاضرة.

### 3. البلاستيدات الخضراء (Chloroplasts)

- تعد النوع الشائع من البلاستيدات.
- تحتوي على الكلوروفيل والإنزيمات.
- تساعد النبات على إجراء عملية التركيب الضوئي (Photosynthesis).
- تحاط بغشائين: غشاء خارجي وغشاء داخلي.

## 🌿 تركيب البلاستيدة الخضراء

تتكون البلاستيدة الخضراء داخلياً من جزأين أساسيين:

1. السدى (Stroma).
2. الجرانا (Grana).

### 1. السدى (Stroma)

- مادة سائلة شفافة تملأ الحيز الداخلي للبلاستيدة الخضراء.
- توجد الجرانا داخل السدى.
- تحتوي السدى على إنزيمات خاصة.
- تساعد هذه الإنزيمات في اختزال ثاني أوكسيد الكربون وتحويله إلى سكريات ضمن تفاعلات التركيب الضوئي.

### 2. الجرانا (Grana)

- تظهر على هيئة صفائح أو تراكيب مفلطحة داخل السدى.
- المفرد يسمى Granum، والجمع يسمى Grana.
- تحتوي أغشية الجرانا على الكلوروفيل.
- يمتص الكلوروفيل الطاقة الضوئية، ولذلك ترتبط الجرانا بالتفاعلات الضوئية (Light Reactions).

### 3. الثايلاكويدات (Thylakoids)

- تتكون كل جرانة من عدد من الأكياس أو الأقراص الغشائية.
- يسمى كل كيس أو قرص ثايلاكويداً (Thylakoid).
- تحتوي أغشية الثايلاكويدات على الكلوروفيل والعناصر اللازمة للتفاعلات الضوئية.
- تنشأ هذه التراكيب من الغشاء الداخلي للبلاستيدة الخضراء.

### 4. حبوب النشا (Starch Grains)

- قد تظهر حبوب النشا داخل البلاستيدة الخضراء.
- تعد من التأشيرات المهمة عند رسم البلاستيدة.

## ☀️ دور أجزاء البلاستيدة في التركيب الضوئي

### الجرانا والثايلاكويدات

- تحتوي على الكلوروفيل.
- تمتص الطاقة الضوئية.
- ترتبط بالتفاعلات الضوئية في عملية التركيب الضوئي.

### السدى

- تحتوي على إنزيمات خاصة.
- تسهم في اختزال ثاني أوكسيد الكربون وتكوين السكريات.
- ترتبط بالتفاعلات غير الضوئية أو التفاعلات المظلمة (Dark Reactions).

## ✏️ تأشيرات الرسم المهمة

عند رسم البلاستيدة الخضراء يجب تحديد:

1. الغشاء الخارجي (Outer Membrane).
2. الغشاء الداخلي (Inner Membrane).
3. السدى (Stroma).
4. الجرانا (Grana).
5. الثايلاكويدات (Thylakoids).
6. حبوب النشا (Starch Grains).

## ⚠️ نقاط مهمة للحفظ

- البلاستيدات توجد في الخلايا النباتية فقط.
- تختلف في الشكل والحجم واللون والصبغات.
- أنواعها ثلاثة: ملونة، وعديمة اللون، وخضراء.
- البلاستيدات الملونة تمنح الثمار والأزهار ألوانها.
- البلاستيدات عديمة اللون ترتبط بخزن النشا والدهون والبروتينات.
- البلاستيدات الخضراء تحتوي على الكلوروفيل والإنزيمات وتؤدي دوراً في التركيب الضوئي.
- الجرانا تحتوي على الكلوروفيل، بينما السدى تحتوي على الإنزيمات.
- الثايلاكويد كيس غشائي، ومجموعة الثايلاكويدات تكوّن الجرانة.

## 🧠 الخلاصة

- البلاستيدات عضيات نباتية تختلف في الشكل والحجم واللون.
- البلاستيدات الملونة تعطي الألوان، وعديمة اللون تخزن الغذاء، والخضراء تنجز التركيب الضوئي.
- تتكون البلاستيدة الخضراء من غشائين، وسدى، وجرانا مكونة من ثايلاكويدات.
