# المحاضرة الرابعة والعشرون – تحول البيروفيك وبداية دورة كربس

## 🧭 نظرة عامة

تشرح المحاضرة مصير حامض البيروفيك بعد التحلل السكري عند توفر الأوكسجين، وكيف يتحول المركب ثلاثي الكربون إلى مجموعة أسيتيل ثنائية الكربون، ثم تدخل دورة كربس داخل المايتوكوندريا.

# أولاً: الانتقال من التحلل السكري إلى التنفس الهوائي

- ينتج التحلل السكري جزيئين من حامض البيروفيك من جزيء جلوكوز واحد.
- عند توفر الأوكسجين ينتقل المسار إلى المايتوكوندريا.
- لا يدخل حامض البيروفيك الثلاثي الكربون دورة كربس بصورته مباشرة.
- يجب أن يتحول كل جزيء بيروفيك إلى مجموعة أسيتيل ثنائية الكربون.
- يعالج الجسم جزيئي البيروفيك، ولذلك تدخل دورة كربس مرتين لكل جزيء جلوكوز.

## قاعدة الحفظ

1 Glucose → 2 Pyruvic Acid → 2 Acetyl-CoA → 2 Krebs Cycles

# ثانياً: تحول البيروفيك إلى أسيتيل مرافق الإنزيم A

## 1. لماذا يحدث التحول؟

حامض البيروفيك مركب ثلاثي الكربون، بينما المركب الذي يفتح دورة كربس يجب أن يقدم مجموعة أسيتيل ثنائية الكربون لتتحد مع مركب رباعي الكربون.

## 2. خطوات التحول لجزيء بيروفيك واحد

1. يتعرض البيروفيك للأكسدة.
2. ينزع منه جزيء CO₂، فيتحول الجزء الكربوني من 3C إلى 2C.
3. ينزع الهيدروجين ويحمل على ناقل مناسب؛ ويرمز له في المنهج بـ `2H`.
4. ترتبط مجموعة الأسيتيل بمرافق الإنزيم A.
5. يتكون Acetyl-CoA القادر على دخول دورة كربس.

## 3. نواتج التحول

### من جزيء بيروفيك واحد

- 1 Acetyl-CoA.
- 1 CO₂.
- 2H، ويعادل 3 ATP وفق حساب المنهج.

### من جزيئي بيروفيك ناتجين من جلوكوز واحد

- 2 Acetyl-CoA.
- 2CO₂.
- مجموعتا 2H، وتعادلان 6 ATP وفق حساب المنهج.

## 4. أهمية Acetyl-CoA

- يمثل المركب المفتاح لدخول دورة كربس.
- ينقل مجموعة الأسيتيل ثنائية الكربون.
- من دونه لا يبدأ تسلسل تفاعلات الدورة.

# ثالثاً: بداية دورة كربس

## 1. مكان حدوثها

تحدث دورة كربس في المايتوكوندريا ضمن التنفس الهوائي.

## 2. أول تفاعل

تتحد مجموعة الأسيتيل ثنائية الكربون مع حامض الأوكسالو أسيتيك رباعي الكربون:

Acetyl-CoA (2C) + Oxaloacetic Acid (4C) → Citric Acid (6C)

## 3. حامض الستريك

- مركب سداسي الكربون.
- أول مركب واضح يتكون في الدورة.
- لذلك تسمى دورة كربس أيضاً **دورة حامض الستريك (Citric Acid Cycle)**.
- تعاد تكوين مادة الأوكسالو أسيتيك في نهاية الدورة لتستقبل مجموعة أسيتيل جديدة.

# رابعاً: التحول إلى ألفا كيتوكلوتاريك

- يتعرض المركب السداسي الكربون للأكسدة ونزع CO₂.
- ينخفض عدد ذرات الكربون من 6 إلى 5.
- ينزع `2H` خلال التفاعل، ويعادل 3 ATP بحسب المنهج.
- يتكون حامض ألفا كيتوكلوتاريك (Alpha-Ketoglutaric Acid)، وهو مركب خماسي الكربون.

Citric Acid (6C) → Alpha-Ketoglutaric Acid (5C) + CO₂ + 2H

# خامساً: إكمال الدورة بصورة مبسطة

بعد ألفا كيتوكلوتاريك تمر الدورة بعدة مركبات وسيطة اختصرها المنهج، ثم:

- تتحرر نواتج طاقة وهيدروجين وCO₂.
- يعاد تكوين حامض الأوكسالو أسيتيك رباعي الكربون.
- يستقبل الأوكسالو أسيتيك مجموعة أسيتيل جديدة وتبدأ دورة أخرى.

## 🔄 لماذا تسمى دورة؟

لأن المركب رباعي الكربون الذي يبدأ التفاعل يعاد تكوينه في النهاية، فيصبح جاهزاً للاتحاد مع مجموعة أسيتيل أخرى.

