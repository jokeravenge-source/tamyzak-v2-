- بذور ذوات الفلقة الواحدة تحتوي على فلقة واحدة وإندوسبيرم باقٍ لتخزين الغذاء.
- أمثلة ذوات الفلقة الواحدة: الحنطة والذرة والأرز، وأمثلة ذوات الفلقتين: الفاصوليا والفول.

