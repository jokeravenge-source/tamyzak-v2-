# المحاضرة التاسعة عشرة – تكوّن البذرة والفرق بين ذوات الفلقتين وذوات الفلقة الواحدة

## 🧭 نظرة عامة سريعة

تشرح المحاضرة المرحلة التي تلي اكتمال تكوين الجنين (Embryo)، إذ تتحول البويضة (Ovule) إلى بذرة (Seed)، وتتحول أغلفة البويضة إلى غلاف البذرة (Seed Coat). كما توضح أصل البذرة ومصدر غلافها، وتفرّق بين بذور ذوات الفلقتين (Dicotyledonous Seeds) وبذور ذوات الفلقة الواحدة (Monocotyledonous Seeds) من حيث وجود الجنين والإندوسبيرم (Endosperm) والفلقة أو الفلقتين، مع أمثلة وردت في المحاضرة.

## 📚 المفاهيم والشرح التفصيلي

### 1. بداية تكوّن البذرة

- بعد اكتمال مراحل تكوين الجنين، يصبح الجنين ناضجاً (Mature Embryo).
- لا تبقى البويضة (Ovule) بويضةً بعد اكتمال الجنين، بل تتحول إلى بذرة.
- لذلك تبدأ عملية تكوين البذرة (Seed Formation) بعد الإخصاب وتكوين الجنين.
- أصل البذرة هو البويضة:

  **البويضة (Ovule) ⟶ البذرة (Seed).**

### 2. تحوّل أغلفة البويضة إلى غلاف البذرة

- أغلفة البويضة (Ovule Integuments) تتحول إلى غلاف البذرة (Seed Coat).
- قد تكون أغلفة البويضة غلافاً واحداً أو عدة أغلفة بحسب نوع النبات والزهرة.
- بعد تحولها إلى غلاف البذرة تسمى علمياً التستا (Testa).
- التستا (Testa) هي طبقة غطائية أصلها أغلفة البويضة، ووظيفتها تغليف البذرة وحماية ما داخلها.

### 3. مصدر كل جزء في البذرة

- البذرة أصلها البويضة.
- غلاف البذرة (Seed Coat) أصله أغلفة البويضة (Integuments).
- تسمى طبقات الغلاف علمياً التستا (Testa).
- الجنين (Embryo) يتكون من اللاقحة (Zygote) بعد انقسامات ونمو متتابع.
- الإندوسبيرم (Endosperm) يتكون من الاتحاد الثاني في الإخصاب المزدوج، ويعمل نسيجاً خازناً للغذاء.

### 4. مكونات البذرة الناضجة

تتكون البذرة الناضجة من مكونات رئيسة:

1. الجنين الناضج (Mature Embryo).
2. غلاف البذرة/التستا (Seed Coat/Testa).
3. الإندوسبيرم (Endosperm) إذا بقي ولم يستهلكه الجنين.

وجود الإندوسبيرم أو اختفاؤه يعتمد على نوع البذرة وما إذا كان الجنين قد استهلك الغذاء المخزون فيه.

## 🌱 بذور ذوات الفلقتين (Dicotyledonous Seeds)

### 1. مكونات بذرة ذوات الفلقتين

عند فحص بذرة ذوات الفلقتين، نلاحظ:

- جنيناً ناضجاً (Mature Embryo).
- فلقتين (Two Cotyledons)، أي ورقتين جنينيتين.
- قد يكون الإندوسبيرم مختفياً أو قليلاً؛ لأن الجنين استعمل الغذاء المخزون فيه.
- في الأمثلة التي ذكرت للفاصوليا، تكون الفلقتان واضحتين ويكون الغذاء قد انتقل إلى الفلقتين أو استهلكه الجنين، لذلك لا يظهر الإندوسبيرم بوضوح.

### 2. سبب اختفاء الإندوسبيرم في بعض بذور ذوات الفلقتين

- الإندوسبيرم نسيج خازن للغذاء.
- أثناء نمو الجنين، يتغذى الجنين على الغذاء الموجود في الإندوسبيرم.
- يختفي الإندوسبيرم أو يقل عندما يستهلكه الجنين.
- لذلك تظهر داخل البذرة الفلقتان والجنين بصورة واضحة، بينما لا يكون الإندوسبيرم واضحاً.

### 3. أمثلة ذوات الفلقتين المذكورة

- الفاصوليا (Beans).
- الفول/الفاصوليا الخضراء كما وردت في الشرح ضمن أمثلة البذور التي يختفي فيها الإندوسبيرم.

## 🌾 بذور ذوات الفلقة الواحدة (Monocotyledonous Seeds)

### 1. مكونات بذور ذوات الفلقة الواحدة

تحتوي بذور ذوات الفلقة الواحدة على:

- جنين (Embryo).
- فلقة واحدة (One Cotyledon).
- إندوسبيرم (Endosperm) يبقى موجوداً.
- غلاف بذرة (Seed Coat/Testa).

### 2. سبب بقاء الإندوسبيرم

- في بذور ذوات الفلقة الواحدة لا يستهلك الجنين الإندوسبيرم بالكامل أثناء تكوّن البذرة.
- يبقى الإندوسبيرم مخزناً للغذاء داخل البذرة.
- يبدأ الجنين باستعماله بعد زراعة البذرة وبدء امتصاص الماء والإنبات.
- لذلك يكون الإندوسبيرم واضحاً في بذور ذوات الفلقة الواحدة.

### 3. أمثلة ذوات الفلقة الواحدة المذكورة

- الحنطة/القمح (Wheat).
- الذرة (Corn).
- الأرز (Rice).

## 🔍 مقارنة بين بذور ذوات الفلقتين وذوات الفلقة الواحدة

| وجه المقارنة | ذوات الفلقتين (Dicotyledons) | ذوات الفلقة الواحدة (Monocotyledons) |
|---|---|---|
| عدد الفلقات | فلقتان | فلقة واحدة |
| الجنين | جنين ناضج موجود | جنين موجود |
| الإندوسبيرم | قد يختفي أو يقل بسبب استهلاكه | يبقى موجوداً ومخزناً للغذاء |
| استعمال الغذاء | يستعمله الجنين خلال التكوين | يبدأ الجنين باستعماله بعد زراعة البذرة وبدء امتصاص الماء |
| أمثلة المحاضرة | الفاصوليا/الفول | الحنطة والذرة والأرز |

## 📖 التعريفات والمصطلحات

- **البذرة (Seed):** التركيب الناتج من تحول البويضة بعد الإخصاب وتكوين الجنين، ويضم الجنين وغلاف البذرة وقد يضم الإندوسبيرم.
- **تكوين البذرة (Seed Formation):** المرحلة التي تتحول فيها البويضة إلى بذرة بعد اكتمال تكوين الجنين.
- **البويضة (Ovule):** تركيب داخل المبيض يتحول بعد الإخصاب والنضج إلى بذرة.
- **غلاف البذرة (Seed Coat):** الغلاف الذي يحيط بالبذرة ويحمي الجنين ومكوناتها.
- **التستا (Testa):** طبقة غلاف البذرة، وأصلها أغلفة البويضة.
- **أغلفة البويضة (Ovule Integuments):** أغلفة تحيط بالبويضة وتتحول بعد النضج إلى غلاف البذرة.
- **الجنين (Embryo):** التركيب الناتج من نمو اللاقحة، ويصبح جنيناً ناضجاً داخل البذرة.
- **الإندوسبيرم (Endosperm):** نسيج خازن للغذاء يزوّد الجنين بالغذاء، وقد يبقى أو يختفي بحسب نوع البذرة.
- **الفلقة (Cotyledon):** ورقة جنينية داخل البذرة؛ تكون فلقتين في ذوات الفلقتين وفلقة واحدة في ذوات الفلقة الواحدة.
- **ذوات الفلقتين (Dicotyledons):** نباتات أو بذور تحتوي على فلقتين.
- **ذوات الفلقة الواحدة (Monocotyledons):** نباتات أو بذور تحتوي على فلقة واحدة.
- **البذرة الإندوسبيرمية (Endospermic Seed):** بذرة يبقى فيها الإندوسبيرم مخزناً للغذاء بعد اكتمال الجنين.

## 🔢 القوانين / الصيغ / القواعد

### قاعدة أصل البذرة

البويضة (Ovule) ⟶ البذرة (Seed).

### قاعدة أصل غلاف البذرة

أغلفة البويضة (Integuments) ⟶ التستا (Testa) ⟶ غلاف البذرة (Seed Coat).

### قاعدة ذوات الفلقتين

جنين ناضج + فلقتان + إندوسبيرم قليل أو مختفٍ بسبب استهلاكه.

### قاعدة ذوات الفلقة الواحدة

جنين + فلقة واحدة + إندوسبيرم باقٍ لتخزين الغذاء.

### قاعدة استعمال الإندوسبيرم

- ذوات الفلقتين: يستهلك الجنين الإندوسبيرم خلال تكوينه.
- ذوات الفلقة الواحدة: يبدأ الجنين استعمال الإندوسبيرم بعد زراعة البذرة وبدء امتصاص الماء.

## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تحديد أصل البذرة

**السؤال:** ما أصل البذرة؟

**الإجابة:** أصل البذرة هو البويضة (Ovule)؛ إذ تتحول البويضة بعد الإخصاب وتكوين الجنين إلى بذرة.

### مثال 2: تحديد أصل غلاف البذرة

**السؤال:** ما أصل غلاف البذرة والتستا؟

**الإجابة:** أصل غلاف البذرة هو أغلفة البويضة (Ovule Integuments)، وتسمى الطبقة الناتجة التستا (Testa).

### مثال 3: تمييز بذرة الفاصوليا

**المعطيات:** بذرة تحتوي على جنين وفلقتين، ولا يظهر فيها الإندوسبيرم بوضوح.

**التحليل:** وجود فلقتين يدل على أنها من ذوات الفلقتين، واختفاء الإندوسبيرم يعني أن الجنين استهلك الغذاء المخزون فيه.

**الناتج النهائي:** بذرة ذات فلقتين (Dicotyledonous Seed)، مثل الفاصوليا.

### مثال 4: تمييز بذرة الحنطة أو الذرة

**المعطيات:** بذرة تحتوي على جنين وفلقة واحدة وإندوسبيرم واضح.

**التحليل:** وجود فلقة واحدة يدل على ذوات الفلقة الواحدة، وبقاء الإندوسبيرم يعني أن الجنين لم يستهلكه خلال تكوين البذرة.

**الناتج النهائي:** بذرة ذات فلقة واحدة (Monocotyledonous Seed)، مثل الحنطة أو الذرة.

### مثال 5: سبب بقاء الإندوسبيرم في ذوات الفلقة الواحدة

**السؤال:** لماذا يبقى الإندوسبيرم في بذور الحنطة والذرة والأرز؟

**الإجابة:** لأن الجنين لا يستهلك الإندوسبيرم بالكامل خلال تكوّن البذرة، فيبقى مخزناً للغذاء ويبدأ الجنين باستعماله بعد زراعة البذرة وبدء امتصاص الماء.

## ⚠️ تنبيهات وأخطاء شائعة (ملاحظات وزارية)

- **مهم جداً:** بعد اكتمال الجنين الناضج تتحول البويضة إلى بذرة، ولا تبقى تسمى بويضة.
- **مهم:** أصل البذرة هو البويضة (Ovule)، وليس المبيض (Ovary).
- أصل غلاف البذرة هو أغلفة البويضة، وتسمى الطبقة الناتجة التستا (Testa).
- لا تخلط بين التستا (Testa) والإندوسبيرم (Endosperm): التستا غلاف، والإندوسبيرم نسيج خازن للغذاء.
- تحتوي بذور ذوات الفلقتين على فلقتين، بينما تحتوي بذور ذوات الفلقة الواحدة على فلقة واحدة.
- في بذور ذوات الفلقتين قد يختفي الإندوسبيرم لأن الجنين استهلكه خلال نموه.
- في بذور ذوات الفلقة الواحدة يبقى الإندوسبيرم؛ لأن الجنين يبدأ باستعماله بعد زراعة البذرة وبدء امتصاص الماء.
- **مهم وزارياً:** أمثلة ذوات الفلقتين: الفاصوليا/الفول. أمثلة ذوات الفلقة الواحدة: الحنطة والذرة والأرز.
- لا تكتب أن بذور ذوات الفلقة الواحدة لا تحتوي على جنين؛ فهي تحتوي على جنين وفلقة واحدة وإندوسبيرم.
- احفظ أصل كل تركيب:
  - البويضة ⟶ البذرة.
  - أغلفة البويضة ⟶ التستا/غلاف البذرة.
  - اللاقحة ⟶ الجنين.
  - الاتحاد الثاني ⟶ الإندوسبيرم.
- وفق تأكيد المدرس، تكون الإجابة النموذجية من نص المنهج، لذلك يجب الالتزام بالمصطلحات والأمثلة المذكورة.

## 🧠 الخلاصة

- تتحول البويضة بعد اكتمال الجنين إلى بذرة.
- تتحول أغلفة البويضة إلى التستا، أي غلاف البذرة.
