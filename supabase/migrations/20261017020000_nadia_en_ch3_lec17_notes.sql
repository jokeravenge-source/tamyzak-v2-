# المحاضرة السابعة عشرة – التلقيح وتكوين أنبوب اللقاح (Pollination and Pollen Tube Formation)

## 🧭 نظرة عامة سريعة

تشرح المحاضرة عملية التلقيح (Pollination)، أي انتقال حبة اللقاح (Pollen Grain) من المتك (Anther) إلى الميسم (Stigma)، وتوضح نوعي التلقيح: التلقيح الذاتي (Self-pollination) والتلقيح الخلطي (Cross-pollination). ثم تشرح ما يحدث بعد سقوط حبة اللقاح على الميسم، وكيف تنبت حبة اللقاح من مناطق رقيقة في جدارها، وتكوّن أنبوب اللقاح (Pollen Tube) الذي يخترق الميسم والقلم والمبيض حتى يصل إلى البويضة (Ovule). كما توضح انقسام النواة التوليدية إلى مشيجين ذكريين.

## 📚 المفاهيم والشرح التفصيلي

### 1. تذكير بالمتك وحبة اللقاح

- وظيفة السداة (Stamen) هي إنتاج حبوب اللقاح (Pollen Grains).
- تنشأ حبوب اللقاح من الخلية الأم للبوغة الدقيقة (Microspore Mother Cell) الموجودة داخل الأكياس البوغية الدقيقة (Microsporangia) في المتك.
- تكون حبة اللقاح داخل المتك غير ناضجة في البداية.
- عند اكتمال تكوّنها وانطلاقها من المتك إلى البيئة، تصبح حبة اللقاح ناضجة وتمثل المشيجي الذكري الناضج (Mature Male Gametophyte).
- تحتوي حبة اللقاح الناضجة على:
  - الخلية الأنبوبية/النواة الأنبوبية (Tube Cell/Tube Nucleus).
  - الخلية التوليدية/النواة التوليدية (Generative Cell/Generative Nucleus)، التي ستكوّن مشيجين ذكريين.

### 2. تذكير بالمدقة والمبيض والبويضة

- المدقة (Pistil) هي الجزء الأنثوي من الزهرة، وتتكون من الميسم (Stigma) والقلم (Style) والمبيض (Ovary).
- المبيض مسؤول عن تكوين البويضات (Ovules).
- البويضة تمثل الكيس البوغي الكبير (Megasporangium)، وتحتوي على الكيس الجنيني (Embryo Sac).
- بعد اكتمال تكوين الكيس الجنيني، يصبح المشيجي الأنثوي الناضج (Mature Female Gametophyte)، لاحتوائه على البيضة (Egg Cell) والخلايا المساعدة والنواتين القطبيتين.

### 3. تعريف التلقيح

التلقيح (Pollination) هو انتقال حبة اللقاح من المتك (Anther) في زهرة إلى الميسم (Stigma) في زهرة.

وقد يكون الانتقال:

- من المتك إلى الميسم في الزهرة نفسها.
- من المتك في زهرة إلى الميسم في زهرة أخرى من النبات نفسه.
- من المتك في نبات إلى الميسم في نبات آخر من النوع نفسه.

### 4. التلقيح الذاتي (Self-pollination)

- يحدث التلقيح الذاتي عندما تنتقل حبة اللقاح من متك الزهرة إلى ميسم الزهرة نفسها.
- الزهرة التي تحتوي على المتك والمدقة معاً تسمى زهرة كاملة/ثنائية الجنس (Perfect Flower)، بحسب ما ورد في الشرح.
- لا تخرج حبة اللقاح من الزهرة؛ إذ تنتقل من المتك إلى الميسم داخل الزهرة نفسها.
- من أمثلة النباتات التي ذُكرت للتلقيح الذاتي:
  - الحنطة/القمح (Wheat).
  - الشعير (Barley).
  - الفاصوليا (Beans).
  - البازلاء (Peas).
  - البرتقال والحمضيات (Orange and Citrus).

### 5. التلقيح الخلطي (Cross-pollination)

- يحدث التلقيح الخلطي عندما تنتقل حبة اللقاح من متك زهرة إلى ميسم زهرة أخرى.
- قد تكون الزهرتان على النبات نفسه، أو على نباتين مختلفين من النوع نفسه.
- في التلقيح الخلطي لا يشترط أن تكون الزهرتان في المكان نفسه، لكن يشترط أن تكونا من النوع نفسه أو من النوع المتوافق الذي يسمح بالتكاثر.
- مثال المحاضرة: يمكن تلقيح تفاحة أمريكية بتفاحة لبنانية أو عراقية ما دامت من النوع نفسه، وقد ينتج عن ذلك اختلاف في السلالة الجينية (Genetic Strain) مع بقاء النوع نفسه.
- ذُكرت أشجار النخيل (Date Palms) مثالاً على التلقيح الخلطي، إذ يمكن نقل حبوب اللقاح إلى الأزهار الأنثوية.

### 6. قانون التلقيح والتكاثر

- حتى إذا اختلفت السلالات أو الأصناف، يجب أن يكون التكاثر بين أفراد من النوع نفسه أو النوع المتوافق.
- لا يمكن اعتبار التفاح والبرتقال مثالاً صحيحاً للتكاثر المنتج؛ لأنهما مختلفان في النوع.
- أما التفاح الأمريكي والتفاح اللبناني أو العراقي، فيمكن أن يختلف الصنف أو السلالة، لكن يبقى النوع واحداً.
- هذا القانون مرتبط بقانون الحياة والتكاثر: يجب أن يحدث التزاوج بين كائنات من النوع نفسه أو أنواع متوافقة حتى ينتج نسل أو محصول.

### 7. أهمية التلقيح الخلطي

ذكرت المحاضرة أن التلقيح الخلطي مهم لأنه يؤدي إلى:

- تحسين نوعية الثمار (Fruit Quality).
- زيادة كمية المحصول (Quantity of Crop).
- زيادة عدد المنتجات أو الثمار الناتجة.
- إنتاج صفات أو سلالات جينية مختلفة.

### 8. دور النحل في التلقيح الخلطي

- يعد النحل (Bees) من أهم الوسائل التي تساعد على التلقيح الخلطي.
- توضع خلايا النحل (Beehives) قرب الحقول أو داخلها.
- ينتقل النحل بين الأزهار، فتلتصق حبوب اللقاح بجسمه ثم ينقلها إلى مياسم أزهار أخرى.
- يساعد ذلك على رفع نسبة حدوث التلقيح، وقد يصل إلى نسبة عالية جداً بحسب ما أكد المدرس.
- لذلك يعد النحل مهماً من الناحية الزراعية والاقتصادية (Agricultural and Economic Importance).

### 9. ما يحدث بعد سقوط حبة اللقاح على الميسم

بعد وصول حبة اللقاح إلى الميسم:

1. تبدأ حبة اللقاح بالإنبات (Germination).
2. تنبت من مناطق رقيقة في جدار حبة اللقاح تسمى مناطق الإنبات (Germination Regions/Germ Pores).
3. يتكون أنبوب ضيق القطر يسمى أنبوب اللقاح (Pollen Tube).
4. يبدأ أنبوب اللقاح بالنمو باتجاه أسفل الميسم.
5. يخترق الميسم، ثم القلم، ثم يصل إلى المبيض.
6. يستمر بالنمو حتى يصل إلى البويضة.
7. يدخل إلى البويضة عبر النقير (Micropyle).

### 10. انقسام النواة التوليدية

- تحتوي حبة اللقاح الناضجة على النواة التوليدية (Generative Nucleus) والنواة الأنبوبية (Tube Nucleus).
- أثناء نمو أنبوب اللقاح، تدخل النواة التوليدية في انقسام خيطي (Mitosis).
- تنتج من هذا الانقسام خليتان/مشيجان ذكريان (Two Male Gametes).
- يتحرك المشيجان الذكريان داخل أنبوب اللقاح باتجاه البويضة.
- عند وصول أنبوب اللقاح إلى البويضة يكون قد حمل داخله النواة الأنبوبية والمشيجين الذكريين.

### 11. اكتمال نضج المشيجي الذكري

- عندما تكون حبة اللقاح داخل المتك وتحتوي على نواة توليدية واحدة، تكون غير ناضجة.
- عندما تخرج من المتك ويكتمل انقسام النواة التوليدية إلى مشيجين ذكريين، تكون ممثلة للمشيجي الذكري الناضج.
- لذلك فإن وجود النواة الأنبوبية والمشيجين الذكريين يدل على النضج.

### 12. مسار أنبوب اللقاح

يسلك أنبوب اللقاح المسار الآتي:

**الميسم (Stigma) ⟶ القلم (Style) ⟶ المبيض (Ovary) ⟶ البويضة (Ovule) ⟶ النقير (Micropyle).**

وعند الوصول إلى البويضة، يكون أنبوب اللقاح قد اخترق الميسم والقلم والمبيض ووصل إلى الكيس الجنيني (Embryo Sac)، تمهيداً لعملية الإخصاب (Fertilization).

## 📖 التعريفات والمصطلحات

- **التلقيح (Pollination):** انتقال حبة اللقاح من المتك إلى الميسم.
- **التلقيح الذاتي (Self-pollination):** انتقال حبة اللقاح من متك الزهرة إلى ميسم الزهرة نفسها.
- **التلقيح الخلطي (Cross-pollination):** انتقال حبة اللقاح من متك زهرة إلى ميسم زهرة أخرى من النوع نفسه أو النوع المتوافق.
- **المتك (Anther):** الجزء من السداة الذي تتكون داخله حبوب اللقاح.
- **الميسم (Stigma):** الجزء العلوي من المدقة الذي تستقبل عليه الزهرة حبوب اللقاح.
- **القلم (Style):** الجزء الذي يصل الميسم بالمبيض، وينمو خلاله أنبوب اللقاح.
- **المبيض (Ovary):** الجزء السفلي من المدقة، ويحتوي على البويضات.
- **البويضة (Ovule):** تركيب داخل المبيض يحتوي على الكيس الجنيني.
- **حبة اللقاح (Pollen Grain):** بنية ناتجة من الأبواغ الدقيقة، وتحمل الخلية الأنبوبية والنواة التوليدية أو المشيجين الذكريين بعد النضج.
- **أنبوب اللقاح (Pollen Tube):** أنبوب ضيق القطر ينمو من حبة اللقاح عبر الميسم والقلم والمبيض حتى يصل إلى البويضة.
- **مناطق الإنبات (Germination Regions/Germ Pores):** مناطق رقيقة في جدار حبة اللقاح يخرج منها أنبوب اللقاح.
- **النواة الأنبوبية (Tube Nucleus):** النواة المرتبطة بنمو أنبوب اللقاح.
- **النواة التوليدية (Generative Nucleus):** النواة التي تنقسم خيطياً لتكوّن مشيجين ذكريين.
- **المشيج الذكري (Male Gamete):** إحدى الخليتين الناتجتين من انقسام النواة التوليدية.
- **الزهرة الكاملة (Perfect Flower):** زهرة تحتوي على السداة والمدقة معاً.
- **الإخصاب (Fertilization):** العملية التي تلي وصول المشيج الذكري إلى البيضة وتؤدي إلى تكوين اللاقحة (Zygote).

