## 🧪 المسائل والأمثلة المحلولة

### مثال 1: تحديد نوع التلقيح

**المعطيات:** انتقلت حبة اللقاح من متك الزهرة إلى ميسم الزهرة نفسها.

**القاعدة:** انتقال حبة اللقاح داخل الزهرة نفسها يسمى تلقيحاً ذاتياً.

**الناتج النهائي:** التلقيح ذاتي (Self-pollination).

### مثال 2: تحديد نوع التلقيح بين نباتين

**المعطيات:** انتقلت حبة اللقاح من زهرة إلى زهرة أخرى من النوع نفسه، مثل انتقال حبوب اللقاح بين أصناف التفاح.

**القاعدة:** انتقال حبة اللقاح إلى زهرة أخرى من النوع نفسه يسمى تلقيحاً خلطياً.

**الناتج النهائي:** التلقيح خلطي (Cross-pollination)، وقد يؤدي إلى اختلاف السلالة الجينية مع بقاء النوع نفسه.

### مثال 3: تحديد مسار أنبوب اللقاح

**المعطيات:** سقطت حبة لقاح ناضجة على الميسم.

**خطوات الحل:**

1. تنبت حبة اللقاح من منطقة إنبات رقيقة.
2. يتكون أنبوب اللقاح.
3. ينمو الأنبوب خلال الميسم.
4. ينتقل خلال القلم.
5. يخترق المبيض.
6. يصل إلى البويضة ويدخل من النقير.

**الناتج النهائي:** يصل أنبوب اللقاح إلى الكيس الجنيني حاملاً المشيجين الذكريين.

### مثال 4: سبب أهمية التلقيح الخلطي

**السؤال:** لماذا يعد التلقيح الخلطي مهماً؟

**الإجابة:** لأنه يحسن نوعية الثمار، ويزيد كمية المحصول وعدد المنتجات، وقد يؤدي إلى ظهور سلالات جينية مختلفة.

### مثال 5: أهمية وضع خلايا النحل قرب الحقول

**السؤال:** لماذا توضع خلايا النحل قرب الحقول؟

**الإجابة:** لأن النحل ينقل حبوب اللقاح بين الأزهار، فيساعد على حدوث التلقيح الخلطي بنسبة عالية، ويزيد كمية المحصول.

## ⚠️ تنبيهات وأخطاء شائعة (ملاحظات وزارية)

- **مهم جداً:** التلقيح (Pollination) هو انتقال حبة اللقاح، أما الإخصاب (Fertilization) فهو العملية التي تلي وصولها وتؤدي إلى تكوين اللاقحة.
- لا تخلط بين المتك (Anther) الذي يطلق حبوب اللقاح والميسم (Stigma) الذي يستقبلها.
- التلقيح الذاتي لا يعني انتقال حبة اللقاح إلى زهرة أخرى؛ بل يحدث داخل الزهرة نفسها.
- التلقيح الخلطي قد يحدث بين زهرتين على النبات نفسه أو بين نباتين من النوع نفسه.
- **مهم وزارياً:** يجب أن يكون التلقيح الخلطي بين أفراد من النوع نفسه أو الأنواع المتوافقة، وليس بين التفاح والبرتقال.
- يمكن أن يختلف الصنف أو السلالة، مثل التفاح الأمريكي واللبناني والعراقي، مع بقاء النوع واحداً.
- **مهم:** النحل من أهم عوامل التلقيح الخلطي، ولذلك توضع خلاياه قرب الحقول.
- حبة اللقاح داخل المتك تكون غير ناضجة، وتصبح ناضجة بعد اكتمال تكوين المشيجين الذكريين.
- يبدأ أنبوب اللقاح من مناطق رقيقة في جدار حبة اللقاح تسمى مناطق الإنبات.
- **مهم جداً:** النواة التوليدية تدخل الانقسام الخيطي، ولا تنقسم النواة الأنبوبية لتكوين المشيجين.
- ينتج من انقسام النواة التوليدية مشيجان ذكريان.
- احفظ مسار أنبوب اللقاح بالترتيب: الميسم ⟶ القلم ⟶ المبيض ⟶ البويضة ⟶ النقير.
- عند وصول أنبوب اللقاح إلى البويضة يكون قد اخترق الميسم والقلم والمبيض.
- السؤال الوزاري المهم: اشرح تكوين أنبوب اللقاح؛ وتبدأ الإجابة بسقوط حبة اللقاح على الميسم ثم إنباتها وتكوين الأنبوب ونموه حتى البويضة.

